# ---------------------------------------------------------------------------
# Валидация входа
# ---------------------------------------------------------------------------

def validirovat(d):
    """Блокирующие ошибки структуры входа. Незаполненные ответы — не ошибка
    (попадают в перечень незаполненных кандидата)."""
    osh = []
    if not isinstance(d, dict):
        return ["вход должен быть JSON-объектом"]
    кандидаты = d.get("кандидаты")
    if not isinstance(кандидаты, list) or not кандидаты:
        osh.append("раздел «кандидаты» должен быть непустым списком "
                   "(1–3 кандидатных потока)")
        return osh
    if len(кандидаты) > МАКС_КАНДИДАТОВ:
        osh.append(f"кандидатов {len(кандидаты)} больше потолка "
                   f"{МАКС_КАНДИДАТОВ} — сравниваются 1–3 потока")
    for i, к in enumerate(кандидаты, 1):
        if not isinstance(к, dict):
            osh.append(f"кандидаты[{i}] должен быть объектом")
            continue
        if not (к.get("название") or "").strip():
            osh.append(f"кандидаты[{i}]: укажите «название» потока")
        for раздел, справ in (("критерии", _КРИТЕРИИ), ("признаки", _ПРИЗНАКИ)):
            бл = к.get(раздел)
            if бл is None:
                continue
            if not isinstance(бл, dict):
                osh.append(f"кандидаты[{i}].{раздел} должен быть объектом")
                continue
            for ключ, v in бл.items():
                if ключ not in справ:
                    osh.append(f"кандидаты[{i}].{раздел}: неизвестный ключ "
                               f"«{ключ}»")
                elif not isinstance(v, bool):
                    osh.append(f"кандидаты[{i}].{раздел}.{ключ} должен быть "
                               "булевым (да/нет)")
    return osh


