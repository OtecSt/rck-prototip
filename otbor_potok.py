def _кандидат(к, позиция):
    """Скоринг одного кандидата: баллы критериев, признаков, итог, статус."""
    критерии = к.get("критерии") or {}
    признаки = к.get("признаки") or {}
    б_крит, незап_крит, провал_обяз = 0, [], []
    for ключ, название, обяз in КРИТЕРИИ:
        v = критерии.get(ключ)
        if v is None:
            незап_крит.append(ключ)
        elif v:
            б_крит += 1
        elif обяз:
            провал_обяз.append(ключ)
    отмеченные = [ключ for ключ in _ПРИЗНАКИ if признаки.get(ключ) is True]
    незап_призн = [ключ for ключ in _ПРИЗНАКИ if признаки.get(ключ) is None]
    б_призн = len(отмеченные)
    дисквал = bool(провал_обяз)
    return {"название": (к.get("название") or "").strip(),
            "позиция": позиция,
            "баллы_критерии": б_крит, "макс_критерии": МАКС_КРИТЕРИИ,
            "баллы_признаки": б_призн, "макс_признаки": МАКС_ПРИЗНАКИ,
            "итог": б_крит + б_призн, "максимум": МАКСИМУМ,
            "отмеченные_признаки": отмеченные,
            "незаполненные_критерии": незап_крит,
            "незаполненные_признаки": незап_призн,
            "проваленные_обязательные": провал_обяз,
            "дисквалифицирован": дисквал,
            "рекомендован": False}


def raschet(d):
    """Полный расчёт выбора пилотного потока (ошибки — через validirovat)."""
    кандидаты = [_кандидат(к, i) for i, к in enumerate(d.get("кандидаты"), 1)]
    допуск = [к for к in кандидаты if not к["дисквалифицирован"]]
    рекомендованный = None
    if допуск:
        рекомендованный = max(
            допуск, key=lambda к: (к["итог"], к["баллы_критерии"],
                                   -к["позиция"]))
        рекомендованный["рекомендован"] = True
    # Обоснование рекомендации
    if рекомендованный is None:
        вердикт = "ни один кандидат не рекомендован"
        обоснование = ("Все кандидаты не прошли обязательный критерий «доля "
                       "потока в выручке не менее 10 %» (п. 5.1 чек-листа "
                       "очного отбора): пилотный проект в таком потоке не "
                       "даст значимого вклада в показатели предприятия. "
                       "Пересмотрите периметр кандидатов.")
    else:
        р = рекомендованный
        вердикт = f"рекомендован пилотный поток: {р['название']}"
        конкуренты = [к for к in допуск if к is not р]
        части = [f"итог {р['итог']} из {р['максимум']} (критерии потока — "
                 f"{р['баллы_критерии']} из {р['макс_критерии']}, признаки "
                 f"потерь — {р['баллы_признаки']} из {р['макс_признаки']})"]
        if конкуренты:
            ближ = max(конкуренты,
                       key=lambda к: (к["итог"], к["баллы_критерии"]))
            разрыв = р["итог"] - ближ["итог"]
            слово = ("балл" if разрыв % 10 == 1 and разрыв % 100 != 11
                     else ("балла" if разрыв % 10 in (2, 3, 4)
                           and разрыв % 100 not in (12, 13, 14) else "баллов"))
            части.append(f"ближайший кандидат «{ближ['название']}» — "
                         f"{ближ['итог']} из {ближ['максимум']} "
                         f"(разрыв {разрыв} {слово})")
            if р["итог"] == ближ["итог"]:
                части.append("при равенстве итогов выбор сделан по баллам "
                             "критериев потока, затем по порядку ввода")
        диск = [к for к in кандидаты if к["дисквалифицирован"]]
        if диск:
            части.append("не рекомендованы: " + "; ".join(
                f"«{к['название']}» (доля в выручке менее 10 % — обязательный "
                "критерий не выполнен)" for к in диск))
        if р["незаполненные_критерии"] or р["незаполненные_признаки"]:
            части.append("оценка неполная: есть незаполненные ответы — "
                         "до обхода потока (Прил. № 3, шаг 3) закройте "
                         "пробелы")
        обоснование = ". ".join(ч[0].upper() + ч[1:] for ч in части) + "."
    res = {"предприятие": (d.get("предприятие") or "").strip() or None,
           "кандидаты": кандидаты,
           "кандидатов": len(кандидаты),
           "допущено": len(допуск),
           "рекомендованный": (рекомендованный["название"]
                               if рекомендованный else None),
           "вердикт": вердикт,
           "обоснование": обоснование}
    res["скоринг_карта_md"] = скоринг_карта(d, res)
    return res


# ---------------------------------------------------------------------------
# Скоринг-карта (итоговый markdown)
# ---------------------------------------------------------------------------

def скоринг_карта(d, r):
    """Итоговый отчёт md: предприятие, дата, кандидаты с баллами,
    рекомендация с обоснованием."""
    L = ["# Скоринг-карта выбора пилотного потока",
         "МР-15-2026, редакция № 5 от 28.07.2026 · критерии разделов 5–6 "
         "чек-листов очного отбора (Приложения № 4 / № 5)", ""]
    L.append(f"- Предприятие: {r['предприятие'] or '___'}")
    L.append(f"- Дата оценки: {datetime.now().strftime('%d.%m.%Y')}")
    L.append("")
    for к in r["кандидаты"]:
        статус = ("РЕКОМЕНДОВАН" if к["рекомендован"]
                  else ("не рекомендован — обязательный критерий не выполнен"
                        if к["дисквалифицирован"] else "не рекомендован"))
        L.append(f"## Кандидат: {к['название']} — {статус}")
        L.append("")
        вход = next((x for x in d.get("кандидаты", [])
                     if (x.get("название") or "").strip() == к["название"]), {})
        критерии = вход.get("критерии") or {}
        признаки = вход.get("признаки") or {}
        L.append(f"### Критерии потока — {к['баллы_критерии']} из "
                 f"{к['макс_критерии']}")
        for ключ, название, обяз in КРИТЕРИИ:
            v = критерии.get(ключ)
            отметка = "V" if v is True else ("─" if v is False else "?")
            зв = " *" if обяз else ""
            L.append(f"- {название} — **{отметка}**{зв}")
        L.append("")
        L.append(f"### Карта признаков потерь — отмечено "
                 f"{к['баллы_признаки']} из {к['макс_признаки']}")
        for ключ, название in ПРИЗНАКИ_ПОТЕРЬ:
            v = признаки.get(ключ)
            отметка = "V" if v is True else ("─" if v is False else "?")
            L.append(f"- {название} — **{отметка}**")
        L.append("")
        L.append(f"**Итог кандидата: {к['итог']} из {к['максимум']}** "
                 f"(критерии {к['баллы_критерии']} + признаки "
                 f"{к['баллы_признаки']}).")
        незап = (к["незаполненные_критерии"] or к["незаполненные_признаки"])
        if незап:
            L.append("")
            L.append(f"> Внимание: по кандидату есть незаполненные ответы "
                     f"(критерии: {len(к['незаполненные_критерии'])}, "
                     f"признаки: {len(к['незаполненные_признаки'])}) — "
                     "итог занижен.")
        L.append("")
    L.append("## Рекомендация")
    L.append("")
    L.append(f"**{r['вердикт'].upper()}.**")
    L.append("")
    L.append(r["обоснование"])
    L.append("")
    L.append("> \\* — обязательный критерий: при ответе «нет» кандидат не "
             "рекомендуется (п. 5.1 чек-листов очного отбора). Выбор потока "
             "по МР подтверждается обходом пилотного потока в ходе очного "
             "отбора (Приложение № 3, шаг 3): «подтвердили или не "
             "подтвердили выбор пилотного потока».")
    return "\n".join(L)


# ---------------------------------------------------------------------------
# CLI (регрессия)
# ---------------------------------------------------------------------------

def _main(argv):
    if len(argv) < 2:
        print("использование: python3 otbor_potok.py вход.json [--json]",
              file=sys.stderr)
        return 2
    with open(argv[1], encoding="utf-8") as f:
        d = json.load(f)
    osh = validirovat(d)
    if osh:
        print("ОШИБКИ ВХОДА:", file=sys.stderr)
        for o in osh:
            print(" - " + o, file=sys.stderr)
        return 1
    r = raschet(d)
    if "--json" in argv[2:]:
        print(json.dumps(r, ensure_ascii=False, indent=2))
    else:
        print(r["скоринг_карта_md"])
    return 0


if __name__ == "__main__":
    sys.exit(_main(sys.argv))
