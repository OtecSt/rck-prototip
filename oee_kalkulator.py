#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Инструмент «OEE-калькулятор» — v1.0 (чистый Python, без LLM).
Один экран: плановое время, простои по категориям, идеальное время цикла,
выпуск и брак → доступность (A), производительность (P), качество (Q),
OEE, разложение шести больших потерь, сравнение с мировым классом,
узкая составляющая и потенциал при устранении топ-потери.

Формулы и источники (архив методичек, распарсенные тексты ИНДЕКС/тексты/):
- OEE = A × P × Q — МР «Анализ эффективности оборудования», ред. № 2, п. 4.1
  (показатель № 1: «ОЕЕ … определяемый как произведение трёх факторов:
  Доступность (А), Производительность (Р), Качество (Q)»).
- Доступность A = OT / PPT = оперативное время / планируемое
  производственное время. Источник: «OEE_Калькулятор_ПримерРасчёта_Дискр.пр.
  _03.03.21.xlsx» (лист «Образец OEE»: «Доступность (Availability)
  A = OT / PPT …»); МР «Анализ эффективности оборудования», Приложение № 5.
- Производительность P = ICT / (OT / TP) = идеальное время цикла × факт
  выпуск / оперативное время. Источник: тот же лист «Образец OEE»
  («Производительность (Performance) … P = ICT / (OT/TP) …»).
- Качество Q = GP / TP = годные / фактический выпуск. Источник: там же
  («Качество (Quality) Q = GP / TP …»).
- Шесть больших потерь — МР «Анализ эффективности оборудования», таблица № 1:
  Доступность — планируемое время простоя, поломки;
  Производительность — короткие остановки, потеря скорости;
  Качество — производственный брак, брак при запуске.
- Целевой уровень (мировой класс) OEE ≥ 85 % — там же, раздел про ОЕЕ:
  «целевой уровень ОЕЕ ≥ 85 % – сейчас уже не редкость».

ДОПУЩЕНИЯ (чего нет в источниках явно):
- Категории простоев входа (аварии, переналадка, микроостановки, прочее)
  отображены на шесть больших потерь так: аварии → «поломки»,
  переналадка → «планируемое время простоя» (в таблице № 1 переналадка
  входит в плановые остановки, см. определение «Плановые остановки»),
  микроостановки → «короткие остановки», прочее → строка вне шести
  категорий. Все четыре категории уменьшают оперативное время (учитываются
  во времени), но в таблице потерь микроостановки отнесены к фактору
  «Производительность» по таблице № 1.
- Потеря скорости = оперативное время − факт выпуск × идеальное Тц
  (остаточный член: всё время, не ушедшее на выпуск и не объявленное
  простоями, — это работа медленнее паспортной скорости).
- Потери качества переведены в минуты через идеальное Тц (брак, шт × Тц).
- Потенциал OEE при устранении топ-потери: устранённые минуты становятся
  оперативным временем и дают выпуск с текущими P и Q (сами P и Q не
  меняются): OEE′ = A′ × P × Q, A′ = (OT + топ_потеря) / PPT.

Запуск: python3 oee_kalkulator.py данные.json
"""

import json
import math
import sys
from datetime import date

ИСТОЧНИК_OEE = ("МР «Анализ эффективности оборудования», ред. № 2, п. 4.1; "
                "OEE_Калькулятор_ПримерРасчёта_Дискр.пр._03.03.21.xlsx, "
                "лист «Образец OEE»")
ИСТОЧНИК_ПОТЕРИ = ("МР «Анализ эффективности оборудования», ред. № 2, "
                  "таблица № 1 (шесть больших потерь); Приложение № 5 "
                  "(пример расчёта ОЕЕ и 6 больших потерь)")
ИСТОЧНИК_КЛАСС = ("МР «Анализ эффективности оборудования», ред. № 2: "
                  "«целевой уровень ОЕЕ ≥ 85 % – сейчас уже не редкость»")

МИРОВОЙ_КЛАСС = 0.85

# Шесть больших потерь (таблица № 1 МР): (ключ, название, фактор OEE)
КАТЕГОРИИ_ПОТЕРЬ = [
    ("аварии", "Аварии и поломки", "доступность"),
    ("переналадка", "Переналадка и настройка (планируемые простои)", "доступность"),
    ("микроостановки", "Короткие остановки и холостой ход", "производительность"),
    ("скорость", "Снижение скорости", "производительность"),
    ("брак", "Производственный брак и переделки", "качество"),
    ("запуск", "Брак при запуске (потери запуска)", "качество"),
]

НАЗВАНИЯ_ФАКТОРОВ = {"A": "Доступность (A)", "P": "Производительность (P)",
                    "Q": "Качество (Q)"}


def fmt(x, nd=1):
    if nd == 1 and x and abs(x) < 0.1:
        nd = 2
    return f"{x:.{nd}f}".replace(".", ",")


def _число(v):
    return (isinstance(v, (int, float)) and not isinstance(v, bool)
            and math.isfinite(v))


def validirovat(d):
    """Валидация входа. Обязательные: плановое_время_мин > 0,
    идеальное_тц_мин > 0, выпуск_всего_шт > 0; выпуск должен укладываться
    в оперативное время (плановое − простои). Остальное — «нет данных»."""
    oshibki = []
    пв = d.get("плановое_время_мин")
    if not _число(пв) or пв <= 0:
        oshibki.append("поле «плановое_время_мин» обязательно: число > 0")
    тц = d.get("идеальное_тц_мин")
    if not _число(тц) or тц <= 0:
        oshibki.append("поле «идеальное_тц_мин» обязательно: число > 0")
    выпуск = d.get("выпуск_всего_шт")
    if not _число(выпуск) or выпуск <= 0:
        oshibki.append("поле «выпуск_всего_шт» обязательно: число > 0")
    простои = d.get("простои") or {}
    if not isinstance(простои, dict):
        oshibki.append("поле «простои»: объект с категориями "
                       "(аварии_мин, переналадка_мин, микроостановки_мин, "
                       "прочее_мин) либо не заполнять")
        простои = {}
    for k in ("аварии_мин", "переналадка_мин", "микроостановки_мин", "прочее_мин"):
        v = простои.get(k)
        if v is not None and (not _число(v) or v < 0):
            oshibki.append(f"простои «{k}»: число ≥ 0")
    брак = d.get("брак_шт")
    if брак is not None and (not _число(брак) or брак < 0):
        oshibki.append("поле «брак_шт»: число ≥ 0")
    запуск = d.get("потери_запуска_шт")
    if запуск is not None and (not _число(запуск) or запуск < 0):
        oshibki.append("поле «потери_запуска_шт»: число ≥ 0")
    if oshibki:
        return oshibki
    if _число(пв) and _число(тц) and _число(выпуск):
        сум_простоев = sum(простои.get(k) or 0 for k in
                           ("аварии_мин", "переналадка_мин",
                            "микроостановки_мин", "прочее_мин"))
        опер = пв - сум_простоев
        if опер <= 0:
            oshibki.append(
                f"простои ({fmt(сум_простоев)} мин) съедают всё плановое "
                f"время ({fmt(пв)} мин) — оперативное время ≤ 0")
        elif выпуск * тц > опер + 1e-9:
            oshibki.append(
                f"выпуск {fmt(выпуск)} шт × идеальное Тц {fmt(тц, 2)} мин = "
                f"{fmt(выпуск * тц)} мин не укладывается в оперативное "
                f"время {fmt(опер)} мин — проверьте данные")
        if _число(брак) and брак > выпуск:
            oshibki.append("брака больше, чем всего выпущено — проверьте данные")
        if _число(запуск) and _число(брак) and брак + запуск > выпуск:
            oshibki.append("брак + потери запуска больше выпуска — проверьте данные")
    return oshibki


def raschet(d):
    """Полный расчёт OEE. Возвращает dict-результат."""
    r = {"расчёты": [], "допущения": [], "домерить": []}
    пв = d["плановое_время_мин"]
    тц = d["идеальное_тц_мин"]
    выпуск = d["выпуск_всего_шт"]
    простои = d.get("простои") or {}
    аварии = простои.get("аварии_мин") or 0
    переналадка = простои.get("переналадка_мин") or 0
    микро = простои.get("микроостановки_мин") or 0
    прочее = простои.get("прочее_мин") or 0
    брак = d.get("брак_шт") or 0
    запуск = d.get("потери_запуска_шт") or 0

    сум_простоев = аварии + переналадка + микро + прочее
    опер = пв - сум_простоев
    r["оперативное_время_мин"] = опер

    # --- Доступность ---
    A = опер / пв
    r["A"] = A
    r["расчёты"].append(
        f"Доступность A = оперативное время / плановое время = "
        f"({fmt(пв)} − {fmt(сум_простоев)}) / {fmt(пв)} = {fmt(опер)} / "
        f"{fmt(пв)} = {fmt(A * 100, 2)} % ({ИСТОЧНИК_OEE})")

    # --- Производительность ---
    P = выпуск * тц / опер
    r["P"] = P
    r["расчёты"].append(
        f"Производительность P = идеальное Тц × факт выпуск / оперативное "
        f"время = {fmt(тц, 2)} × {fmt(выпуск)} / {fmt(опер)} = "
        f"{fmt(P * 100, 2)} % ({ИСТОЧНИК_OEE})")

    # --- Качество ---
    годные = выпуск - брак - запуск
    Q = годные / выпуск
    r["Q"] = Q
    r["годные_шт"] = годные
    r["расчёты"].append(
        f"Качество Q = годные / выпуск = ({fmt(выпуск)} − {fmt(брак)}"
        + (f" − {fmt(запуск)}" if запуск else "")
        + f") / {fmt(выпуск)} = {fmt(годные)} / {fmt(выпуск)} = "
        f"{fmt(Q * 100, 2)} % ({ИСТОЧНИК_OEE})")

    # --- OEE ---
    oee = A * P * Q
    r["OEE"] = oee
    r["расчёты"].append(
        f"OEE = A × P × Q = {fmt(A * 100, 2)} % × {fmt(P * 100, 2)} % × "
        f"{fmt(Q * 100, 2)} % = {fmt(oee * 100, 2)} % ({ИСТОЧНИК_OEE})")

    # --- Шесть больших потерь (мин и % планового времени) ---
    скорость_мин = опер - выпуск * тц
    r["допущения"].append(
        f"Снижение скорости = оперативное время − выпуск × идеальное Тц = "
        f"{fmt(опер)} − {fmt(выпуск * тц)} = {fmt(скорость_мин)} мин "
        "(остаточный член: явной формулы разложения в источниках нет — "
        "всё незанятое выпуском и не объявленное простоями время считаем "
        "работой медленнее паспортной скорости)")
    r["допущения"].append(
        "Потери качества переведены в минуты через идеальное Тц "
        f"(брак {fmt(брак)} шт × {fmt(тц, 2)} мин"
        + (f", запуск {fmt(запуск)} шт × {fmt(тц, 2)} мин" if запуск else "")
        + "); микроостановки уменьшают оперативное время, но по таблице № 1 "
        "МР отнесены к фактору «Производительность»")
    значения = {"аварии": аварии, "переналадка": переналадка,
                "микроостановки": микро, "скорость": скорость_мин,
                "брак": брак * тц, "запуск": запуск * тц}
    потери = []
    for ключ, название, фактор in КАТЕГОРИИ_ПОТЕРЬ:
        мин = значения[ключ]
        потери.append({"ключ": ключ, "название": название, "фактор": фактор,
                       "мин": мин, "пкт_планового": мин / пв * 100})
    if прочее:
        потери.append({"ключ": "прочее",
                       "название": "Прочие простои (вне шести категорий)",
                       "фактор": "доступность",
                       "мин": прочее, "пкт_планового": прочее / пв * 100})
    r["потери"] = потери
    r["расчёты"].append(
        "Шесть больших потерь (мин и % планового времени): "
        + "; ".join(f"{п['название']} {fmt(п['мин'])} мин "
                    f"({fmt(п['пкт_планового'], 2)} %)" for п in потери)
        + f" ({ИСТОЧНИК_ПОТЕРИ})")

    # --- Мировой класс ---
    r["мировой_класс_пкт"] = МИРОВОЙ_КЛАСС * 100
    r["разрыв_до_класса_пп"] = (МИРОВОЙ_КЛАСС - oee) * 100
    r["расчёты"].append(
        f"Мировой класс OEE ≥ {fmt(МИРОВОЙ_КЛАСС * 100)} %; факт "
        f"{fmt(oee * 100, 2)} % → разрыв {fmt(r['разрыв_до_класса_пп'], 2)} "
        f"п.п. ({ИСТОЧНИК_КЛАСС})")

    # --- Узкая составляющая и потенциал ---
    факторы = {"A": A, "P": P, "Q": Q}
    узкий = min(факторы, key=факторы.get)
    r["узкая_составляющая"] = {"фактор": узкий,
                               "название": НАЗВАНИЯ_ФАКТОРОВ[узкий],
                               "значение": факторы[узкий]}
    топ = max(потери, key=lambda п: п["мин"])
    r["топ_потеря"] = топ
    if топ["мин"] > 0:
        # ДОПУЩЕНИЕ: устранённые минуты топ-потери становятся оперативным
        # временем и дают выпуск с текущими P и Q (P и Q не меняются).
        if топ["фактор"] == "доступность":
            oee_пот = (опер + топ["мин"]) / пв * P * Q
        elif топ["ключ"] == "скорость":
            oee_пот = A * 1.0 * Q
        else:  # качество: минуты брака становятся годным выпуском
            oee_пот = A * P * min(1.0, Q + топ["мин"] / (выпуск * тц))
        r["потенциал_oee"] = oee_пот
        r["потенциал_пп"] = (oee_пот - oee) * 100
        r["допущения"].append(
            f"Потенциал при устранении топ-потери «{топ['название']}» "
            f"({fmt(топ['мин'])} мин): освобождённое время даёт выпуск "
            f"с текущими P и Q → OEE′ = {fmt(oee_пот * 100, 2)} % "
            f"(+{fmt(r['потенциал_пп'], 2)} п.п.)")
    else:
        r["потенциал_oee"] = oee
        r["потенциал_пп"] = 0.0
    if not any(простои.get(k) for k in
               ("аварии_мин", "переналадка_мин", "микроостановки_мин")):
        r["домерить"].append("простои по категориям (хронометраж/фотография "
                             "рабочего дня) → точное разложение потерь")
    return r


def otchyot(d, r):
    """Markdown-отчёт прогона (и для ответа API, и для progony.отчёт_md)."""
    L = [f"# OEE оборудования · {d.get('поток') or 'участок'}",
         f"Дата прогона: {date.today().isoformat()} · инструмент v1.0 "
         "(детерминированный, без ИИ)", ""]
    L.append("## 1. Сводка OEE")
    L.append(f"- Доступность A: **{fmt(r['A'] * 100, 2)} %** (оперативное "
             f"время {fmt(r['оперативное_время_мин'])} мин из плановых "
             f"{fmt(d['плановое_время_мин'])} мин)")
    L.append(f"- Производительность P: **{fmt(r['P'] * 100, 2)} %** "
             f"(выпуск {fmt(d['выпуск_всего_шт'])} шт × идеальное Тц "
             f"{fmt(d['идеальное_тц_мин'], 2)} мин)")
    L.append(f"- Качество Q: **{fmt(r['Q'] * 100, 2)} %** (годные "
             f"{fmt(r['годные_шт'])} шт из {fmt(d['выпуск_всего_шт'])} шт)")
    L.append(f"- **OEE = A × P × Q = {fmt(r['OEE'] * 100, 2)} %**")
    L.append(f"- Мировой класс ≥ {fmt(r['мировой_класс_пкт'])} %: разрыв "
             f"**{fmt(r['разрыв_до_класса_пп'], 2)} п.п.**")
    L.append("")
    L.append("## 2. Шесть больших потерь")
    L.append("| Потеря | Фактор OEE | мин | % планового времени |")
    L.append("|---|---|---|---|")
    for п in r["потери"]:
        L.append(f"| {п['название']} | {п['фактор']} | {fmt(п['мин'])} "
                 f"| {fmt(п['пкт_планового'], 2)} |")
    L.append("")
    уз = r["узкая_составляющая"]
    топ = r["топ_потеря"]
    L.append(f"**Узкая составляющая: {уз['название']}** — "
             f"{fmt(уз['значение'] * 100, 2)} % (минимум из A, P, Q).")
    L.append(f"**Топ-потеря: «{топ['название']}»** — {fmt(топ['мин'])} мин "
             f"({fmt(топ['пкт_планового'], 2)} % планового времени). "
             f"При её устранении OEE → **{fmt(r['потенциал_oee'] * 100, 2)} %** "
             f"(+{fmt(r['потенциал_пп'], 2)} п.п.).")
    L.append("")
    if r["домерить"]:
        L.append("## 3. Каких данных не хватает")
        for x in r["домерить"]:
            L.append(f"- {x}")
        L.append("")
    L.append("## 4. Расчёты и источники")
    for x in r["расчёты"]:
        L.append(f"- {x}")
    L.append("")
    if r["допущения"]:
        L.append("## 5. Допущения (чего нет в источниках явно)")
        for x in r["допущения"]:
            L.append(f"- {x}")
        L.append("")
    L.append("> Только расчёт показателей. Мероприятия не предлагаются.")
    return "\n".join(L)


def itogi(d, r):
    """Компактные итоги для progony.итоги_json."""
    return {"поток": d.get("поток") or "",
            "A": round(r["A"], 6), "P": round(r["P"], 6),
            "Q": round(r["Q"], 6), "OEE": round(r["OEE"], 6),
            "оперативное_время_мин": round(r["оперативное_время_мин"], 2),
            "узкая_составляющая": r["узкая_составляющая"]["название"],
            "узкая_значение": round(r["узкая_составляющая"]["значение"], 6),
            "топ_потеря": r["топ_потеря"]["название"],
            "топ_потеря_мин": round(r["топ_потеря"]["мин"], 2),
            "потенциал_oee": round(r["потенциал_oee"], 6),
            "разрыв_до_класса_пп": round(r["разрыв_до_класса_пп"], 2),
            "домерить": r["домерить"]}


def main():
    if len(sys.argv) != 2:
        sys.exit("Запуск: python3 oee_kalkulator.py <данные.json>")
    with open(sys.argv[1], encoding="utf-8") as f:
        d = json.load(f)
    oshibki = validirovat(d)
    if oshibki:
        sys.exit("Ошибки входа:\n" + "\n".join(f"- {e}" for e in oshibki))
    r = raschet(d)
    print(otchyot(d, r))


