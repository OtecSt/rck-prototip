#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Инструмент «Калькулятор показателей потока» — v1.0 (чистый Python, без LLM).
Один экран: спрос, доступное время, численность, таблица операций
(название + Тц + запас после операции) → все показатели потока сразу.

Формулы и источники (архив методичек, распарсенные тексты ИНДЕКС/тексты/):
- Время такта = доступное время / спрос.
  Источник: МР «Поток единичных изделий», п. 2 (определение Тт);
  «Приложение 2. Схемы и расчеты показателей» (Тдост = 8 ч, 240 дет/день → Ттакт = 2 мин).
- ВПП (время протекания процесса) = Σ Тц операций + Σ (запас после операции × база),
  где база = max(Ттакт, Тц узкого места).
  Источник: «Приложение 2. Схемы и расчеты показателей», стр. 2:
  «Ттакт или Туз.места* (выбираем большее по времени)», «ВПП = Тожид.1 + … + Тожид.4»;
  определение ВПП — МР «Поток единичных изделий», п. 2, Краткий глоссарий (ВПП).
- Время цикла Тц — Краткий глоссарий (Тц).
- Выработка на человека = объём выпуска / численность.
  Источник: Краткий глоссарий («Выработка — объём выполненной за единицу времени
  работы, приходящейся на одного работника»).
- % загрузки операции = Тц / такт × 100.
  Источник: Краткий глоссарий (диаграмма Ямадзуми — загрузка операторов
  в соответствии со временем такта); МР «Поток единичных изделий», п. 6.3
  (загрузка оператора «со временем такта»).
- Число операторов по норме = Σ Тц / такт.
  ДОПУЩЕНИЕ: в источниках явной формулы нет; следует из балансировки
  загрузки под время такта (МР «Поток единичных изделий», пп. 5.2, 6.3).
- Трудоёмкость = Σ Тц на единицу × объём выпуска.
  ДОПУЩЕНИЕ: термин встречается в «Приложении 2» (нормы трудоёмкости),
  но явной формулы в источниках нет — считаем как полное рабочее время на выпуск.
- Потенциал снижения ВПП = Σ (запасы × база) = ВПП − Σ Тц.
  ДОПУЩЕНИЕ: потенциал трактуем как время ожидания в межоперационных запасах
  (полное устранение запасов → ВПП стремится к Σ Тц).

Запуск: python3 pokazateli_potoka.py данные.json
"""

import json
import math
import sys
from datetime import date

ИСТОЧНИК_ТАКТ = ("МР «Поток единичных изделий», п. 2; «Приложение 2. Схемы и расчёты "
                 "показателей»")
ИСТОЧНИК_ВПП = "«Приложение 2. Схемы и расчёты показателей», стр. 2"
ИСТОЧНИК_ВЫРАБОТКА = "Краткий глоссарий терминов по бережливому производству"
ИСТОЧНИК_ЗАГРУЗКА = ("Краткий глоссарий (Ямадзуми); МР «Поток единичных изделий», "
                     "п. 6.3")


def fmt(x, nd=1):
    if nd == 1 and x and abs(x) < 0.1:
        nd = 2
    return f"{x:.{nd}f}".replace(".", ",")


def _число(v):
    return (isinstance(v, (int, float)) and not isinstance(v, bool)
            and math.isfinite(v))


def validirovat(d):
    """Валидация входа. Обязательные: спрос > 0, доступное время > 0,
    хотя бы одна операция с именем и Тц > 0. Остальное — «нет данных»."""
    oshibki = []
    спрос = d.get("спрос_шт_в_период")
    if not _число(спрос) or спрос <= 0:
        oshibki.append("поле «спрос_шт_в_период» обязательно: число > 0")
    время = d.get("доступное_время_мин")
    if not _число(время) or время <= 0:
        oshibki.append("поле «доступное_время_мин» обязательно: число > 0")
    чел = d.get("численность_чел")
    if чел is not None and (not _число(чел) or чел <= 0):
        oshibki.append("поле «численность_чел»: число > 0 либо не заполнять")
    объём = d.get("объём_выпуска_шт")
    if объём is not None and (not _число(объём) or объём <= 0):
        oshibki.append("поле «объём_выпуска_шт»: число > 0 либо не заполнять")
    ops = d.get("операции")
    if not isinstance(ops, list) or not ops:
        oshibki.append("нужна хотя бы одна операция (название + Тц)")
        return oshibki
    рабочих = 0
    for i, op in enumerate(ops, 1):
        имя = (op.get("имя") or "").strip()
        тц = op.get("тц_мин")
        if not имя and тц is None and op.get("запас_после_шт") is None:
            continue  # полностью пустая строка — пропускаем
        if not имя:
            oshibki.append(f"операция № {i}: нет названия")
        if not _число(тц) or тц <= 0:
            oshibki.append(f"операция «{имя or i}»: Тц — число > 0")
        зап = op.get("запас_после_шт")
        if зап is not None and (not _число(зап) or зап < 0):
            oshibki.append(f"операция «{имя or i}»: запас — число ≥ 0")
        if имя and _число(тц) and тц > 0:
            рабочих += 1
    if not рабочих:
        oshibki.append("ни одной рабочей операции: заполните название и Тц > 0")
    return oshibki


def raschet(d):
    """Полный расчёт показателей потока. Возвращает dict-результат."""
    r = {"расчёты": [], "допущения": [], "домерить": []}
    спрос = d["спрос_шт_в_период"]
    время = d["доступное_время_мин"]
    ops = [op for op in d["операции"]
           if (op.get("имя") or "").strip() and _число(op.get("тц_мин"))
           and op["тц_мин"] > 0]

    # --- Время такта ---
    такт = время / спрос
    r["такт_мин"] = такт
    r["расчёты"].append(
        f"Такт = доступное время / спрос = {fmt(время)} / {fmt(спрос)} = "
        f"{fmt(такт, 2)} мин/шт ({ИСТОЧНИК_ТАКТ})")

    # --- Время цикла потока и узкое место ---
    сум_тц = sum(op["тц_мин"] for op in ops)
    r["сум_тц_мин"] = сум_тц
    ум = max(ops, key=lambda op: op["тц_мин"])
    r["узкое_место"] = {"имя": ум["имя"].strip(), "тц_мин": ум["тц_мин"]}
    r["расчёты"].append(
        f"Σ Тц = {fmt(сум_тц, 2)} мин; узкое место — «{ум['имя'].strip()}» "
        f"(max Тц = {fmt(ум['тц_мин'], 2)} мин)")

    # --- База ожидания: max(такт, Тц узкого места) ---
    база = max(такт, ум["тц_мин"])
    r["база_ожидания_мин"] = база
    if база != такт:
        r["расчёты"].append(
            f"База ожидания = Тц узкого места {fmt(ум['тц_мин'], 2)} мин "
            f"(больше такта {fmt(такт, 2)} мин) — {ИСТОЧНИК_ВПП}")
    else:
        r["расчёты"].append(
            f"База ожидания = такт {fmt(такт, 2)} мин (больше Тц узкого места) "
            f"— {ИСТОЧНИК_ВПП}")

    # --- По операциям: загрузка, норма операторов, ожидание запасов ---
    по_операциям = []
    выше_такта = []
    сум_запасов = 0
    for op in ops:
        тц = op["тц_мин"]
        зап = op.get("запас_после_шт")
        загрузка = тц / такт * 100
        стр = {"имя": op["имя"].strip(), "тц_мин": тц,
               "запас_после_шт": зап,
               "загрузка_пкт": round(загрузка, 1),
               "выше_такта": тц > такт,
               "операторов_норма": тц / такт,
               "ожидание_мин": (зап or 0) * база if зап is not None else None}
        if тц > такт:
            выше_такта.append(op["имя"].strip())
        if зап:
            сум_запасов += зап
        по_операциям.append(стр)
    r["операции"] = по_операциям
    r["выше_такта"] = выше_такта
    r["сум_запасов_шт"] = сум_запасов

    # --- ВПП ---
    есть_запасы = any(op.get("запас_после_шт") is not None for op in ops)
    if есть_запасы:
        ожидание = sum(op["ожидание_мин"] or 0 for op in по_операциям)
        впп = сум_тц + ожидание
        r["впп_мин"] = впп
        r["впп_ожидание_мин"] = ожидание
        r["потенциал_впп_мин"] = ожидание
        r["потенциал_впп_пкт"] = round(ожидание / впп * 100, 1) if впп else 0.0
        r["расчёты"].append(
            f"ВПП = Σ Тц + Σ (запас × база) = {fmt(сум_тц, 2)} + "
            f"{fmt(ожидание, 2)} = {fmt(впп, 2)} мин ({ИСТОЧНИК_ВПП})")
        r["допущения"].append(
            "Потенциал снижения ВПП = время ожидания в запасах "
            f"({fmt(ожидание, 2)} мин = {fmt(r['потенциал_впп_пкт'])} % ВПП): "
            "явной формулы в источниках нет — считаем, что полное устранение "
            "межоперационных запасов сводит ВПП к Σ Тц")
    else:
        r["домерить"].append("запасы после операций → ВПП и потенциал снижения ВПП")

    # --- Число операторов по норме ---
    норма = сум_тц / такт
    r["операторов_по_норме"] = норма
    r["допущения"].append(
        f"Число операторов по норме = Σ Тц / такт = {fmt(сум_тц, 2)} / "
        f"{fmt(такт, 2)} = {fmt(норма, 2)} чел.: явной формулы в источниках "
        "нет — следует из балансировки загрузки под время такта")

    # --- Выработка и трудоёмкость ---
    объём = d.get("объём_выпуска_шт")
    if объём is None:
        объём = спрос
        r["допущения"].append(
            "Объём выпуска не задан — для выработки и трудоёмкости принят "
            "равным спросу за период")
    r["объём_выпуска_шт"] = объём
    чел = d.get("численность_чел")
    if чел:
        r["выработка_шт_на_чел"] = объём / чел
        r["расчёты"].append(
            f"Выработка = объём / численность = {fmt(объём)} / {fmt(чел)} = "
            f"{fmt(объём / чел, 2)} шт/чел за период ({ИСТОЧНИК_ВЫРАБОТКА})")
    else:
        r["домерить"].append("численность персонала потока → выработка на человека")
    r["трудоёмкость_чел_мин"] = сум_тц * объём
    r["допущения"].append(
        f"Трудоёмкость = Σ Тц × объём = {fmt(сум_тц, 2)} × {fmt(объём)} = "
        f"{fmt(сум_тц * объём, 1)} чел·мин: термин есть в «Приложении 2» "
        "(нормы трудоёмкости), явной формулы в источниках нет")

    # --- % загрузки (для отчёта сводной строкой) ---
    r["расчёты"].append(
        "Загрузка операций = Тц / такт × 100: "
        + "; ".join(f"«{o['имя']}» {fmt(o['загрузка_пкт'])} %"
                    for o in по_операциям)
        + f" ({ИСТОЧНИК_ЗАГРУЗКА})")
    return r


def otchyot(d, r):
    """Markdown-отчёт прогона (и для ответа API, и для progony.отчёт_md)."""
    L = [f"# Показатели потока · {d.get('поток') or 'поток'}",
         f"Дата прогона: {date.today().isoformat()} · инструмент v1.0 "
         "(детерминированный, без ИИ)", ""]
    L.append("## 1. Сводка показателей")
    L.append(f"- Время такта: **{fmt(r['такт_мин'], 2)} мин/шт** "
             f"(спрос {fmt(d['спрос_шт_в_период'])} шт, доступное время "
             f"{fmt(d['доступное_время_мин'])} мин)")
    L.append(f"- Σ Тц (время цикла потока): **{fmt(r['сум_тц_мин'], 2)} мин**")
    if r.get("впп_мин") is not None:
        L.append(f"- ВПП: **{fmt(r['впп_мин'], 2)} мин** "
                 f"({fmt(r['впп_мин'] / 60, 1)} ч), из них ожидание в запасах "
                 f"{fmt(r['впп_ожидание_мин'], 2)} мин")
        L.append(f"- Потенциал снижения ВПП: **{fmt(r['потенциал_впп_мин'], 2)} мин** "
                 f"({fmt(r['потенциал_впп_пкт'])} % ВПП)")
    if r.get("выработка_шт_на_чел") is not None:
        L.append(f"- Выработка на человека: **{fmt(r['выработка_шт_на_чел'], 2)} "
                 f"шт/чел** за период (объём {fmt(r['объём_выпуска_шт'])} шт, "
                 f"численность {fmt(d['численность_чел'])} чел.)")
    L.append(f"- Трудоёмкость выпуска: **{fmt(r['трудоёмкость_чел_мин'], 1)} "
             f"чел·мин** ({fmt(r['трудоёмкость_чел_мин'] / 60, 1)} чел·ч)")
    L.append(f"- Операторов по норме: **{fmt(r['операторов_по_норме'], 2)} чел.**")
    L.append("")
    L.append("## 2. Операции")
    L.append("| Операция | Тц, мин | Загрузка, % | Выше такта | Запас после, шт | "
             "Ожидание, мин | Операторов по норме |")
    L.append("|---|---|---|---|---|---|---|")
    for o in r["операции"]:
        L.append(f"| {o['имя']} | {fmt(o['тц_мин'], 2)} | {fmt(o['загрузка_пкт'])} "
                 f"| {'ДА' if o['выше_такта'] else '—'} "
                 f"| {fmt(o['запас_после_шт']) if o['запас_после_шт'] is not None else '—'} "
                 f"| {fmt(o['ожидание_мин'], 2) if o['ожидание_мин'] is not None else '—'} "
                 f"| {fmt(o['операторов_норма'], 2)} |")
    L.append("")
    ум = r["узкое_место"]
    L.append(f"**Узкое место: «{ум['имя']}»** — max Тц {fmt(ум['тц_мин'], 2)} мин.")
    if r["выше_такта"]:
        L.append("Операции выше такта (не успевают за темпом спроса): "
                 + ", ".join(f"«{и}»" for и in r["выше_такта"]) + ".")
    else:
        L.append("Все операции укладываются в такт.")
    L.append("")
    if r["домерить"]:
        L.append("## 3. Каких данных не хватает")
        for x in r["домерить"]:
            L.append(f"- {x}")
        L.append("")
    L.append("## 4. Расчёты и источники")
    for x in r["расчёты"]:
        L.append(f"- {x}")
    L.append("")
    if r["допущения"]:
        L.append("## 5. Допущения (чего нет в источниках явно)")
        for x in r["допущения"]:
            L.append(f"- {x}")
        L.append("")
    L.append("> Только расчёт показателей. Мероприятия не предлагаются.")
    return "\n".join(L)


def itogi(d, r):
    """Компактные итоги для progony.итоги_json."""
    return {"поток": d.get("поток") or "",
            "такт_мин": round(r["такт_мин"], 4),
            "сум_тц_мин": round(r["сум_тц_мин"], 4),
            "впп_мин": (round(r["впп_мин"], 2)
                        if r.get("впп_мин") is not None else None),
            "потенциал_впп_мин": (round(r["потенциал_впп_мин"], 2)
                                  if r.get("потенциал_впп_мин") is not None else None),
            "выработка_шт_на_чел": (round(r["выработка_шт_на_чел"], 4)
                                    if r.get("выработка_шт_на_чел") is not None else None),
            "трудоёмкость_чел_мин": round(r["трудоёмкость_чел_мин"], 1),
            "операторов_по_норме": round(r["операторов_по_норме"], 2),
            "узкое_место": r["узкое_место"]["имя"],
            "узкое_место_тц_мин": r["узкое_место"]["тц_мин"],
            "выше_такта": r["выше_такта"],
            "операций": len(r["операции"]),
            "домерить": r["домерить"]}


def main():
    if len(sys.argv) != 2:
        sys.exit("Запуск: python3 pokazateli_potoka.py <данные.json>")
    with open(sys.argv[1], encoding="utf-8") as f:
        d = json.load(f)
    oshibki = validirovat(d)
    if oshibki:
        sys.exit("Ошибки входа:\n" + "\n".join(f"- {e}" for e in oshibki))
    r = raschet(d)
    print(otchyot(d, r))


if __name__ == "__main__":
    main()
