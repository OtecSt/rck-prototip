def _main(argv):
    if len(argv) < 2:
        print("использование: python3 otbor.py вход.json [--json]",
              file=sys.stderr)
        return 2
    with open(argv[1], encoding="utf-8") as f:
        d = json.load(f)
    osh = validirovat(d)
    if osh:
        print("ОШИБКИ ВХОДА:", file=sys.stderr)
        for o in osh:
            print(" - " + o, file=sys.stderr)
        return 1
    r = raschet(d)
    if "--json" in argv[2:]:
        print(json.dumps(r, ensure_ascii=False, indent=2))
    else:
        print(r["скоринг_карта_md"])
    return 0


