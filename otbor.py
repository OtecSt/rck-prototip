def validirovat(d):
    """Блокирующие ошибки структуры входа. Незаполненные пункты — не ошибка
    (попадают в перечень незаполненных результата)."""
    osh = []
    if not isinstance(d, dict):
        return ["вход должен быть JSON-объектом"]
    трек = d.get("трек", "рцк")
    if not isinstance(трек, str) or трек.lower() not in ТРЕКИ:
        osh.append("поле «трек» должно быть строкой «рцк» или «фцк»")
        трек = "рцк"
    спека = спека_трека(трек)
    пункты = спека["пункты"]
    фп = d.get("формальная_проверка")
    if фп is not None:
        if not isinstance(фп, dict):
            osh.append("раздел «формальная_проверка» должен быть объектом")
        else:
            for k, _ in ФОРМАЛЬНЫЕ_КРИТЕРИИ:
                if k in фп and not isinstance(фп[k], bool):
                    osh.append(f"«формальная_проверка.{k}» должна быть "
                               "булевой (да/нет)")
    отв = d.get("ответы_чеклиста")
    if отв is not None:
        if not isinstance(отв, list):
            osh.append("раздел «ответы_чеклиста» должен быть списком")
        else:
            for i, з in enumerate(отв, 1):
                if not isinstance(з, dict):
                    osh.append(f"ответы_чеклиста[{i}] должен быть объектом")
                    continue
                н = з.get("пункт")
                if н not in пункты:
                    osh.append(f"ответы_чеклиста[{i}]: неизвестный пункт "
                               f"«{н}» чек-листа {спека['название']}")
                if "ответ" in з and not isinstance(з["ответ"], bool):
                    osh.append(f"ответы_чеклиста[{i}] (п. {н}): «ответ» "
                               "должен быть булевым (да/нет)")
    return osh


