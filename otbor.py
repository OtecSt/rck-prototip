def _формальная(d):
    """Итог формальной проверки: проваленные и незаполненные критерии."""
    фп = d.get("формальная_проверка") or {}
    проваленные, пропущенные = [], []
    for k, название in ФОРМАЛЬНЫЕ_КРИТЕРИИ:
        v = фп.get(k)
        if v is None:
            пропущенные.append({"ключ": k, "название": название})
        elif v is False:
            проваленные.append({"ключ": k, "название": название})
    return {"проваленные": проваленные, "пропущенные": пропущенные,
            "прошла": not проваленные and not пропущенные,
            "полностью_заполнена": not пропущенные}


def _чеклист(d, спека):
    """Подсчёт баллов по чек-листу трека (ответ True = соответствует = 1 балл)."""
    чеклист = спека["чеклист"]
    пункты = спека["пункты"]
    ответы = {з.get("пункт"): з.get("ответ")
              for з in (d.get("ответы_чеклиста") or [])
              if isinstance(з, dict) and з.get("пункт") in пункты}
    по_разделам = []
    баллы = 0
    отсекающие, условные, незаполненные = [], [], []
    for р in чеклист:
        б, м = 0, 0
        for п in р["пункты"]:
            м += 1
            a = ответы.get(п["номер"])
            if a is None:
                незаполненные.append(п["номер"])
                continue
            if a:
                б += 1
            elif п.get("отсекающий"):
                отсекающие.append({"пункт": п["номер"], "текст": п["текст"]})
            elif п.get("условно_отсекающий"):
                условные.append({"пункт": п["номер"], "текст": п["текст"]})
        баллы += б
        по_разделам.append({"раздел": р["раздел"], "название": р["название"],
                            "баллы": б, "максимум": м})
    return {"баллы": баллы, "максимум": спека["максимум"], "по_разделам": по_разделам,
            "отсекающие_сработавшие": отсекающие,
            "условные_отсекающие": условные,
            "незаполненные": незаполненные}


def raschet(d):
    """Полный расчёт отбора. Возвращает результат (ошибки — через validirovat)."""
    трек = (d.get("трек") or "рцк").lower()
    спека = спека_трека(трек)
    ф = _формальная(d)
    ч = _чеклист(d, спека)
    порог_пройден = ч["баллы"] >= ПОРОГ
    # Вердикт: сначала формальная, потом отсекающие, потом порог (п. 3.7 МР).
    if not ф["прошла"]:
        if ф["проваленные"]:
            вердикт, код = "не проходит", "не_проходит_формальная"
        else:
            вердикт, код = "формальная проверка не завершена", "формальная_неполная"
    elif ч["отсекающие_сработавшие"]:
        вердикт, код = "отклонено", "отклонено_отсекающий"
    elif not ч["незаполненные"] and порог_пройден:
        вердикт, код = "проходит", "проходит"
    elif not ч["незаполненные"]:
        вердикт, код = "не проходит", "не_проходит_баллы"
    else:
        вердикт, код = "чек-лист заполнен не полностью", "чеклист_неполный"
    res = {"предприятие": (d.get("предприятие") or "").strip() or None,
           "трек": трек,
           "трек_название": спека["название"],
           "приложение": спека["приложение"],
           "порог": ПОРОГ,
           "формальная": ф,
           "чеклист": ч,
           "порог_пройден": порог_пройден,
           "отсекающие_сработавшие": [з["пункт"]
                                      for з in ч["отсекающие_сработавшие"]],
           "вердикт": вердикт, "вердикт_код": код}
    res["скоринг_карта_md"] = скоринг_карта(d, res)
    return res


