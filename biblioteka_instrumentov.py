def proverit_kursy(put_k_katalogu=None):
    """Самопроверка: каждая ссылка kurs_fck обязана существовать в каталоге
    курсов. Возвращает список нарушений (пустой = всё найдено)."""
    if put_k_katalogu is None:
        put_k_katalogu = (Path(__file__).resolve().parent.parent
                          / "конспекты_курсов" / "каталог_сырой.txt")
    try:
        текст = Path(put_k_katalogu).read_text(encoding="utf-8")
    except OSError:
        # Каталог — артефакт контура разработки; в прод-образе его нет.
        # Сверка пропускается (не блокирует генерацию плана), без нарушений.
        return []
    нарушения = []
    def _проверить(kurs, контекст):
        if kurs not in текст:
            нарушения.append(f"{контекст}: курс «{kurs}» не найден в каталоге")
    for тип, инструменты in БИБЛИОТЕКА.items():
        for ин in инструменты:
            _проверить(ин["kurs_fck"], f"библиотека[{тип}]/{ин['instrument']}")
    # Цифровая ветка вне каталога ФЦК: kurs_fck=None — легитимно, пропускаем;
    # но если курс всё же указан — он обязан существовать в каталоге.
    for тип, инструменты in ЦИФРОВАЯ_ВЕТКА.items():
        for ин in инструменты:
            if ин.get("kurs_fck") is not None:
                _проверить(ин["kurs_fck"],
                           f"цифровая ветка[{тип}]/{ин['instrument']}")
    for ключ, з in ИНСТРУМЕНТЫ_ЗАМЕРА.items():
        _проверить(з["kurs_fck"], f"замер[{ключ}]")
    return нарушения


