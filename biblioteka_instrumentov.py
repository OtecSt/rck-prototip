def цифровой_инструмент(тип, название):
    """Запись цифровой ветки по (причина-тип, название) или None."""
    for ин in ЦИФРОВАЯ_ВЕТКА.get(тип, []):
        if ин["instrument"] == название:
            return ин
    return None


def библиотека_полная():
    """Базовые 24 инструмента + цифровая ветка, сгруппированные по
    причина-типу. Базовая БИБЛИОТЕКА не мутируется."""
    полная = {тип: list(инструменты) for тип, инструменты in БИБЛИОТЕКА.items()}
    for тип, инструменты in ЦИФРОВАЯ_ВЕТКА.items():
        полная.setdefault(тип, []).extend(инструменты)
    return полная

