def build_soglashenie(d, путь_выход):
    """Соглашение о сотрудничестве (ред. 8): основной текст разделов 1–12
    дословно по шаблону + подстановка реквизитов; приложения № 1–8
    формируются отдельными документами."""
    if not isinstance(d, dict):
        raise ValueError("Корень вход-JSON должен быть объектом")
    недомеры = []
    замены, подстроки, места, лица = _подстановки(d, недомеры)
    подп = d.get("подписанты") or {}
    пп, пц = подп.get("предприятие") or {}, подп.get("рцк") or {}
    if not (пп.get("фио") or "").strip():
        недомеры.append("Подписант от Предприятия: ФИО")
    if not (пц.get("фио") or "").strip():
        недомеры.append("Подписант от РЦК: ФИО")

    doc = _новый_документ()
    очередь_мест = list(места)
    очередь_лиц = list(лица)
    for kind, payload in СКЕЛЕТ_СОГЛАШЕНИЕ:
        if kind == "p":
            текст = payload
            стр = текст.strip()
            if стр in замены:
                текст = замены[стр]
            elif "(далее – Предприятие) в лице" in текст and \
                    "заключили настоящее" in текст:
                текст = замены["ПРЕАМБУЛА"]
            elif стр == "Место нахождения:":
                текст = "Место нахождения: " + (очередь_мест.pop(0)
                                               if очередь_мест else ПУСТО)
            elif стр == "Уполномоченное лицо:":
                текст = "Уполномоченное лицо: " + (очередь_лиц.pop(0)
                                                   if очередь_лиц else ПУСТО)
            else:
                for старое, новое in подстроки:
                    if старое in текст:
                        текст = текст.replace(старое, новое)
            bold = стр.startswith(("Соглашение о сотрудничестве",
                                   "1. Предмет", "2. Условия", "3. Протокол",
                                   "4. Конфиденциальность", "5.Уведомления",
                                   "5. Уведомления", "6. Противодействие",
                                   "7. Заверения", "8. Обстоятельства",
                                   "9. Заключительные", "10. Адреса",
                                   "11. Приложения", "12. Подписи"))
            if стр:
                параграф(doc, текст, bold=bold, size=10 if not bold else 11,
                         space_after=4)
        else:
            rows = payload
            t = таблица(doc, len(rows), max(len(r) for r in rows), границы=False)
            _снять_границы(t)
            for ri, row in enumerate(rows):
                for ci, val in enumerate(row):
                    if ci >= len(t.rows[ri].cells):
                        continue
                    v = val
                    if v.strip() == "место подписания":
                        v = (d.get("место") or "").strip() or ПУСТО
                        if v == ПУСТО:
                            недомеры.append("Соглашение: место подписания")
                    elif v.strip().startswith("«__» ___________ 20__ г."):
                        v = (d.get("дата") or "").strip() or ПУСТО
                        if v == ПУСТО:
                            недомеры.append("Соглашение: дата подписания")
                    elif "от Предприятия:" in v:
                        v = "от Предприятия:"
                    elif v.startswith("_____________________ /") and ri > 0:
                        # строка подписи: колонка 0 — предприятие, 1 — РЦК
                        фио = (пп.get("фио") if ci == 0 else пц.get("фио")) or "___"
                        v = f"_____________________ /{фио}/\\nМ.П."
                    ячейка(t.rows[ri].cells[ci], v,
                           bold=("от " in v or "Подписи" in v), size=10)
    _раздел_домерить(doc, недомеры)
    doc.save(путь_выход)
    return {"незаполненных_полей": len(set(недомеры)), "путь": путь_выход}


