def извлечь_скелет():
    doc = Document(ШАБЛОН)
    body = doc.element.body
    seq = []
    for child in body.iterchildren():
        tag = child.tag.split("}")[1]
        if tag == "p":
            seq.append(("p", Paragraph(child, doc).text))
        elif tag == "tbl":
            t = Table(child, doc)
            rows = [[c.text for c in r.cells] for r in t.rows]
            seq.append(("tbl", rows))
    # обрезка: до таблицы подписей (таблица после «12. Подписи Сторон») включительно
    скелет = []
    seen_12 = False
    for kind, payload in seq:
        скелет.append([kind, payload])
        if kind == "p" and payload.strip().startswith("12. Подписи Сторон"):
            seen_12 = True
            continue
        if seen_12 and kind == "tbl":
            break
    assert seen_12, "не найден раздел 12 в шаблоне"
    return скелет


