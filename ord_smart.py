def main():
    if len(sys.argv) < 3:
        sys.exit("Запуск:\n"
                 "  python3 ord_smart.py ord данные.json [пакет.docx]\n"
                 "  python3 ord_smart.py smart цели.json [цели.md]")
    режим, вход_path = sys.argv[1], sys.argv[2]
    with open(вход_path, encoding="utf-8") as f:
        d = json.load(f)

    if режим == "ord":
        osh = validirovat_ord(d)
        if osh:
            sys.exit("Ошибки входа:\n" + "\n".join(f"- {e}" for e in osh))
        out = sys.argv[3] if len(sys.argv) > 3 else "пакет_орд.docx"
        недомеры = gen_ord_docx(d, out)
        print(отчёт_ord(d, недомеры, out))
    elif режим == "smart":
        osh = validirovat_smart(d)
        if osh:
            sys.exit("Ошибки входа:\n" + "\n".join(f"- {e}" for e in osh))
        md, _, _ = gen_smart_md(d)
        if len(sys.argv) > 3:
            with open(sys.argv[3], "w", encoding="utf-8") as f:
                f.write(md)
            print(f"# записано: {sys.argv[3]}")
        else:
            print(md)
    else:
        sys.exit(f"неизвестный режим «{режим}»: ord | smart")


if __name__ == "__main__":
    main()
