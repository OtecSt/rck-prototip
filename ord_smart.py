    p("3. Ответственным по п. 1 настоящего приказа создать рабочие группы по "
      "направлениям, организовать их работу и обеспечить выполнение ключевых "
      "мероприятий Программы, в том числе утверждение целей по повышению "
      "производительности труда (направление «Декомпозиция целей») и реализацию "
      f"проекта по оптимизации пилотного потока «{поток}» "
      "(направление «Оптимизация продуктовых потоков»).")
    p("4. На период отсутствия ответственных лиц ответственность несут лица, "
      "назначенные исполняющими обязанности соответствующими приказами.")
    p("5. Контроль исполнения настоящего приказа оставляю за собой.")
    p("")
    долж_рук = _v(рук, "должность", недомеры=недомеры, метка="руководитель.должность")
    фио_рук = _v(рук, "фио", недомеры=недомеры, метка="руководитель.фио")
    p("")
    hp2 = doc.add_paragraph()
    hp2.add_run(f"{долж_рук} ______________________ {фио_рук}")
    p("")

    # ================= РАЗДЕЛ 2. КАРТОЧКА ПРОЕКТА =================
    doc.add_page_break()

    p("УТВЕРЖДАЮ:", align="right")
    p(f"{долж_рук} {предприятие}", align="right")
    p(f"____________________ {фио_рук}", align="right")
    p(f"«___» ______________________ {date.today().year} г.", align="right")
    p("")
    название_проекта = _v(проект, "название", недомеры=недомеры,
                          метка="проект.название")
    p(f"Проект по оптимизации: «{название_проекта}»", bold=True, align="center",
      size=13)
    p("")

    # --- Ключевые события проекта
    p("Ключевые события проекта", bold=True)
    дс = _v(события, "диагностика_с", недомеры=недомеры, метка="события.диагностика_с")
    дп = _v(события, "диагностика_по", недомеры=недомеры, метка="события.диагностика_по")
    вс = _v(события, "внедрение_с", недомеры=недомеры, метка="события.внедрение_с")
    вп = _v(события, "внедрение_по", недомеры=недомеры, метка="события.внедрение_по")
    p(f"Старт проекта: {_v(события, 'старт', недомеры=недомеры, метка='события.старт')}")
    p(f"Диагностика и целевое состояние: {дс} – {дп}")
    p(f"Совещание — старт мероприятий по улучшениям: "
      f"{_v(события, 'совещание', недомеры=недомеры, метка='события.совещание')}")
    p(f"Внедрение улучшений: {вс} – {вп}")
    p(f"Закрепление результатов и закрытие проекта: "
      f"{_v(события, 'закрытие', недомеры=недомеры, метка='события.закрытие')}")
    p("")

    # --- Обоснование выбора
    p("Обоснование выбора", bold=True)
    p(f"Ключевой риск: {_v(проект, 'ключевой_риск', недомеры=недомеры, метка='проект.ключевой_риск')}")
    вр = [_s(x) for x in (проект.get("второстепенные_риски") or []) if _s(x)]
    if вр:
        p("Второстепенные риски:")
        for x in вр:
            p(f"— {x};")
    else:
        недомеры.append("проект.второстепенные_риски")
        p(f"Второстепенные риски: {PLACE}")
    p("")

    # --- Цели и плановый эффект
    p("Цели и плановый эффект", bold=True)
    цели = d.get("цели") or []
    таб = doc.add_table(rows=1, cols=4)
    таб.style = "Table Grid"
    hdr = таб.rows[0].cells
    for i, h in enumerate(("Наименование цели", "Текущий показатель",
                           "Целевой показатель", "Показатель идеального состояния")):
        hdr[i].paragraphs[0].add_run(h).bold = True
    if not цели:
        недомеры.append("цели (наименование, текущий, целевой, идеальный показатели)")
        row = таб.add_row().cells
        row[0].text = PLACE
    else:
        for i, ц in enumerate(цели, 1):
            row = таб.add_row().cells
            наим = _s(ц.get("наименование")) or PLACE
            row[0].text = f"{i}. {наим}"
            row[1].text = str(ц.get("текущий") if ц.get("текущий") not in (None, "") else PLACE)
            row[2].text = str(ц.get("целевой") if ц.get("целевой") not in (None, "") else PLACE)
            row[3].text = str(ц.get("идеальный") if ц.get("идеальный") not in (None, "") else PLACE)
            if PLACE in (наим, row[1].text, row[2].text):
                недомеры.append(f"цели[{i}] «{наим}»: текущий/целевой показатель")
    p("")

    # --- Вовлечённые лица и рамки проекта
    p("Вовлечённые лица и рамки проекта", bold=True)
    p(f"Клиенты процесса: {_v(рамки, 'клиенты', недомеры=недомеры, метка='рамки.клиенты')}")
