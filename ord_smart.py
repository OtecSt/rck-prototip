# ---------- Утилиты ----------

def _s(v):
    """Строка или None (пустое = недомер)."""
    if v is None:
        return None
    s = str(v).strip()
    return s if s else None


def _num(v):
    """Число или None."""
    if isinstance(v, bool):
        return None
    if isinstance(v, (int, float)):
        return float(v)
    if isinstance(v, str):
        s = v.strip().replace("\u00a0", " ").replace(",", ".")
        s = s.replace(" ", "")
        try:
            return float(s)
        except ValueError:
            return None
    return None


def _f(x):
    """Число по-русски: 17,85; целое без дробной части."""
    if x is None:
        return PLACE
    if abs(x - round(x)) < 1e-9:
        return str(int(round(x)))
    return f"{x:.2f}".rstrip("0").rstrip(".").replace(".", ",")


def _пкт(x):
    if x is None:
        return PLACE
    return f"{x:.1f}".replace(".", ",")


