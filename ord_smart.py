ПОРОГ_ОБОСНОВАНИЯ_ПКТ = 30.0  # рост/снижение свыше 30 % — «требует обоснования»


def _ключ_показателя(наим):
    n = (наим or "").lower()
    for алиас, ключ in _АЛИАСЫ.items():
        if алиас in n:
            return ключ
    return None


def validirovat_smart(d):
    osh = []
    if not isinstance(d, dict):
        return ["вход должен быть JSON-объектом"]
    рамка = d.get("рамка", "федеральная")
    if рамка not in РАМКИ_ПТ:
        osh.append(f"поле «рамка» должно быть одним из: {', '.join(РАМКИ_ПТ)}")
    if not isinstance(d.get("цели"), list) or not d.get("цели"):
        osh.append("поле «цели» должно быть непустым списком объектов")
    return osh


def _smart_разбор(ц, i, рамка_ключ):
    """Разворачивает одну цель по SMART + валидаторы. Возвращает (md-блок,
    итоги-запись, недомеры)."""
    недомеры = []
    флаги = []
    наим = _s(ц.get("наименование")) or f"Цель {i}"
    ед = _s(ц.get("ед"))
    тек = _num(ц.get("текущий"))
    цел = _num(ц.get("целевой"))
    идеал = _num(ц.get("идеальный"))
    срок = _s(ц.get("срок"))
    методика_вход = _s(ц.get("методика"))
    источник_вход = _s(ц.get("источник"))
    период_вход = _s(ц.get("периодичность"))
    напр_вход = _s(ц.get("направление"))

    ключ = _ключ_показателя(наим)
    спр = МУ66.get(ключ) if ключ else None
    напр = напр_вход or (спр["направление"] if спр else None)

    # --- M: дельта
    дельта_пкт = None
    if тек is not None and цел is not None and тек != 0:
        дельта_пкт = (цел - тек) / abs(тек) * 100.0
        if напр == "снижение":
            дельта_пкт = -дельта_пкт if дельта_пкт < 0 else дельта_пкт
            # для снижения «движение к цели» = падение значения
            движ = (тек - цел) / abs(тек) * 100.0
            дельта_пкт = движ

    # --- A: достижимость
    if дельта_пкт is not None and дельта_пкт > ПОРОГ_ОБОСНОВАНИЯ_ПКТ:
        флаги.append(f"ТРЕБУЕТ ОБОСНОВАНИЯ: изменение {_пкт(дельта_пкт)} % — выше "
                     f"порога {int(ПОРОГ_ОБОСНОВАНИЯ_ПКТ)} %; приложить расчёт "
                     "резервов (диагностика, карта целевого состояния)")
    if дельта_пкт is not None and дельта_пкт <= 0:
        флаги.append("целевое значение не улучшает текущее — проверить направление "
                     "цели (рост/снижение)")

    # --- M: измеримость
    измеримо = тек is not None and цел is not None and (спр is not None or методика_вход)
    if тек is None:
        недомеры.append(f"цели[{i}] «{наим}»: текущий показатель (замер «до»)")
    if цел is None:
        недомеры.append(f"цели[{i}] «{наим}»: целевой показатель")
    if ед is None:
        недомеры.append(f"цели[{i}] «{наим}»: единица измерения")
    if not измеримо:
        флаги.append("НЕ ИЗМЕРИМА: нет числовой базы/цели или методики расчёта "
                     "(МУ-65, п. 4.1.5: методика — в приложение к карточке)")

    # --- R: релевантность (обязательный показатель МУ-66 + рамка ПТ)
    if спр is None:
        флаги.append("показатель не из реестра МУ-66 (выработка/трудоёмкость/ВПП/"
                     "запасы) — допустим как локальный, но проект обязан двигать "
                     "обязательный показатель (выработка или трудоёмкость)")

    # --- R: рамка ПТ (только для обязательного показателя роста)
    рамка = РАМКИ_ПТ[рамка_ключ]
    рамка_замечание = None
    if ключ == "выработка" and дельта_пкт is not None:
        горизонт = int(_num(ц.get("горизонт_лет")) or 1)
        горизонт = min(max(горизонт, 1), 3)
        норма = рамка["годы"][горизонт]
        if дельта_пкт < норма:
            рамка_замечание = (f"НИЖЕ РАМКИ ПТ: +{_пкт(дельта_пкт)} % при норме "
                               f"≥ {_пкт(норма)} % ({рамка_ключ}, горизонт "
                               f"{горизонт} г.) — усилить цель или зафиксировать "
                               "обоснование")
            флаги.append(рамка_замечание)
        else:
            рамка_замечание = (f"В рамке ПТ ({рамка_ключ}): +{_пкт(дельта_пкт)} % "
                               f"при норме ≥ {_пкт(норма)} % (горизонт {горизонт} г.)")

    if срок is None:
        недомеры.append(f"цели[{i}] «{наим}»: срок достижения (T)")

    # ---------- markdown ----------
    L = [f"## Цель {i}. {наим}", ""]
    L.append(f"**S (конкретная):** {наим.rstrip('.')}"
             + (f", {_s(ц.get('поток'))}" if _s(ц.get("поток")) else "")
             + ". Цель относится к результату процесса, а не к мероприятиям "
               "(мероприятия — средства, МУ-65, п. 4.1.5).")
    m_числа = f"текущий {_f(тек)} → целевой {_f(цел)}"
    if идеал is not None:
        m_числа += f", идеал {_f(идеал)}"
    L.append(f"**M (измеримая):** {m_числа} {ед or PLACE}"
             + (f"; изменение {_пкт(дельта_пкт)} %" if дельта_пкт is not None else "")
             + ("" if измеримо else " — **измеримость НЕ подтверждена**"))
    if спр:
        L.append(f"- методика расчёта (МУ-66-2024): {спр['формула']}")
        L.append(f"- источник данных: {источник_вход or спр['источник']}")
        L.append(f"- периодичность: {период_вход or спр['периодичность']}")
    else:
        L.append(f"- методика расчёта: {методика_вход or PLACE + ' — указать и приложить к карточке'}")
        L.append(f"- источник данных: {источник_вход or PLACE}")
        L.append(f"- периодичность: {период_вход or PLACE}")
    if дельта_пкт is not None:
        a_txt = (f"изменение {_пкт(дельта_пкт)} % к базе "
                 + ("— в пределах типового коридора проектов ФЦК (≤ 30 %)."
                    if дельта_пкт <= ПОРОГ_ОБОСНОВАНИЯ_ПКТ and дельта_пкт > 0
                    else ""))
    else:
        a_txt = PLACE + " (нет базы/цели — см. «домерить»)"
    L.append(f"**A (достижимая):** {a_txt}")
    r_txt = (спр["подпись"] if спр else
             "локальный показатель (вне реестра МУ-66)")
    L.append(f"**R (значимая):** {r_txt}. Рамка ПТ: {рамка_ключ} — {рамка['описание']}."
             + (f" {рамка_замечание}." if рамка_замечание else ""))
    L.append(f"**T (ограниченная во времени):** срок — {срок or PLACE}. "
             "Привязка к этапам спины:")
    for e in ЭТАПЫ_ЦЕЛИ:
        L.append(f"  - {e}")
    if флаги:
        L.append("")
        L.append("**Флаги валидаторов:**")
        for f in флаги:
            L.append(f"- ⚠ {f}")
    L.append("")

    итог = {
        "наименование": наим,
        "показатель_му66": ключ,
        "ед": ед,
        "текущий": тек,
        "целевой": цел,
        "идеальный": идеал,
        "дельта_пкт": round(дельта_пкт, 2) if дельта_пкт is not None else None,
        "измеримо": измеримо,
        "флаги": флаги,
        "срок": срок,
    }
    return L, итог, недомеры


def gen_smart_md(d):
    """Полный markdown конструктора SMART. Возвращает (md, итоги, недомеры)."""
    рамка_ключ = d.get("рамка", "федеральная")
    недомеры = []
    L = ["# Цели проекта по SMART (МУ-65, п. 4.1.5; показатели — МУ-66-2024)", ""]
    пред = _s((d.get("предприятие") or {}) if isinstance(d.get("предприятие"), dict)
              else d.get("предприятие"))
    поток = _s(d.get("поток"))
    if isinstance(d.get("предприятие"), dict):
        пред = _s(d["предприятие"].get("название")) or пред
    L.append(f"**Предприятие:** {пред or PLACE}  ")
    L.append(f"**Поток:** {поток or PLACE}  ")
    L.append(f"**Рамка ПТ:** {рамка_ключ} — {РАМКИ_ПТ[рамка_ключ]['описание']}  ")
    L.append(f"**Дата сборки:** {date.today().isoformat()}")
    if not пред:
        недомеры.append("предприятие")
    if not поток:
        недомеры.append("поток")
    L.append("")

    итоги_цели = []
    есть_обязательный = False
    for i, ц in enumerate(d.get("цели") or [], 1):
        блок, итог, нед = _smart_разбор(ц, i, рамка_ключ)
        L.extend(блок)
        итоги_цели.append(итог)
        недомеры.extend(нед)
        if итог["показатель_му66"] in ("выработка", "трудоёмкость"):
            есть_обязательный = True

    if not есть_обязательный:
        L.append("> ⚠ **Нет обязательного показателя МУ-66.** Каждый проект обязан "
                 "двигать рост выработки или снижение трудоёмкости — добавьте такую "
                 "цель, иначе карточка не пройдёт защиту (МУ-66-2024).")
        L.append("")

    L.append("## Домерить")
    if недомеры:
        for x in dict.fromkeys(недомеры):
            L.append(f"- {x}")
    else:
        L.append("- ничего, вход полный")
    L.append("")
    L.append("> Связка: эти цели переносятся в таблицу «Цели и плановый эффект» "
             "карточки проекта (режим `ord` этого ядра), уточняются на этапе 2 "
             "(МУ-65, п. 4.2.4), факт «после» — в протокол закрытия. "
             "Ограничения v0.1: рамка ПТ проверяется только для выработки; "
             "идеальное состояние нормативом не проверяется.")
    итоги = {
        "рамка": рамка_ключ,
        "предприятие": пред,
        "поток": поток,
        "целей": len(итоги_цели),
        "обязательный_показатель_есть": есть_обязательный,
        "цели": итоги_цели,
        "недомеры": list(dict.fromkeys(недомеры)),
    }
    return "\n".join(L), итоги, недомеры


