"""
Инструмент № 1 «Поиск узких мест потока» — v0.3 (Фаза 1, чистый Python, без LLM).
Спека: ИИ-направление/Спеки/Спека_01_Узкие_места.md; стандарт: Спеки/СТАНДАРТ_спеки.md.
Изменения v0.3 (по ревизии-2, Протокол № 12):
- слабый детектор max(Тц) исключается из ранжирования при предупреждении о базисах;
- второй эшелон ранжирования по доле ВПП (порог 10 %);
- детектор переделки (поле «возврат_пкт»);
- тип потери не выставляется без данных запасов;
- фиксы шаблона (округление малых Тц, разделы 4/5, спагетти-замеры в доказательствах).
Запуск: python3 узкие_места.py данные.json
Только диагностика. Мероприятия не предлагает.
"""

import json
import math
import sys
from datetime import date

POROG_DISBALANS_PCT = 5.0   # правило 5 % (МУ-66-2024, примечание к ф. 5.5)
POROG_BAZIS_TЦ = 3.0        # max/min Тц > 3 → базисы Тц подозрительно разные
POROG_DOLYA_VPP_PCT = 25.0  # доля блока в ВПП > 25 % → кандидат первого эшелона
POROG_DOLYA_VPP_2_PCT = 10.0  # доля блока > 10 % → второй эшелон (резерв времени)


def fmt(x, nd=1):
    if nd == 1 and x and abs(x) < 0.1:
        nd = 2
    return f"{x:.{nd}f}".replace(".", ",")


def сек_ч(сек):
    """Двойная запись секунд: «32400 сек (9,0 ч)»."""
    return f"{сек} сек ({fmt(сек / 3600)} ч)"


def пунктов(n):
    if n % 10 == 1 and n % 100 != 11:
        return "пункт"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return "пункта"
    return "пунктов"


def proverit_vhod(d):
    oshibki = []
    for i, op in enumerate(d.get("операции") or []):
        if not op.get("имя"):
            oshibki.append(f"операция #{i+1}: нет имени")
        tc = op.get("тц_мин")
        if tc is not None and (not isinstance(tc, (int, float)) or isinstance(tc, bool)
                               or not math.isfinite(tc) or tc <= 0):
            oshibki.append(f"операция «{op.get('имя', '?')}»: Тц ≤ 0 или не конечное число")
    return oshibki


def razbor(d):
    r = {"кандидаты": {}, "домерить": [], "расчёты": [], "базис_предупр": None,
         "доли_впп": [], "спагетти": []}
    ops = d.get("операции") or []
    tc_ops = [op for op in ops if op.get("тц_мин")]
    if not tc_ops:
        r["домерить"].append("время цикла (Тц) по операциям потока → узкие места, ВПП")

    # --- Такт ---
    tt = d.get("такт_линии_мин")
    if tt is None and d.get("спрос_шт_в_период") and d.get("доступное_время_мин"):
        tt = d["доступное_время_мин"] / d["спрос_шт_в_период"]
        r["расчёты"].append(
            f"Тт = доступное время / спрос = {d['доступное_время_мин']} / "
            f"{d['спрос_шт_в_период']} = {fmt(tt)} мин/шт")
    elif tt is None:
        r["домерить"].append("спрос за период и доступное рабочее время → Тт")
    r["тт"] = tt

    def кандидат(имя, детектор, доказательство, тип):
        c = r["кандидаты"].setdefault(имя, {"детекторы": [], "доказательства": [], "типы": []})
        c["детекторы"].append(детектор)
        c["доказательства"].append(доказательство)
        c["типы"].append(тип)

    # --- Контроль базисов Тц ---
    базис_битый = False
    if tc_ops:
        um = max(tc_ops, key=lambda op: op["тц_мин"])
        mn = min(tc_ops, key=lambda op: op["тц_мин"])
        if mn["тц_мин"] > 0 and um["тц_мин"] / mn["тц_мин"] > POROG_BAZIS_TЦ:
            базис_битый = True
            r["базис_предупр"] = (
                f"Разброс Тц {fmt(um['тц_мин'] / mn['тц_мин'])}× (max {fmt(um['тц_мин'])} / "
                f"min {fmt(mn['тц_мин'])} мин): операции, вероятно, в РАЗНЫХ базисах "
                f"(шт vs партия) — детектор max(Тц) исключён из ранжирования")

    # --- Детектор 1: Тц (max / Тц>Тт) ---
    if tc_ops:
        um = max(tc_ops, key=lambda op: op["тц_мин"])
        r["расчёты"].append(f"max(Тц) = «{um['имя']}» ({fmt(um['тц_мин'])} мин)")
        if tt is not None:
            for op in sorted(tc_ops, key=lambda o: -o["тц_мин"]):
                if op["тц_мин"] > tt:
                    п = (op["тц_мин"] - tt) / tt * 100
                    кандидат(op["имя"], "Тц > Тт",
                             f"Тц {fmt(op['тц_мин'])} мин > Тт {fmt(tt)} мин "
                             f"(дисбаланс {fmt(п)} %)", "ожидание (дисбаланс)")
            дисб = (um["тц_мин"] - tt) / tt * 100
            r["дисбаланс"] = {"пкт": дисб,
                              "вердикт": "несбалансирована" if дисб > POROG_DISBALANS_PCT
                                         else "сбалансирована",
                              "расчёт": f"Дисбаланс = ({fmt(um['тц_мин'])} − {fmt(tt)}) / "
                                        f"{fmt(tt)} = {fmt(дисб)} % (порог 5 %)"}
        elif not базис_битый:
            кандидат(um["имя"], "max(Тц)",
                     f"Тц {fmt(um['тц_мин'])} мин — максимальный по потоку "
                     f"(без Тт — слабый детектор)", "не классифицировано (нет Тт)")
        else:
            r["расчёты"].append(
                f"max(Тц) «{um['имя']}» исключён из ранжирования (базисы Тц разные)")

    # --- Детектор 2: min производительность ---
    пр_ops = [(op["имя"], op["производительность_т_ч"])
              for op in ops if op.get("производительность_т_ч")]
    if len(пр_ops) >= 2:
        имя, пр = min(пр_ops, key=lambda t: t[1])
        строка = " / ".join(fmt(p) for _, p in пр_ops)
        кандидат(имя, "min(Пр)",
                 f"производительность {fmt(пр)} т/ч — минимальная из измеренных "
                 f"({строка} т/ч): кандидат на роль темпа потока", "узкое место пропускной способности")
        r["расчёты"].append(f"min(Пр) = «{имя}» ({fmt(пр)} т/ч) — темп потока")
    elif пр_ops:
        r["домерить"].append("производительность хотя бы по 2 операциям → детектор темпа потока")

    # --- Детектор 3: доля блока в ВПП (первый и второй эшелоны) ---
    впп_итого = d.get("впп_итого_сек")
    if впп_итого:
        for op in ops:
            if op.get("впп_сек"):
                доля = op["впп_сек"] / впп_итого * 100
                r["доли_впп"].append((op["имя"], op["впп_сек"], доля))
        r["доли_впп"].sort(key=lambda t: -t[2])
        for имя, сек, доля in r["доли_впп"]:
            if доля > POROG_DOLYA_VPP_PCT:
                кандидат(имя, "доля ВПП",
                         f"ВПП блока {сек} сек = {fmt(доля)} % всего ВПП потока "
                         f"({впп_итого} сек) — крупный резерв времени",
                         "концентрация времени в блоке")
            elif доля >= POROG_DOLYA_VPP_2_PCT:
                кандидат(имя, "доля ВПП (эшелон 2)",
                         f"ВПП блока {сек} сек = {fmt(доля)} % ВПП потока — резерв времени",
                         "концентрация времени в блоке")
        if r["доли_впп"]:
            r["расчёты"].append(
                "Доли ВПП: " + "; ".join(f"«{n}» {fmt(dl)} %" for n, _, dl in r["доли_впп"][:3])
                + f" (ВПП итого {впп_итого} сек)")
    elif any(op.get("впп_сек") for op in ops):
        r["домерить"].append("ВПП итого по потоку → доли блоков")

    # --- Детектор 4: переделка / возврат ---
    for op in ops:
        if op.get("возврат_пкт"):
            кандидат(op["имя"], "переделка",
                     f"возврат {fmt(op['возврат_пкт'], 0)} % продукции на повторную "
                     f"обработку — скрытый параллельный поток брака",
                     "переделка (брак/возврат)")
            r["расчёты"].append(f"Переделка: «{op['имя']}» — возврат "
                                f"{fmt(op['возврат_пкт'], 0)} %")

    # --- ВПП тактового потока (ф. 5.5) ---
    нзп = sum(op.get("запас_перед_шт") or 0 for op in ops)
    if нзп and tt is not None and tc_ops:
        um = max(tc_ops, key=lambda o: o["тц_мин"])
        база = um["тц_мин"] if abs(um["тц_мин"] - tt) / tt * 100 > POROG_DISBALANS_PCT else tt
        впп = нзп * база
        r["впп_мин"] = впп
        r["расчёты"].append(f"ВПП = ΣНЗП × {'Тц узк. места' if база != tt else 'Тт'} = "
                            f"{нзп} × {fmt(база)} = {fmt(впп)} мин (ф. 5.5)")

    # --- Точечные замеры (выработка, Тож, спагетти) ---
    for z in d.get("точечные_замеры") or []:
        if z.get("выпуск_шт") and z.get("персонал") and z.get("смена_ч"):
            фов = z["персонал"] * z["смена_ч"]
            впр = z["выпуск_шт"] / фов
            r.setdefault("выработка", []).append(
                {"замер": z["имя"], "значение": впр,
                 "расчёт": f"ВПпр = {z['выпуск_шт']} / ({z['персонал']} × {z['смена_ч']}) "
                           f"= {fmt(впр)} шт/чел·ч"})
        if z.get("запас_шт") and z.get("производительность_шт_ч"):
            тоз = z["запас_шт"] / z["производительность_шт_ч"]
            r.setdefault("тож", []).append(
                {"замер": z["имя"], "значение": тоз,
                 "расчёт": f"Тож = {z['запас_шт']} / {z['производительность_шт_ч']} "
                           f"= {fmt(тоз)} ч (ф. 5.2)"})
            кандидат(z["имя"], "запас→ожидание",
                     f"запас {z['запас_шт']} шт = {fmt(тоз)} ч ожидания",
                     "ожидание (межоперационный запас)")
        if z.get("время_сек") and z.get("расстояние_м"):
            r["спагетти"].append(z)

    # --- Оборачиваемость ГП ---
    zd = d.get("запасы_деньги") or {}
    if zd.get("гп_кон_тыс") and zd.get("реализация_тыс_мес"):
        оз = zd["гп_кон_тыс"] * 30 / zd["реализация_тыс_мес"]
        r["оборачиваемость_дн"] = оз
        r["расчёты"].append(f"ОЗ = Зкон × 30 / Рмес = {zd['гп_кон_тыс']} × 30 / "
                            f"{zd['реализация_тыс_мес']} = {fmt(оз)} дн (ф. 7.3/7.4)")
    else:
        r["домерить"].append("запасы ГП в деньгах и реализация за месяц → оборачиваемость")

    # --- Вердикт кросс-детектора ---
    if r["кандидаты"]:
        ранж = sorted(r["кандидаты"].items(), key=lambda kv: -len(kv[1]["детекторы"]))
        r["ранжирование"] = ранж
        гл_имя, гл = ранж[0]
        r["главное"] = {"имя": гл_имя, "детекторов": len(гл["детекторы"]),
                        "сошлось": len(гл["детекторы"]) >= 2}
        if r["главное"]["сошлось"]:
            r["расчёты"].append(
                f"Главное узкое место: «{гл_имя}» — подтверждено {len(гл['детекторы'])} "
                f"независимыми детекторами: {', '.join(гл['детекторы'])}")
    return r


def otchyot(d, r):
    статус = ("нет пробелов в данных" if not r["домерить"]
              else f"есть пробелы в данных ({len(r['домерить'])} {пунктов(len(r['домерить']))})")
    L = [f"# Поиск узкого места · {d.get('поток', 'поток')}",
         f"**Статус: {статус}**",
         f"Дата прогона: {date.today().isoformat()} · инструмент v0.3 (детерминированный)", ""]
    # 1. Базовые параметры
    L.append("## 1. Базовые параметры потока")
    L.append(f"- Тт: {fmt(r['тт']) + ' мин' if r.get('тт') else 'нет данных (домерить)'}")
    ops = d.get("операции") or []
    тц_сумма = sum(o["тц_мин"] for o in ops if o.get("тц_мин"))
    L.append(f"- Операций с Тц: {sum(1 for o in ops if o.get('тц_мин'))} из {len(ops)}; "
             f"ΣТц = {fmt(тц_сумма)} мин")
    if d.get("впп_итого_сек"):
        L.append(f"- ВПП итого (вход): {d['впп_итого_сек']} сек")
    if d.get("персонал_итого"):
        L.append(f"- Персонал потока: {d['персонал_итого']} чел.")
    if r.get("базис_предупр"):
        L.append(f"- ⚠ {r['базис_предупр']}")
    L.append("")
    # 2. Ранжирование
    L.append("## 2. Ранжированный список узких мест (кросс-детектор)")
    if r.get("главное"):
        гл = r["главное"]
        L.append(f"**ГЛАВНОЕ УЗКОЕ МЕСТО: «{гл['имя']}»** — "
                 f"{'подтверждено ' + str(гл['детекторов']) + ' детекторами' if гл['сошлось'] else 'ОДИН детектор (слабое подтверждение — домерить)'}")
        for i, (имя, к) in enumerate(r["ранжирование"], 1):
            L.append(f"{i}. **{имя}** [{', '.join(к['детекторы'])}]")
            for док in к["доказательства"]:
                L.append(f"   - {док}")
            L.append(f"   - тип потери: {', '.join(sorted(set(к['типы'])))}")
    else:
        L.append("- кандидатов нет: данных недостаточно (см. раздел 6)")
    L.append("")
    # 3. Дисбаланс
    L.append("## 3. Дисбаланс тактовой линии")
    if r.get("дисбаланс"):
        L.append(f"**{r['дисбаланс']['вердикт']}** — {r['дисбаланс']['расчёт']}")
    else:
        L.append("- не вычисляется: нет Тт (домерить спрос/время)")
    L.append("")
    # 4. ВПП и доля ценности
    L.append("## 4. ВПП и доли блоков")
    if r.get("впп_мин"):
        L.append(f"- ВПП тактового потока (ф. 5.5): **{fmt(r['впп_мин'])} мин**")
    if r.get("доли_впп"):
        L.append(f"- ВПП итого: {сек_ч(d['впп_итого_сек'])}; доли блоков:")
        for имя, сек, доля in r["доли_впп"][:5]:
            L.append(f"  - «{имя}»: {сек_ч(сек)} = {fmt(доля)} %")
    if not r.get("впп_мин") and not r.get("доли_впп"):
        L.append("- нет данных")
    L.append("")
    # 5. Показатели по замерам
    L.append("## 5. Показатели по точечным замерам")
    пр_ops = [(op["имя"], op["производительность_т_ч"]) for op in ops
              if op.get("производительность_т_ч")]
    if пр_ops:
        L.append("- Производительности (использованы детектором темпа): "
                 + "; ".join(f"«{n}» {fmt(p)} т/ч" for n, p in пр_ops))
    for v in r.get("выработка", []):
        L.append(f"- Выработка «{v['замер']}»: **{fmt(v['значение'])} шт/чел·ч**")
    for t in r.get("тож", []):
        L.append(f"- Время ожидания «{t['замер']}»: **{fmt(t['значение'])} ч**")
    if r.get("оборачиваемость_дн"):
        L.append(f"- Оборачиваемость ГП: **{fmt(r['оборачиваемость_дн'])} дн**")
    if r.get("спагетти"):
        итого = next((z for z in r["спагетти"] if "ИТОГО" in z["имя"].upper()), None)
        if итого:
            L.append(f"- Перемещения (спагетти, текущее): {итого['расстояние_м']} м / "
                     f"{итого['время_сек']} сек суммарно — кандидат на потерю «транспортировка»")
    if not (пр_ops or r.get("выработка") or r.get("тож") or r.get("оборачиваемость_дн")):
        L.append("- нет точечных замеров в вычислимом виде")
    L.append("")
    # 6. Домерить
    L.append("## 6. Каких данных не хватает (что домерить)")
    if r["домерить"]:
        for x in r["домерить"]:
            L.append(f"- {x}")
    else:
        L.append("- ничего, вход полный по текущей спеке")
    L.append("")
    # 7. Расчёты
    L.append("## 7. Расчёты (как считали)")
    for x in r["расчёты"]:
        L.append(f"- {x}")
    for v in r.get("выработка", []) + r.get("тож", []):
        L.append(f"- {v['расчёт']}")
    L.append("")
    L.append("> Границы: только диагностика. Мероприятия не предлагаются (спека № 1, п. 7).")
    return "\n".join(L)


def main():
    if len(sys.argv) != 2:
        sys.exit("Запуск: python3 узкие_места.py <данные.json>")
    with open(sys.argv[1], encoding="utf-8") as f:
        d = json.load(f)
    oshibki = proverit_vhod(d)
    if oshibki:
        sys.exit("Ошибки входа:\n" + "\n".join(f"- {e}" for e in oshibki))
    print(otchyot(d, razbor(d)))


if __name__ == "__main__":
    main()
