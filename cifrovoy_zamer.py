def skelet():
    """Структура чек-листа для UI (GET /api/zamer/skelet): блоки, вопросы,
    варианты с весами + названия шагов."""
    return {"ok": True,
            "блоки": ЧЕКЛИСТ,
            "шаги": [{"shag": s, "nazvanie": ШАГИ_НАЗВАНИЯ[s]}
                     for s in (-1, 0, 1, 2)],
            "вопросов": len(_ВОПРОСЫ)}


def validirovat(вход):
    """Проверка входа: объект; все вопросы отвечены; id вариантов валидны."""
    ошибки = []
    if not isinstance(вход, dict):
        return ["вход должен быть JSON-объектом {«ответы»: {вопрос: вариант}}"]
    ответы = вход.get("ответы")
    if not isinstance(ответы, dict):
        return ["во входе нет объекта «ответы» {id вопроса: id варианта}"]
    for блок in ЧЕКЛИСТ:
        for в in блок["voprosy"]:
            выб = ответы.get(в["id"])
            if выб is None:
                ошибки.append(f"блок «{блок['nazvanie']}»: нет ответа на "
                              f"вопрос «{в['текст'][:60]}…»")
            elif выб not in {x["id"] for x in в["варианты"]}:
                ошибки.append(f"вопрос «{в['id']}»: неизвестный вариант "
                              f"«{выб}»")
    лишние = set(ответы) - set(_ВОПРОСЫ)
    if лишние:
        ошибки.append("неизвестные вопросы в «ответы»: "
                      + ", ".join(sorted(лишние)))
    return ошибки


def raschet(вход):
    """Баллы по блокам → итоговый шаг (худший блок) + узкий блок +
    рекомендации цифровой ветки по итоговому шагу."""
    ответы = вход.get("ответы") or {}
    блоки = []
    for блок in ЧЕКЛИСТ:
        детали = []
        for в in блок["voprosy"]:
            выб_id = ответы.get(в["id"])
            вариант = next((x for x in в["варианты"] if x["id"] == выб_id),
                           None)
            детали.append({"vopros_id": в["id"],
                           "vopros": в["текст"],
                           "variant_id": выб_id,
                           "variant": вариант["текст"] if вариант else None,
                           "ves": вариант["вес"] if вариант else None})
        веса = [д["ves"] for д in детали if д["ves"] is not None]
        шаг_блока = min(веса) if веса else None
        блоки.append({"id": блок["id"], "nazvanie": блок["nazvanie"],
                      "shag": шаг_блока,
                      "shag_nazvanie": ШАГИ_НАЗВАНИЯ.get(шаг_блока),
                      "voprosy": детали,
                      "сумма_весов": sum(веса) if веса else None,
                      "мин_шаг_вопрос": min(
                          (д for д in детали if д["ves"] == шаг_блока),
                          key=lambda д: д["vopros_id"])["vopros"]
                      if шаг_блока is not None else None})
    шаги_блоков = [б["shag"] for б in блоки if б["shag"] is not None]
    итог = min(шаги_блоков) if шаги_блоков else None
    узкий = next((б for б in блоки if б["shag"] == итог), None)
    рекомендации = []
    for ин_id in РЕКОМЕНДАЦИИ_ПО_ШАГУ.get(итог, []):
        ин = ЦИФРОВЫЕ_ПО_ID.get(ин_id)
        if ин:
            рекомендации.append({"id": ин["id"],
                                 "instrument": ин["instrument"],
                                 "shag": ин["shag"],
                                 "uslovie_primenimosti":
                                     ин["uslovie_primenimosti"]})
    return {"shag_gotovnosti": итог,
            "shag_nazvanie": ШАГИ_НАЗВАНИЯ.get(итог),
            "uzkiy_blok": ({"id": узкий["id"], "nazvanie": узкий["nazvanie"],
                            "shag": узкий["shag"],
                            "min_vopros": узкий["мин_шаг_вопрос"]}
                           if узкий else None),
            "bloki": блоки,
            "rekomendacii": рекомендации,
            "предприятие": вход.get("предприятие") or None,
            "метод": ("итоговый шаг = худший блок (философия узкого места); "
                      "шаг блока = худший ответ блока; рекомендации — "
                      "мероприятия цифровой ветки итогового шага")}


def итоги_zamer(вход, r):
    """Сводка прогона замера для реестра progony (контракт итогов)."""
    return {"предприятие": вход.get("предприятие") or None,
            "shag_gotovnosti": r["shag_gotovnosti"],
            "shag_nazvanie": r["shag_nazvanie"],
            "узкий_блок": (r["uzkiy_blok"] or {}).get("nazvanie"),
            "шаги_блоков": {б["nazvanie"]: б["shag"] for б in r["bloki"]},
            "рекомендаций": len(r["rekomendacii"]),
            "рекомендации": [р["instrument"] for р in r["rekomendacii"]]}


def отчёт_zamer_md(вход, r):
    """Markdown-сводка прогона замера (для progony.отчёт_md), по паттерну
    скоринг-карты отбора."""
    предприятие = вход.get("предприятие") or "____"
    L = [f"# Цифровой замер · {предприятие}", ""]
    шаг = r["shag_gotovnosti"]
    L.append(f"**Итоговый шаг готовности: {шаг} — «{r['shag_nazvanie']}»** "
             f"(по худшему блоку — философия узкого места).")
    уз = r.get("uzkiy_blok") or {}
    L.append(f"**Узкий блок:** «{уз.get('nazvanie', '—')}»"
             + (f" — тащит вниз ответ «{уз['min_vopros'][:70]}…»"
                if уз.get("min_vopros") else ""))
    L.append("")
    L.append("## Баллы по блокам")
    for б in r["bloki"]:
        L.append(f"- **{б['nazvanie']}** — шаг {б['shag']} "
                 f"«{б['shag_nazvanie']}»")
        for д in б["voprosy"]:
            L.append(f"  - {д['vopros']} — _{д['variant']}_ "
                     f"(вес {д['ves']})")
    L.append("")
    L.append("## Рекомендации (мероприятия цифровой ветки итогового шага)")
    for р in r["rekomendacii"]:
        L.append(f"- **{р['instrument']}** (шаг {р['shag']}): "
                 f"условие применимости — {р['uslovie_primenimosti']}")
    L.append("")
    L.append("> Следующий шаг: передать шаг готовности в генератор "
             "мероприятий (карточка «План мероприятий», поле «Шаг из "
             "замера») — цифровые мероприятия выше шага будут скрыты "
             "с записью в отчёт.")
    return "\n".join(L)


