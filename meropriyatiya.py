def _kvant(value=None, unit=None, evidence="gap", замер=None):
    """Квантификация ветки/шага с evidence-классом. gap → рекомендация замера."""
    k = {"value": value, "unit": unit, "evidence": evidence}
    if evidence == "gap":
        ключ = замер or "хронометраж"
        з = ИНСТРУМЕНТЫ_ЗАМЕРА[ключ]
        k["нужен_замер"] = {
            "instrument": з["nazvanie"],
            "kurs_fck": з["kurs_fck"],
            "dlya": з["dlya"],
        }
    return k


def _шаг_5почему(n, вопрос, ответ, evidence, замер=None):
    шаг = {"n": n, "vopros": вопрос, "otvet": ответ, "evidence": evidence}
    if evidence == "gap":
        з = ИНСТРУМЕНТЫ_ЗАМЕРА[замер or "хронометраж"]
        шаг["нужен_замер"] = {"instrument": з["nazvanie"],
                              "kurs_fck": з["kurs_fck"], "dlya": з["dlya"]}
    return шаг


