def сгенерировать(vhod):
    """Контракт раздела 3 спеки + ключ qc. Ломтик 2: шаг 5 — квантификация
    и ранжирование мероприятий (ΔВПП, Δвыработка, ΔПТ, ΔЭЭ через
    ЭЭ-калькулятор, трудоёмкость, риски, prioritet по матрице Прил. 8).
    Ломтик 3: шаг 6 — plan по шаблону Прил. 4 (sobrat_plan)."""
    problema = сформировать_проблему(vhod)
    vetki = построить_дерево(vhod, problema)
    prichiny = найти_причины(vhod, problema, vetki)
    meropriyatiya = подобрать_мероприятия(prichiny)
    # Фильтр замера готовности (Протокол № 43, п. 2): если во входе задан
    # shag_gotovности (−1/0/1/2 — результат «Цифрового замера»), цифровые
    # мероприятия с шагом выше допустимого исключаются с записью в отчёт.
    shag_gotovnosti = vhod.get("shag_gotovnosti")
    скрытые = []
    if shag_gotovnosti is not None:
        if (type(shag_gotovnosti) is not int
                or shag_gotovnosti not in (-1, 0, 1, 2)):
            raise ValueError("поле «shag_gotovnosti» — только целые −1, 0, 1 "
                             "или 2 (шаг из инструмента «Цифровой замер»)")
        оставленные = []
        for м in meropriyatiya:
            if м.get("shag") is not None and м["shag"] > shag_gotovnosti:
                скрытые.append(м)
            else:
                оставленные.append(м)
        meropriyatiya = оставленные
    meropriyatiya = kvantifitsirovat(vhod, problema, meropriyatiya)
    meropriyatiya = rangirovat(meropriyatiya, vhod)
    plan = sobrat_plan(vhod, meropriyatiya, problema)
    result = {
        "problema": problema,
        "vetki": vetki,
        "prichiny": prichiny,
        "meropriyatiya": meropriyatiya,
        "plan": plan,        # ломтик 3: шаблон Прил. 4
        "shag_gotovnosti": shag_gotovnosti,
        # «скрыто замером готовности: …» — список исключённых цифровых
        "skrytye_zamerom_gotovnosti": [м["instrument"] for м in скрытые],
    }
    if vhod.get("ekonomika") is not None:
        result["_vhod_ekonomika"] = copy.deepcopy(vhod["ekonomika"])
    result["qc"] = proverit_qc(result)
    result.pop("_vhod_ekonomika", None)  # служебный ключ, в прогон не идёт
    return copy.deepcopy(result)
