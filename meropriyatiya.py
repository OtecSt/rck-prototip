def сформировать_проблему(vhod):
    """Правило ФЦК: факт (что), где, сколько (разрыв от нормы/такта),
    последствие. Курс-эталон: «Определение и формулирование проблем»."""
    участок = (vhod.get("uchastok") or "").strip()
    if not участок:
        raise ValueError("во входе нет «uchastok» (участок / УМ)")
    vpp = vhod.get("vpp_pct")
    if vpp is None:
        raise ValueError("во входе нет «vpp_pct» (% ВПП на УМ)")
    норма = vhod.get("norma_vpp_pct")
    разрыв_вх = vhod.get("razryv")
    if разрыв_вх is None and норма is not None:
        разрыв_вх = {"value": round(vpp - норма, 1), "unit": "п.п. ВПП",
                     "evidence": "fact" if vhod.get("razryv_fakt", True)
                     else "assumption"}
    if разрыв_вх is not None:
        ev = разрыв_вх.get("evidence", "assumption")
        сколько = f"разрыв {разрыв_вх['value']} {разрыв_вх.get('unit', '')}".strip()
    else:
        ev = "gap"
        сколько = "разрыв от нормы не замерен"
    факт = (f"Узкое место потока — участок «{участок}»: время вспомогательных "
            f"процессов (ВПП) составляет {str(vpp).replace('.', ',')} % "
            f"сменного времени")
    последствие = ("участок ограничивает выработку всего потока: каждый "
                   "процент ВПП на УМ — прямая потеря производительности "
                   "труда потока")
    формулировка = f"{факт}; {сколько}; последствие: {последствие}."
    problema = {"uchastok": участок,
                "fakt": формулировка,
                "vpp_pct": vpp,
                "razryv": (разрыв_вх["value"] if разрыв_вх else None),
                "razryv_unit": (разрыв_вх.get("unit") if разрыв_вх else None),
                "posledstvie": последствие,
                "evidence": ev,
                "kurs_etalon": "Определение и формулирование проблем"}
    if ev == "gap":
        з = ИНСТРУМЕНТЫ_ЗАМЕРА["фотография_рабочего_дня"]
        problema["нужен_замер"] = {"instrument": з["nazvanie"],
                                   "kurs_fck": з["kurs_fck"],
                                   "dlya": "разрыв ВПП от нормы/такта"}
    return problema


