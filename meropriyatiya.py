def итоги_мероприятия(progon):
    """Сводка прогона генератора мероприятий для реестра progony
    (аналог итоги_akt / итоги протокола). На вход — результат сгенерировать()."""
    мсп = progon.get("meropriyatiya") or []
    план = progon.get("plan") or []
    qc = progon.get("qc") or []
    return {
        "предприятие": None,  # заполняется из входа на стороне UI (ломтик 4)
        "участок": (progon.get("problema") or {}).get("uchastok"),
        "vpp_pct": (progon.get("problema") or {}).get("vpp_pct"),
        "razryv_pp": (progon.get("problema") or {}).get("razryv"),
        "веток": len(progon.get("vetki") or []),
        "причин": len(progon.get("prichiny") or []),
        "мероприятий": len(мсп),
        "план_записей": len(план),
        "сумма_dVPP_pp": round(sum(м["dVPP_pp"] for м in мсп
                                   if м.get("dVPP_pp") is not None), 2),
        "сумма_dPT_pct": round(sum(м["dPT_pct"] for м in мсп
                                   if м.get("dPT_pct") is not None), 2),
        "сумма_dEE_rub": round(sum(м["dEE_rub"] for м in мсп
                                   if м.get("dEE_rub") is not None), 2),
        "класс_A": sum(1 for м in мсп
                       if (м.get("matritsa") or {}).get("prioritet_klass") == "A"),
        "класс_B": sum(1 for м in мсп
                       if (м.get("matritsa") or {}).get("prioritet_klass") == "B"),
        "класс_C": sum(1 for м in мсп
                       if (м.get("matritsa") or {}).get("prioritet_klass") == "C"),
        "gap_замеров": sum(
            1 for в in (progon.get("vetki") or [])
            if (в.get("kvant") or {}).get("evidence") == "gap"),
        "shag_gotovnosti": progon.get("shag_gotovnosti"),
        "скрыто_замером_готовности":
            len(progon.get("skrytye_zamerom_gotovnosti") or []),
        "qc_замечаний": len(qc),
        "qc_pass": len(qc) == 0,
    }


