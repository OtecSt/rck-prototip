_EVIDENCE_КЛАССЫ = {"fact", "assumption", "gap"}


def proverit_qc(result):
    """QC-гейты ломтика 1. Возвращает список нарушений (пустой = pass):
      1) сумма ΔВПП (квантифицированных) веток ≤ разрыва УМ;
      2) каждое мероприятие привязано к причине;
      3) у каждого шага «5 почему» есть класс evidence;
      4) у каждой ветки/проблемы класс evidence из {fact, assumption, gap}."""
    нарушения = []

    # Гейт 1: сумма квантов веток ≤ разрыва УМ (только совместимые единицы)
    разрыв = result["problema"].get("razryv")
    unit_разрыв = result["problema"].get("razryv_unit")
    сумма, найдены = 0.0, False
    for в in result["vetki"]:
        k = в.get("kvant") or {}
        if k.get("value") is not None and k.get("unit") == unit_разрыв:
            сумма += k["value"]
            найдены = True
    if найдены and разрыв is not None and сумма > разрыв + 1e-9:
        нарушения.append(
            f"сумма ΔВПП веток {round(сумма, 2)} {unit_разрыв} превышает "
            f"разрыв УМ {разрыв} {unit_разрыв} — структура потерь "
            f"несогласована с проблемой")

    # Гейт 2: каждое мероприятие привязано к причине
    корни = {п["koren"] for п in result["prichiny"] if п.get("koren")}
    for i, м in enumerate(result["meropriyatiya"], 1):
        if not м.get("prichina") or м["prichina"] not in корни:
            нарушения.append(f"мероприятие #{i} («{м.get('instrument')}») не "
                             f"привязано к причине из карты причин")
        if not м.get("kurs_fck") and м.get("semya") != ЦИФРОВАЯ_СЕМЬЯ:
            нарушения.append(f"мероприятие #{i} («{м.get('instrument')}») без "
                             f"ссылки на курс ФЦК")

    # Гейт 3: у каждого шага «5 почему» есть класс evidence
    for п in result["prichiny"]:
        for шаг in п.get("cep_5pochemu", []):
            if шаг.get("evidence") not in _EVIDENCE_КЛАССЫ:
                нарушения.append(
                    f"причина «{(п.get('koren') or п['vetka'])[:50]}…»: шаг "
                    f"«5 почему» № {шаг.get('n')} без класса evidence")

    # Гейт 4: evidence-классы проблемы и веток
    if result["problema"].get("evidence") not in _EVIDENCE_КЛАССЫ:
        нарушения.append("у проблемы нет корректного класса evidence")
    for в in result["vetki"]:
        if (в.get("kvant") or {}).get("evidence") not in _EVIDENCE_КЛАССЫ:
            нарушения.append(f"ветка «{в['poterya'][:50]}…»: квант без "
                             f"класса evidence")
        if (в.get("kvant") or {}).get("evidence") == "gap" \
                and "нужен_замер" not in в["kvant"]:
            нарушения.append(f"ветка «{в['poterya'][:50]}…»: gap без "
                             f"рекомендации инструмента замера")

    # Гейт 5 (ломтик 2): сумма ΔВПП мероприятий ≤ разрыва УМ
    сумма_м = sum(м["dVPP_pp"] for м in result["meropriyatiya"]
                  if м.get("dVPP_pp") is not None)
    if разрыв is not None and сумма_м > разрыв + 1e-9:
        нарушения.append(
            f"сумма ΔВПП мероприятий {round(сумма_м, 2)} п.п. превышает "
            f"разрыв УМ {разрыв} п.п. — нормировка шага 5 нарушена")

    # Гейт 6 (ломтик 2): ΔЭЭ мероприятий согласовано с ЭЭ-калькулятором —
    # пересчитываем той же связкой суммарный ΔВПП и сверяем: сумма
    # помероприятийных ΔЭЭ не должна превышать ΔЭЭ пакета (допуск 1 %)
    # на случай нелинейности модели (МР ЭЭ ред. 4 — методика та же).
    квант_ээ = [м for м in result["meropriyatiya"]
                if м.get("dEE_rub") is not None and м.get("dVPP_pp")
                # ΔЭЭ из типового диапазона цифровой ветки (обеспечивающие
                # процессы) не сравнивается с ЭЭ-калькулятором УМ — другая
                # методика, помечена источником в dEE_istochnik
                and not (_запись_библиотеки(м["prichina_tip"], м["instrument"])
                         or {}).get("dEE_diapazon")]
    if квант_ээ and result.get("_vhod_ekonomika") is not None:
        vpp = result["problema"]["vpp_pct"]
        сумма_pp = sum(м["dVPP_pp"] for м in квант_ээ)
        dТ_пакет = сумма_pp / (100.0 - vpp) if vpp < 100 else 0.0
        ээ_пакет, причина = _ээ_через_калькулятор(result["_vhod_ekonomika"],
                                                  dТ_пакет)
        if ээ_пакет is not None:
            сумма_ээ = sum(м["dEE_rub"] for м in квант_ээ)
            if сумма_ээ > ээ_пакет * 1.01 + 0.01:
                нарушения.append(
                    f"сумма ΔЭЭ мероприятий {round(сумма_ээ, 2)} руб/год "
                    f"превышает ΔЭЭ пакета по ЭЭ-калькулятору "
                    f"{round(ээ_пакет, 2)} руб/год — методики разошлись")
        else:
            нарушения.append("QC: пересчёт ΔЭЭ пакета через ЭЭ-калькулятор "
                             f"не удался: {причина}")

    # Гейт 7 (ломтик 3): план заполнен по шаблону Прил. 4
    план = result.get("plan") or []
    if len(план) != len(result["meropriyatiya"]):
        нарушения.append(f"записей плана {len(план)} ≠ мероприятий "
                         f"{len(result['meropriyatiya'])}")
    for з in план:
        for кол in _КОЛОНКИ_ПЛАНА:
            # dEE_rub может быть None без секции «ekonomika» во входе —
            # это легитимный пробел (dEE_gap), а не нарушение шаблона
            if кол == "dEE_rub":
                continue
            if з.get(кол) is None:
                нарушения.append(f"план, запись № {з.get('n')}: пустая "
                                 f"обязательная колонка «{кол}»")
    ранги_плана = [з.get("prioritet") for з in план]
    if ранги_плана != sorted(r for r in ранги_плана if r is not None) and \
            len(план) > 1:
        нарушения.append("план не отсортирован по prioritet")

    # Сверка ссылок на курсы с каталогом (контроль целостности библиотеки)
    for н in proverit_kursy():
        нарушения.append("каталог курсов: " + н)
    return нарушения


