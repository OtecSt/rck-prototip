def _ээ_через_калькулятор(ekonomika, dТ_доля):
    """ΔЭЭ мероприятия через модуль ээ_калькулятор (МР ЭЭ ред. 4,
    модель ФЦК v5.2): состояние «до» = ekonomika как есть, «после» —
    фактическое время выросло на dТ_доля (снятая доля ВПП). Возвращает
    (ээ_руб_год, пояснение) или (None, причина)."""
    ee_kalk = _загрузить_ээ_калькулятор()
    if ee_kalk is None:
        return None, "модуль ээ_калькулятор.py не найден рядом с Прототипом"
    требуемые = ("тцикл_мин", "ттакт_мин", "цена_ед", "перем_сс_ед")
    if any(k not in ekonomika for k in требуемые) or (
            ekonomika.get("время_мин_год") is None
            and ekonomika.get("фонд_времени") is None):
        return None, ("во входе «ekonomika» не хватает полей ЭЭ-калькулятора "
                      "(тцикл_мин, ттакт_мин, фонд времени, цена_ед, "
                      "перем_сс_ед)")
    до = copy.deepcopy(ekonomika)
    после = copy.deepcopy(ekonomika)
    # «После»: время производства годной продукции выросло на dТ_доля
    # (Орп = Т / Тцикл, МР ЭЭ ред. 4, п. 6.6.1.3.1)
    if после.get("время_мин_год") is not None:
        т1 = после["время_мин_год"]["до"]
        после["время_мин_год"] = {"до": т1, "после": т1 * (1.0 + dТ_доля)}
    else:
        ф = после["фонд_времени"]
        после["фонд_времени"] = dict(ф)
        после["время_мин_год"] = {
            "до": ф["смены"] * ф["часы"] * ф["дни"] * 60,
            "после": ф["смены"] * ф["часы"] * ф["дни"] * 60 * (1.0 + dТ_доля),
        }
        del после["фонд_времени"]
    до["время_мин_год"] = после["время_мин_год"] and {
        "до": после["время_мин_год"]["до"],
        "после": после["время_мин_год"]["до"],
    }
    if до.get("фонд_времени"):
        del до["фонд_времени"]
    ошибки = ee_kalk.validirovat(после)
    if ошибки:
        return None, "вход «ekonomika» не прошёл валидацию ЭЭ-калькулятора: " \
                     + "; ".join(ошибки)
    r_до = ee_kalk.raschet(до)
    r_после = ee_kalk.raschet(после)
    if r_до.get("отказ") or r_после.get("отказ"):
        return None, "ЭЭ-калькулятор отказал: " + str(
            r_до.get("отказ") or r_после.get("отказ"))
    if "ээ" not in r_до or "ээ" not in r_после:
        return None, "ЭЭ-калькулятор не вычислил ЭЭ (неполный вход)"
    return round(r_после["ээ"] - r_до["ээ"], 2), None


def kvantifitsirovat(vhod, problema, meropriyatiya):
    """Шаг 5а. Каждое мероприятие получает ΔВПП (п.п. и мин/смену), Δвыработку,
    ΔПТ (% и вклад в цель +5 %/год), ΔЭЭ (руб./год — связка с
    ээ_калькулятор.py), трудоёмкость и риски.
    Нормировка: если сумма средних ΔВПП превышает разрыв УМ, все ΔВПП
    масштабируются пропорционально (QC-гейт «Σ ΔВПП ≤ разрыва»)."""
    разрыв = problema.get("razryv")  # п.п. ВПП
    vpp = problema.get("vpp_pct")
    смена_мин = vhod.get("smena_min")  # допущение: 480 мин, если не задано
    if смена_мин is None:
        смена_мин = 480.0
        источник_смены = "допущение: смена 8 ч × 60 мин (вход smena_min не задан)"
    else:
        источник_смены = "вход smena_min"
    ekonomika = vhod.get("ekonomika")
    цель_пт = vhod.get("cel_pt_pct", 5.0)  # цель +5 % ПТ в год (нацпроект)

    # Базовые ΔВПП — середина типового диапазона библиотеки
    базовые = []
    for м in meropriyatiya:
        диап = None
        for ин in БИБЛИОТЕКА[м["prichina_tip"]]:
            if ин["instrument"] == м["instrument"]:
                диап = ин["dVPP_diapazon"]
                break
        базовые.append((диап["min"] + диап["max"]) / 2.0 if диап else 0.0)
    сумма = sum(базовые)
    масштаб = 1.0
    if разрыв is not None and сумма > разрыв > 0:
        масштаб = разрыв / сумма  # нормировка под разрыв УМ

    for м, база in zip(meropriyatiya, базовые):
        ин_запись = _запись_библиотеки(м["prichina_tip"], м["instrument"])
        диап = ин_запись["dVPP_diapazon"]
        dVPP_pp = round(база * масштаб, 2)
        м["_dvpp_tipovoy_pp"] = база  # типовой эффект (для матрицы Прил. 8)
        if масштаб < 1.0:
            база_поясн = (f"середина диапазона {диап['min']}–{диап['max']} п.п., "
                          f"нормирована ×{round(масштаб, 3)} под разрыв УМ "
                          f"{разрыв} п.п.")
        else:
            база_поясн = f"середина диапазона {диап['min']}–{диап['max']} п.п."
        dVPP_min = round(dVPP_pp / 100.0 * смена_мин, 1)
        # ΔПТ % = ΔТ / Т_полезн = dVPP_pp / (100 − ВПП): формула Орп = Т/Тцикл
        # (МР ЭЭ ред. 4, п. 6.6.1.3.1); ΔПТ = ΔV при неизменной численности
        # (допущение по разбору УЗГО «Расчет ЭЭ.docx»).
        dТ_доля = dVPP_pp / (100.0 - vpp) if vpp is not None and vpp < 100 else 0.0
        dPT_pct = round(dТ_доля * 100.0, 2)
        # Δвыработка, ед/смену = ΔВПП_мин / Тцикл УМ (та же формула Орп=Т/Тцикл)
        тцикл = (ekonomika or {}).get("тцикл_мин", {})
        тцикл_до = тцикл.get("до") if isinstance(тцикл, dict) else None
        if тцикл_до:
            dвыработка = round(dVPP_min / тцикл_до, 2)
            dTc = {"d_vyrabotka_ed_smenu": dвыработка,
                   "istochnik": "Орп = Т / Тцикл (МР ЭЭ ред. 4, п. 6.6.1.3.1)"}
        else:
            dTc = {"d_vyrabotka_ed_smenu": None, "evidence": "gap",
                   "нужен_замер": "время цикла УМ (мин) → Δвыработка, ед/смену"}
        dEE_из_диапазона = ин_запись.get("dEE_diapazon")
        if dEE_из_диапазона is not None:
            # Обеспечивающие процессы (Process Mining, RPA): эффект не
            # выражается в ΔВПП узкого места — типовой ΔЭЭ из цифровой
            # ветки с источником, без связки с ЭЭ-калькулятором УМ.
            dEE_rub = round((dEE_из_диапазона["min"] + dEE_из_диапазона["max"])
                            / 2.0, 2)
            ee_причина = None
        else:
            dEE_rub, ee_причина = (None, "во входе нет секции «ekonomika»") \
                if ekonomika is None else _ээ_через_калькулятор(ekonomika, dТ_доля)
        чел_дней = _ТРУДОЗАТРАТЫ_ЧЕЛ_ДНЕЙ[м["instrument"]]
        риск_класс = _РИСК_ПО_ИНСТРУМЕНТУ[м["instrument"]]
        м["dVPP_min"] = dVPP_min
        м["dVPP_pp"] = dVPP_pp
        м["dVPP_obosnovanie"] = (f"{база_поясн}; диапазон: "
                                 f"{диап['istochnik']}")
        м["dTc"] = dTc
        м["dPT_pct"] = dPT_pct
        м["dPT_vklad_cel_pct"] = (round(dPT_pct / цель_пт * 100.0, 1)
                                  if цель_пт else None)
        м["dPT_istochnik"] = ("ΔПТ % = ΔВПП п.п. / (100 − ВПП факт): Орп = Т/Тцикл "
                              "(МР ЭЭ ред. 4, п. 6.6.1.3.1); ΔПТ = ΔV при "
                              "неизменной численности — допущение по разбору "
                              "УЗГО «Расчет ЭЭ.docx»")
        м["dEE_rub"] = dEE_rub
        if dEE_из_диапазона is not None:
            м["dEE_istochnik"] = (
                f"середина типового диапазона ΔЭЭ "
                f"{dEE_из_диапазона['min']:,.0f}–{dEE_из_диапазона['max']:,.0f} "
                f"{dEE_из_диапазона['unit']}: {dEE_из_диапазона['istochnik']}"
                .replace(",", " "))
        elif dEE_rub is not None:
            м["dEE_istochnik"] = ("расчёт модулем ээ_калькулятор.py "
                                  "(МР ЭЭ ред. 4, модель ФЦК v5.2) — связка, "
                                  "не дубль")
        else:
            м["dEE_gap"] = ee_причина
        м["trudoemkost"] = {
            "klass": _класс_трудоёмкости(чел_дней),
            "chel_dnej": чел_дней,
            "istochnik": ("допущение: типовая практика внедрения; пороги "
                          f"≤{_ПОРОГ_ТРУДОЁМКОСТИ[0]} / "
                          f"≤{_ПОРОГ_ТРУДОЁМКОСТИ[1]} чел.-дней"),
        }
        м["riski"] = {
            "klass": риск_класс,
            "opisanie": _ТЕКСТ_РИСКА[риск_класс],
            "istochnik": ("структура — Прил. № 6 МУ-65-2024 «Оценка рисков "
                          "предлагаемых решений»; качественная шкала — "
                          "допущение (шаблон в архиве пустой)"),
        }
    # Пост-проход нормировки: после округления каждого ΔВПП до 0,01 п.п.
    # сумма может превысить разрыв на сотые — избыток снимается из крупнейших
    # мероприятий (QC-гейт «Σ ΔВПП ≤ разрыва» строгий).
    if разрыв is not None:
        избыток = round(sum(м["dVPP_pp"] for м in meropriyatiya
                            if м.get("dVPP_pp")) - разрыв, 2)
        if избыток > 0:
            for м in sorted(meropriyatiya,
                            key=lambda x: x.get("dVPP_pp") or 0,
                            reverse=True):
                if избыток <= 0:
                    break
                if not м.get("dVPP_pp") or м["dVPP_pp"] <= избыток + 0.01:
                    continue
                м["dVPP_pp"] = round(м["dVPP_pp"] - избыток, 2)
                м["dVPP_obosnovanie"] += (
                    f"; минус {str(избыток).replace('.', ',')} п.п. — "
                    "погрешность округления нормировки (Σ ≤ разрыва УМ)")
                избыток = 0.0
    return meropriyatiya


# Матрица приоритезации: эффект × трудоёмкость. Пороги эффекта —
# Прил. № 8 «Матрица приоритезации проблем»: высокое влияние > 5 %,
# низкое < 2 %; ячейки матрицы → класс приоритета A/B/C (там же).
_ПОРОГ_ЭФФЕКТА = (5.0, 2.0)  # п.п. ВПП: высокий / средний / низкий

_МАТРИЦА_ПРИОРИТЕТА = {
    # (эффект, трудоёмкость) → класс (A — делать первым)
    ("высокий", "низкая"): "A",
    ("высокий", "средняя"): "A",
    ("высокий", "высокая"): "B",
    ("средний", "низкая"): "A",
    ("средний", "средняя"): "B",
    ("средний", "высокая"): "C",
    ("низкий", "низкая"): "B",
    ("низкий", "средняя"): "C",
    ("низкий", "высокая"): "C",
}
_КЛАСС_ВЕС = {"A": 0, "B": 1, "C": 2}


def rangirovat(meropriyatiya, vhod=None):
    """Шаг 5б. Класс приоритета по матрице эффект × трудоёмкость (Прил. 8),
    затем сквозное ранжирование: класс A → B → C, внутри класса — по отдаче
    на вложенный чел.-день (ΔЭЭ / чел.-дни; без ЭЭ — ΔВПП п.п. / чел.-дни).
    prioritet = 1 — высший.

    QC-гейт цифровой ветки (Протокол № 43, п. 1): мероприятие семьи
    «цифровые» с shag=2 не поднимается выше класса B без подтверждённой
    окупаемости (поле okupaemost_podtverzhdena во входе; по умолчанию
    False → кап класса B)."""
    def _эффект_класс(м):
        # Класс влияния — по ТИПОВОМУ диапазону инструмента (до нормировки):
        # в терминах Прил. 8 это «влияние на показатель», свойство пары
        # «причина → инструмент», а не нормированная доля в плане.
        pp = м.get("_dvpp_tipovoy_pp") or 0.0
        if pp > _ПОРОГ_ЭФФЕКТА[0]:
            return "высокий"
        if pp >= _ПОРОГ_ЭФФЕКТА[1]:
            return "средний"
        return "низкий"

    def _отдача(м):
        знаменатель = max(м["trudoemkost"]["chel_dnej"], 1)
        if м.get("dEE_rub"):
            return м["dEE_rub"] / знаменатель
        return (м.get("dVPP_pp") or 0.0) * 1000.0 / знаменатель

    for м in meropriyatiya:
        эк = _эффект_класс(м)
        м["matritsa"] = {
            "effekt_klass": эк,
            "trudoemkost_klass": м["trudoemkost"]["klass"],
            "matritsa_klass_bazovyy":
                _МАТРИЦА_ПРИОРИТЕТА[(эк, м["trudoemkost"]["klass"])],
            "istochnik": ("Прил. № 8 «Матрица приоритезации проблем»: пороги "
                          "влияния > 5 % / < 2 %; класс влияния — по типовому "
                          "диапазону инструмента (до нормировки); классы "
                          "A/B/C — квантили ранга (A: верхние 20 %, B: до "
                          "50 %), как в Прил. 8; отдача на вложенный "
                          "чел.-день — вторичная сортировка"),
        }
    упорядоченные = sorted(
        meropriyatiya,
        key=lambda м: (_КЛАСС_ВЕС[м["matritsa"]["matritsa_klass_bazovyy"]],
                       -_отдача(м), м["instrument"]))
    n = len(упорядоченные)
    граница_a = max(1, math.ceil(n * 0.2))   # A: верхние 20 % (Прил. 8)
    граница_b = max(граница_a, math.ceil(n * 0.5))  # B: до 50 % (Прил. 8)
    for ранг, м in enumerate(упорядоченные, 1):
        м["prioritet"] = ранг
        м["matritsa"]["prioritet_klass"] = (
            "A" if ранг <= граница_a else "B" if ранг <= граница_b else "C")
        м.pop("_dvpp_tipovoy_pp", None)  # служебное поле, в прогон не идёт
    # QC-гейт цифровой ветки: shag=2 без подтверждённой окупаемости — кап B
    окупаемость = bool((vhod or {}).get("okupaemost_podtverzhdena"))
    for м in упорядоченные:
        if (м.get("semya") == ЦИФРОВАЯ_СЕМЬЯ and м.get("shag") == 2
                and not окупаемость
                and м["matritsa"]["prioritet_klass"] == "A"):
            м["matritsa"]["prioritet_klass"] = "B"
            м["matritsa"]["qc_gate"] = (
                "кап QC-гейта: ИИ-мероприятие шага 2 без подтверждённой "
                "окупаемости не поднимается выше класса B (Протокол № 43, "
                "п. 1; okupaemost_podtverzhdena во входе = False)")
    return meropriyatiya


