def _дата_iso(д):
    return д.isoformat() if isinstance(д, (_dt.date, _dt.datetime)) else str(д)


def sobrat_plan(vhod, meropriyatiya, problema):
    """Шаг 6. Из квантифицированных мероприятий собирает plan — записи по
    шаблону Прил. 4 (колонки шаблона + показатель до/после, ΔЭЭ, класс
    приоритета, курс ФЦК). Сортировка — по prioritet (п. 1 — высший).

    Ответственный — плейсхолдер из входа (vhod["otvetstvenny"]) или
    «____ (назначается…)». Срок — из входа (vhod["data_nachala_plana"] /
    vhod["sroki"][instrument]) или авто-предложение по трудоёмкости:
    низкая 14 дн., средняя 45 дн., высокая 90 дн. (допущение, помечено)."""
    старт = vhod.get("data_nachala_plana")
    if старт:
        база = _dt.date.fromisoformat(str(старт)[:10])
        источник_сроков = "вход data_nachala_plana"
    else:
        база = _dt.date.today()
        источник_сроков = ("авто-предложение от текущей даты; длительность "
                           "по классу трудоёмкости — допущение (низкая 14 дн., "
                           "средняя 45 дн., высокая 90 дн.)")
    сроки_вх = vhod.get("sroki") or {}
    ответств_вх = (vhod.get("otvetstvenny") or "").strip() or None
    ответств_по_м = vhod.get("otvetstvennye") or {}
    vpp = problema.get("vpp_pct")
    разрыв = problema.get("razryv")

    план = []
    for м in sorted(meropriyatiya, key=lambda x: x.get("prioritet") or 999):
        ин = м["instrument"]
        курс = (м.get("kurs_fck")
                or "вне каталога ФЦК (цифровая ветка, Протокол № 43)")
        ответств = (ответств_по_м.get(ин) or ответств_вх
                    or _ОТВЕТСТВЕННЫЙ_ПУСТО)
        сроки = сроки_вх.get(ин) or {}
        начало = _dt.date.fromisoformat(str(сроки["nachala"])[:10]) \
            if сроки.get("nachala") else база
        if сроки.get("okonchanie"):
            конец = _dt.date.fromisoformat(str(сроки["okonchanie"])[:10])
        else:
            конец = начало + _dt.timedelta(
                days=_ДЛИТЕЛЬНОСТЬ_ДНЕЙ[м["trudoemkost"]["klass"]])
        if vpp is not None and м.get("dVPP_pp") is not None:
            до = f"ВПП {str(vpp).replace('.', ',')} % сменного времени"
            после = (f"ВПП {str(round(vpp - м['dVPP_pp'], 2)).replace('.', ',')} % "
                     f"(−{str(м['dVPP_pp']).replace('.', ',')} п.п.)")
        else:
            до = "разрыв ВПП не замерен"
            после = "цель уточняется после замера"
        план.append({
            "n": len(план) + 1,
            "meropriyatie": ин,
            "prichina": м.get("prichina"),
            "otvetstvenny": ответств,
            "srok": f"{_дата_iso(начало)} — {_дата_iso(конец)}",
            "data_nachala": _дата_iso(начало),
            "data_okonchaniya": _дата_iso(конец),
            "status": "В реализации",
            "pokazatel_do": до,
            "pokazatel_posle": после,
            "dVPP_pp": м.get("dVPP_pp"),
            "dVPP_min": м.get("dVPP_min"),
            "dPT_pct": м.get("dPT_pct"),
            "dEE_rub": м.get("dEE_rub"),
            "prioritet": м.get("prioritet"),
            "prioritet_klass": (м.get("matritsa") or {}).get("prioritet_klass"),
            "trudoemkost_dnej": (м.get("trudoemkost") or {}).get("chel_dnej"),
            "kurs_fck": курс,
            "vazhno": (f"приоритет {м.get('prioritet')}, класс "
                       f"{(м.get('matritsa') or {}).get('prioritet_klass')}; "
                       f"обучение — курс ФЦК «{курс}»"),
            "istochnik_srokov": ("вход sroki" if сроки else источник_сроков),
        })
    if разрыв is not None:
        for з in план:
            з["razryv_pp_um"] = разрыв
    return план


