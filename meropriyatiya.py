# Шаг 2. Дерево проблем (ветки потерь)
# ---------------------------------------------------------------------------

def построить_дерево(vhod, problema):
    """Симптом → ветки по 15 признакам пп. 6.2–6.16 (формулировки дословно
    из otbor_potok.ПРИЗНАКИ_ПОТЕРЬ) + 7 видов потерь. Каждая ветка
    квантифицируется; нет данных — gap «нужен замер»."""
    признаки_вх = vhod.get("priznaki") or {}
    замеры = vhod.get("zamery") or {}
    виды_вх = vhod.get("vidy_potery") or []
    ветки = []

    # 2а. Ветки по отмеченным признакам пп. 6.2–6.16
    for ключ, формулировка in ПРИЗНАКИ_ПОТЕРЬ:
        if признаки_вх.get(ключ) is not True:
            continue
        причина_тип, вид = _ПРИЗНАК_К_ПРИЧИНЕ[ключ]
        замер = замеры.get(ключ)
        замер_ключ = _ЗАМЕР_ПО_ПРИЧИНЕ.get(причина_тип, "фотография_рабочего_дня")
        if замер and замер.get("value") is not None:
            kvant = _kvant(замер["value"], замер.get("unit"),
                           замер.get("evidence", "fact"))
        else:
            kvant = _kvant(evidence="gap", замер=замер_ключ)
        ветки.append({
            "poterya": формулировка,
            "istochnik": f"признак п. 6.x Прил. № 5 («{ключ}»)",
            "vid_potery": вид,
            "prichina_tip": причина_тип,
            "kvant": kvant,
        })

    # 2б. Ветки по явно заданным видам потерь (Прил. 1), без дублей
    занятые = {в["vid_potery"] for в in ветки}
    for вд in виды_вх:
        название = вд.get("nazvanie") if isinstance(вд, dict) else str(вд)
        if название not in ВИДЫ_ПОТЕРЬ or название in занятые:
            continue
        причина_тип = _ВИД_К_ПРИЧИНЕ.get(название)
        kvant_вх = вд.get("kvant") if isinstance(вд, dict) else None
        if kvant_вх and kvant_вх.get("value") is not None:
            kvant = _kvant(kvant_вх["value"], kvant_вх.get("unit"),
                           kvant_вх.get("evidence", "fact"))
        else:
            замер_ключ = _ЗАМЕР_ПО_ПРИЧИНЕ.get(причина_тип,
                                               "фотография_рабочего_дня")
            kvant = _kvant(evidence="gap", замер=замер_ключ)
        ветки.append({
            "poterya": f"Вид потерь: {название}",
            "istochnik": "Приложение 1 «Виды потерь» (отмечен во входе)",
            "vid_potery": название,
            "prichina_tip": причина_тип,
            "kvant": kvant,
        })
        занятые.add(название)

    if not ветки:
        # Нет отмеченных признаков — единственная ветка-пробел по самому УМ
        ветки.append({
            "poterya": (f"Структура потерь участка «{problema['uchastok']}» "
                        "не разложена: признаки потерь не отмечены"),
            "istochnik": "ветка по умолчанию (нет входных признаков)",
            "vid_potery": None,
            "prichina_tip": None,
            "kvant": _kvant(evidence="gap", замер="фотография_рабочего_дня"),
        })
    return ветки


