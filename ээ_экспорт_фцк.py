#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ЭЭ-экспортёр ФЦК — v0.1 (детерминированный, без LLM).

Назначение: из нашего JSON ЭЭ-калькулятора (спека № 2, концевой серийный
поток) сгенерировать справку ФЦК «1.4 Справка …xlsm» — копию эталонного
шаблона модели v5.2 с записанными входными ячейками листа «Чек-лист».
Формулы модели (лист «Экономический эффект», расчётные ячейки чек-листа
D81:E83, итоги G194:G197, валидаторы J) НЕ перезаписываются — справка
считает сама при открытии в Excel. VBA/макросы, скрытые строки/листы,
защита листов, внешние ссылки сохраняются (openpyxl keep_vba=True).

Карта маппинга: разведка_ээ/ВСКРЫТИЕ_ЭЭ_ФЦК.md, раздел 6.

Запуск CLI:
    python3 ээ_экспорт_фцк.py данные.json [выход.xlsm]

Вход — наш JSON ЭЭ + необязательные метаданные верхнего уровня:
    регион, доля_потока, численность, единица_гп (дефолт «шт»),
    дата_первичного_сбора / дата_вторичного_сбора («YYYY-MM-DD»),
    бизнес_контекст, проблема_решение, результат_эффект,
    цена_ед_после (только если цена менялась — вопрос 21 чек-листа).

РЕШЕНИЯ ПО «ПЛАНОВОМУ РЕЖИМУ» (зафиксированы по задаче ЭЭ_Экспортёр):
- В эталонном плановом экземпляре часть «входных» ячеек — формулы с
  зашитыми константами (G77 =G85*G74, H77 =G77, G84/G85 =(вес/0.071)/40,
  G87/G88 =(выручка или затраты/объём)*40). Это способ ввода владельца:
  он фактически вбивал свои цифры внутрь формул. Экспортёр пишет в эти
  ячейки ЗНАЧЕНИЯ (числа) — это эквивалентно вводу владельца и не ломает
  модель: расчётные цепочки читают эти ячейки как вход (см. ВСКРЫТИЕ §3).
- Формулы, которые по маппингу «не трогать» (D81:E83, E71/E87/E184/E185,
  J-валидаторы, G194:G197, весь лист «Экономический эффект», Tech,
  Декомпозиция, списки) — не трогаем: они пересчитаются Excel'ем.
- ОЧИСТКА: шаблон — заполненный экземпляр Оренбургхладокомбината. Перед
  записью все входные ячейки чек-листа очищаются (аналог их макроса
  «Очистка_10»), иначе чужие данные попали бы в новую справку.
  Ответы «да/нет» по незадействованным блокам проставляются «нет»
  (как в эталоне), флаги задействованных — «да».
"""

import io
import json
import sys
from datetime import date, datetime
from pathlib import Path

import openpyxl

# Эталонный шаблон (заполненный владельцем плановый экземпляр модели v5.2).
# Файл НЕ изменяется — читается только как образец структуры/формул.
ШАБЛОН = (Path(__file__).resolve().parent / "разведка_ээ"
          / "1.4 Справка плановый_ЭЭ_Оренбургхладокомбинат.xlsm")

ЛИСТ = "Чек-лист"

# ---------------------------------------------------------------------------
# КАРТА ОЧИСТКИ — все входные ячейки чек-листа (по ВСКРЫТИЮ §4, §6 и дампу).
# Очищаются перед записью, чтобы в справке не осталось данных шаблона.
# Расчётные ячейки (D81:E83, E71/E87/E184/E185, J*, G194:G197) сюда НЕ входят.
# ---------------------------------------------------------------------------
ОЧИСТКА = (
    # шапка
    ["E5", "E6", "E7", "E8", "E9", "E10", "E11", "E12", "G16", "H16"]
    # полуфабрикаты (серия + позаказ), мультипродукт, позаказный концевой —
    # ветки вне контура v0.1: чистим на случай данных шаблона
    + [f"{к}{р}" for к in "GH" for р in (
        20, 21, 22, 25, 26, 27, 31, 32, 35, 36, 39, 40, 42, 43, 45, 46, 48, 49,
        54, 55, 56, 57, 59, 61, 63, 65, 72,
        113, 114, 115, 119, 120, 122, 123, 124, 125, 126, 127,
        133, 134, 135, 137, 139, 141, 143)]
    # концевой серийный блок (основной вход)
    + ["E73"]
    + [f"{к}{р}" for к in "GH" for р in (74, 75, 77, 78, 79, 80, 84, 85, 87, 88)]
    # нормы: сырьё, э/э, вода, газ, тепло, труд
    + [f"{к}{р}" for к in "GH" for р in (
        91, 92, 95, 96, 98, 99, 101, 102, 104, 105, 109, 110)]
    # постоянные: персонал на окладе, коммуналка (4 вида), ремонт
    + [f"{к}{р}" for к in "GH" for р in (146, 147, 150, 151, 153, 154, 156, 157,
                                          159, 160, 162)]
    + ["E156"]  # единица ГСМ
    # прочие доходы/расходы: аренда, брак, суммарные переменные заказов
    + [f"{к}{р}" for к in "GH" for р in (165, 167, 168, 170, 171)]
    # рабочий капитал: НЗП, СиМ, ГП (натуральные и рублёвые вводы)
    + [f"{к}{р}" for к in "GH" for р in (174, 175, 176, 179, 180, 181,
                                          184, 185, 186)]
    # ключевая ставка, НДС, доп. эффект
    + ["G187", "H187", "G193", "H191"]
)

# Ответы «да/нет»: дефолт «нет» (как в эталоне для незадействованных блоков),
# далее экспортёр ставит «да» по наличию данных. G17/G67 — всегда «да»
# (контур v0.1 = конечный передел, серийное производство).
ФЛАГИ_НЕТ = [89, 93, 106, 145, 148, 161, 164, 166, 169, 173, 177, 178,
             182, 183, 189, 190]


def _число(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _дата(v, поле):
    """«YYYY-MM-DD» → datetime.date; ошибки — по-русски."""
    if v is None:
        return None
    if isinstance(v, (datetime, date)):
        return v if isinstance(v, date) else v.date()
    try:
        return datetime.strptime(str(v).strip()[:10], "%Y-%m-%d").date()
    except ValueError:
        raise ValueError(f"поле «{поле}»: дата должна быть в формате "
                         f"«YYYY-MM-DD», получено «{v}»")


def фонд_времени(d, метка):
    """Годовой фонд времени (мин/год): прямой ввод или смены×часы×дни×60."""
    в = (d.get("время_мин_год") or {}).get(метка)
    if _число(в):
        return в
    ф = d.get("фонд_времени") or {}
    if all(_число(ф.get(k)) for k in ("смены", "часы", "дни")):
        return ф["смены"] * ф["часы"] * ф["дни"] * 60
    return None


def собрать_записи(d):
    """Наш JSON → {(ячейка): значение} для листа «Чек-лист».
    Возвращает (записи, предупреждения)."""
    z = {}          # ячейка → значение
    предупр = []

    def put(ячейка, значение):
        if значение is not None:
            z[ячейка] = значение

    # --- Шапка ---
    put("E5", d.get("предприятие"))
    put("E6", d.get("регион"))
    put("E7", d.get("поток"))
    put("E8", d.get("доля_потока"))
    put("E9", d.get("численность"))
    put("E10", d.get("бизнес_контекст"))
    put("E11", d.get("проблема_решение"))
    put("E12", d.get("результат_эффект"))
    put("G16", _дата(d.get("дата_первичного_сбора"), "дата_первичного_сбора"))
    put("H16", _дата(d.get("дата_вторичного_сбора"), "дата_вторичного_сбора"))

    # --- Вопросы ветки (контур v0.1 = конечный передел, серийное пр-во) ---
    z["G17"] = "да"      # конечный передел
    z["G67"] = "да"      # серийная продукция
    z["G69"] = "да" if d.get("спрос_превышает_возможности") else "нет"
    цена_после = d.get("цена_ед_после")
    z["G70"] = "да" if _число(цена_после) else "нет"
    for р in ФЛАГИ_НЕТ:
        z[f"G{р}"] = "нет"

    # --- Объём и цены (концевой серийный блок) ---
    put("E73", d.get("единица_гп") or "шт")
    тц1, тц2 = d["тцикл_мин"]["до"], d["тцикл_мин"]["после"]
    тт1, тт2 = d["ттакт_мин"]["до"], d["ттакт_мин"]["после"]
    z["G74"], z["H74"] = тц1, тц2
    z["G75"], z["H75"] = тт1, тт2

    т1 = фонд_времени(d, "до")
    т2 = фонд_времени(d, "после")
    # G77/H77 — фактическое время производства годной (мин/год). Пишем ЧИСЛАМИ
    # (в плановом эталоне тут формулы =G85*G74 / =G77 — см. шапку модуля).
    put("G77", т1)
    put("H77", т2)

    # Объёмы: логика ячеек D82/E82 модели (спрос vs возможности)
    if т1 is not None:
        б1 = тц1 if тт1 < тц1 else тт1
        v1, vп1 = т1 / б1, т1 / тц1
        # G84 — объём реализации за год: заявленный факт первичного сбора,
        # иначе расчётный (в эталоне совпадают; J84 сверяет их ±10 %)
        put("G84", d.get("объем_реализации_факт") or v1)
        put("G85", vп1)
    if т2 is not None:
        б2 = тц2 if тт2 < тц2 else тт2
        put("H84", т2 / тц2)
        put("H85", т2 / б2)

    put("G87", d.get("цена_ед"))
    if _число(цена_после):
        put("H87", цена_после)   # H87 читается только при G70="да"
    put("G88", d.get("перем_сс_ед"))
    put("H88", d.get("перем_сс_ед"))  # конвенция формы: H88 = G88 (как в эталоне)

    # --- Нормы переменных затрат (дельты считает лист «Экономический эффект») —
    нормы = d.get("нормы") or {}
    б = нормы.get("сырье") or {}
    if any(_число(б.get(k)) for k in ("норма_до", "норма_после")):
        z["G89"] = "да"
        put("G91", б.get("норма_до")); put("H91", б.get("норма_после"))
        put("G92", б.get("цена"))
    энерго = {"электроэнергия": (95, 96, "тариф"), "вода": (98, 99, "тариф"),
              "газ": (101, 102, "тариф"), "тепло": (104, 105, "тариф")}
    for вид, (рн, рц, ключ_цены) in энерго.items():
        б = нормы.get(вид) or {}
        if any(_число(б.get(k)) for k in ("норма_до", "норма_после")):
            z["G93"] = "да"
            put(f"G{рн}", б.get("норма_до")); put(f"H{рн}", б.get("норма_после"))
            put(f"G{рц}", б.get(ключ_цены))
    б = нормы.get("труд") or {}
    if any(_число(б.get(k)) for k in ("трудоемкость_до", "трудоемкость_после")):
        z["G106"] = "да"
        put("G109", б.get("трудоемкость_до")); put("H109", б.get("трудоемкость_после"))
        put("G110", б.get("ставка"))

    # --- Постоянные затраты ---
    п = d.get("постоянные") or {}
    б = п.get("персонал_оклад") or {}
    if any(_число(б.get(k)) for k in ("чел_до", "чел_после")):
        z["G145"] = "да"
        put("G146", б.get("чел_до")); put("H146", б.get("чел_после"))
        put("G147", б.get("зп_мес"))
    комм = {"электроэнергия": (150, 151), "вода": (153, 154),
            "гсм": (156, 157), "тепло": (159, 160)}
    for кб in п.get("коммуналка") or []:
        яч = комм.get(str(кб.get("вид", "")).strip().lower())
        if not яч:
            if кб.get("вид"):
                предупр.append(f"постоянная коммуналка «{кб.get('вид')}»: вид не "
                               "маппируется в справку ФЦК (электроэнергия/вода/гсм/тепло) — пропущено")
            continue
        if any(_число(кб.get(k)) for k in ("объем_до", "объем_после")):
            z["G148"] = "да"
            ро, рт = яч
            put(f"G{ро}", кб.get("объем_до")); put(f"H{ро}", кб.get("объем_после"))
            put(f"G{рт}", кб.get("тариф"))  # тариф «после» модель жёстко берёт = «до»
    б = п.get("ремонт") or {}
    if any(_число(б.get(k)) for k in ("до", "после")):
        z["G161"] = "да"
        put("G162", б.get("до")); put("H162", б.get("после"))

    # --- Прочие доходы/расходы: аренда, брак, прочий эффект ---
    пр = d.get("прочее") or {}
    ар = пр.get("аренда") or {}
    if _число(ар.get("площадь_м2")) and ар.get("площадь_м2"):
        z["G164"] = "да"
        put("H165", ар.get("площадь_м2"))            # ЭЭ!F158 читает H165
        put("H167", ар.get("ставка_потенциальная"))  # ЭЭ!F160 (потенциальный)
        put("H168", ар.get("ставка_реальная"))       # ЭЭ!F159 (реальный)
        z["G166"] = "да" if _число(ар.get("ставка_реальная")) and ар.get("ставка_реальная") else "нет"
    бр = пр.get("брак_доля") or {}
    if _число(бр.get("до")) and _число(бр.get("после")):
        z["G169"] = "да"
        put("G170", бр.get("до")); put("H170", бр.get("после"))
    if _число(пр.get("прочий_эффект_руб")) and пр.get("прочий_эффект_руб"):
        z["G189"] = "да"
        z["G190"] = "да" if пр.get("прочий_реальный", True) else "нет"
        put("H191", пр["прочий_эффект_руб"])  # ЭЭ!F163/F164 по флагу G190

    # --- Рабочий капитал (у нас — только рублёвый ввод запасов) ---
    зап = d.get("запасы_руб") or {}
    б = зап.get("нзп") or {}
    if _число(б.get("до")) or _число(б.get("после")):
        z["G173"] = "нет"  # натуральной оценки НЗП нет → рублёвый ввод
        put("G176", б.get("до")); put("H176", б.get("после"))
    б = зап.get("сим") or {}
    if _число(б.get("до")) or _число(б.get("после")):
        z["G177"] = "да"; z["G178"] = "нет"  # только рублёвый эквивалент
        put("G181", б.get("до")); put("H181", б.get("после"))
    б = зап.get("гп") or {}
    if _число(б.get("до")) or _число(б.get("после")):
        z["G182"] = "да"; z["G183"] = "нет"
        put("G186", б.get("до")); put("H186", б.get("после"))

    # --- Ставки ---
    к = d.get("константы") or {}
    if _число(к.get("ключевая_ставка")):
        z["G187"] = z["H187"] = к["ключевая_ставка"]
    if _число(к.get("ндс")):
        z["G193"] = к["ндс"]
    # налог на прибыль 20 % в модели захардкожен (G194) — не выносим

    return z, предупр


def экспортировать_в_bytes(d, шаблон=None):
    """Наш JSON → (bytes xlsm, предупреждения). Шаблон не изменяется."""
    шаблон = Path(шаблон) if шаблон else ШАБЛОН
    if not шаблон.exists():
        raise FileNotFoundError(f"не найден шаблон справки ФЦК: {шаблон}")
    записи, предупр = собрать_записи(d)
    wb = openpyxl.load_workbook(шаблон, keep_vba=True)
    ws = wb[ЛИСТ]
    # Очистка входных ячеек (аналог их макроса «Очистка_10»): шаблон —
    # заполненный экземпляр, чужие данные не должны попасть в новую справку.
    for ячейка in ОЧИСТКА:
        ws[ячейка] = None
    for ячейка, значение in записи.items():
        ws[ячейка] = значение
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue(), предупр


def экспортировать(d, выход, шаблон=None):
    """Наш JSON → файл .xlsm по пути `выход`. Возвращает (Path, предупреждения)."""
    б, предупр = экспортировать_в_bytes(d, шаблон)
    выход = Path(выход)
    выход.write_bytes(б)
    return выход, предупр


def имя_файла(d, дата=None):
    """«1.4 Справка_ЭЭ_<предприятие>_<дата>.xlsm» — безопасное имя."""
    import re
    пред = re.sub(r"[^\wа-яА-ЯёЁ -]", "", str(d.get("предприятие") or "предприятие"))
    пред = пред.strip().replace(" ", "_") or "предприятие"
    д = (дата or date.today()).isoformat()
    return f"1.4 Справка_ЭЭ_{пред}_{д}.xlsm"


def main():
    if len(sys.argv) < 2 or len(sys.argv) > 3:
        sys.exit("Запуск: python3 ээ_экспорт_фцк.py <данные.json> [выход.xlsm]")
    with open(sys.argv[1], encoding="utf-8") as f:
        d = json.load(f)
    # Валидация — штатным валидатором ядра ЭЭ (единая точка истины)
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import ээ_калькулятор as ядро
    ошибки = ядро.validirovat(d)
    if ошибки:
        sys.exit("Ошибки входа:\n" + "\n".join(f"- {e}" for e in ошибки))
    выход = sys.argv[2] if len(sys.argv) == 3 else имя_файла(d)
    путь, предупр = экспортировать(d, выход)
    print(f"Справка ФЦК сформирована: {путь} ({путь.stat().st_size} байт)")
    for w in предупр:
        print(f"⚠ {w}")


if __name__ == "__main__":
    main()
