class _Сим:
    """Один прогон ДСС линейного потока (фиксированный seed)."""

    def __init__(self, d, seed):
        сим = d.get("симуляция") or {}
        self.время = float(d["доступное_время_мин"])
        self.спрос = float(d["спрос_шт_в_период"])
        self.такт = self.время / self.спрос
        self.vmin = float(сим.get("вариативность_мин", 0.9))
        self.vmax = float(сим.get("вариативность_макс", 1.15))
        ёмк = сим.get("ёмкость_буферов") or {}
        кран = сим.get("кран") or {}
        self.кран_вер = float(кран.get("вероятность", 0.0))
        self.кран_дл = float(кран.get("длительность_мин", 0.0))
        self.rnd = random.Random(seed)
        self.seed = seed

        self.ops = []
        for op in d["операции"]:
            ту = float(op["тц_мин"])
            исп = op.get("исполнители") or 1
            партия = op.get("партия_шт")
            пер = float(op.get("переналадка_мин") or 0.0)
            эфф = (ту + (пер / партия if партия and пер else 0.0)) / исп
            self.ops.append({
                "имя": op["имя"].strip(), "ту": ту, "исп": исп,
                "брак": float(op.get("брак_пкт") or 0.0) / 100.0,
                "пер": пер, "партия": партия, "эфф": эфф,
                "свободно": исп, "ожид_pull": 0, "счёт_партии": 0,
                "занято_мин": 0.0, "занято_с": None, "брак_шт": 0,
            })
        K = len(self.ops)
        # Виртуальная операция-отгрузка (обслуживает выходной буфер).
        self.ops.append({"имя": "— отгрузка —", "ту": 0.0, "исп": 1,
                         "брак": 0.0, "пер": 0.0, "партия": None, "эфф": 0.0,
                         "свободно": 1, "ожид_pull": 0, "счёт_партии": 0,
                         "занято_мин": 0.0, "занято_с": None, "брак_шт": 0})
        self.база = max([self.такт] + [o["эфф"] for o in self.ops])
        # Буферы после каждой реальной операции (последний — выходной).
        self.буферы = []
        for i, op in enumerate(d["операции"]):
            cap = ёмк.get(op["имя"].strip())
            нач = int(op.get("запас_после_шт") or 0)
            self.буферы.append({"ёмкость": cap if cap is not None else math.inf,
                                "очередь": [(None, 0.0)] * нач,  # (id, приход)
                                "last_pull": -self.база})
        self.K = K  # реальных операций; индекс отгрузки = K

        self.куча = []          # (t, seq, тип, *payload)
        self.seq = 0
        self.t = 0.0
        self.след_id = 0
        self.вход_очередь = []  # id изделий перед первой операцией
        self.запущено = {}      # id → t запуска (только новые изделия)
        self.впп = []           # lead time завершённых запущенных изделий
        self.выпуск = 0         # отгружено в горизонте (включая начальный НЗП)
        self.нзп = float(sum(int(op.get("запас_после_шт") or 0)
                             for op in d["операции"]))
        self.нзп_макс = self.нзп
        self._нзп_интеграл = 0.0
        self._нзп_с = 0.0

    # --- событийная механика ---
    def push(self, t, тип, *payload):
        heapq.heappush(self.куча, (t, self.seq, тип) + payload)
        self.seq += 1

    def треуг(self, номинал):
        return self.rnd.triangular(self.vmin * номинал,
                                   self.vmax * номинал, номинал)

    def _учесть_нзп(self, t):
        if t > self._нзп_с:
            до = min(t, self.время)
            если = min(self._нзп_с, self.время)
            if до > если:
                self._нзп_интеграл += self.нзп * (до - если)
            self._нзп_с = t

    def _занятость(self, op, t0, t1):
        до = min(t1, self.время)
        если = min(t0, self.время)
        if до > если:
            op["занято_мин"] += до - если

    def _заблокировать(self, i, item):
        """Операция i не может сдать деталь в полный буфер — сервер блокируется."""
        op = self.ops[i]
        op.setdefault("блок", []).append(item)

    def _старт(self, i, t, item):
        """START: сервер операции i начинает обработку изделия."""
        op = self.ops[i]
        op["свободно"] -= 1
        op["занято_с"] = t
        длит = self.треуг(op["ту"]) if op["ту"] > 0 else 0.0
        self.push(t + длит, "FINISH", i, item)

    def _попробовать(self, i, t):
        """Назначить работу свободным серверам операции i из её входного буфера."""
        op = self.ops[i]
        while op["свободно"] - op["ожид_pull"] > 0:
            if i == 0:
                if not self.вход_очередь:
                    break
                item = self.вход_очередь.pop(0)
                self._старт(i, t, item)
            else:
                б = self.буферы[i - 1]
                if not б["очередь"]:
                    break
                # С2.1: темп передачи задаёт операция-источник (i-1),
                # а не глобальная база — иначе ускорение не-УМ не влияло
                # на ВПП/НЗП вообще. Запуск (RELEASE) остаётся по self.база.
                темп = max(self.такт, self.ops[i - 1]["эфф"])
                приход = б["очередь"][0][1]
                тик = math.ceil((приход - 1e-12) / темп) * темп
                t_pull = max(t, тик, б["last_pull"] + темп)
                б["last_pull"] = t_pull           # резервируем слот темпа
                op["ожид_pull"] += 1
                self.push(t_pull, "PULL", i)

    def run(self):
        # RELEASE: запуск изделий с темпом база в горизонте доступного времени
        k = 0
        while k * self.база < self.время - 1e-12:
            self.push(k * self.база, "RELEASE")
            k += 1
        self.push(self.время, "HORIZON")
        # Начальный НЗП в буферах начинает отгружаться с t=0 (темп линии).
        for i in range(self.K + 1):
            self._попробовать(i, 0.0)
        while self.куча:
            ev = heapq.heappop(self.куча)
            t, тип = ev[0], ev[2]
            self._учесть_нзп(t)
            self.t = t
            if тип == "RELEASE":
                self.след_id += 1
                item = self.след_id
                self.запущено[item] = t
                self.нзп += 1
                self.нзп_макс = max(self.нзп_макс, self.нзп)
                self.вход_очередь.append(item)
                self._попробовать(0, t)
            elif тип == "PULL":
                i = ev[3]
                op = self.ops[i]
                op["ожид_pull"] -= 1
                б = self.буферы[i - 1]
                if not б["очередь"]:  # страховка: слот был, очередь пуста
                    self._попробовать(i, t)
                    continue
                item, _ = б["очередь"].pop(0)
                self._старт(i, t, item)
                # освободившееся место → разблокировать операцию-источник i-1
                пред = self.ops[i - 1]
                if пред.get("блок"):
                    it = пред["блок"].pop(0)
                    б["очередь"].append((it, t))
                    self._после_сдачи(i - 1, t)
                    self._попробовать(i, t)
            elif тип == "FINISH":
                i, item = ev[3], ev[4]
                op = self.ops[i]
                op["счёт_партии"] += 1
                if i == self.K:  # отгрузка (SHIP): изделие покидает поток
                    op["свободно"] += 1
                    self._учесть_нзп(t)
                    self.нзп -= 1
                    if t <= self.время - 1e-9:
                        self.выпуск += 1
                    старт = self.запущено.get(item)
                    if старт is not None:
                        self.впп.append(t - старт)
                    self._попробовать(i, t)
                    continue
                # FAIL: брак → переделка на той же операции
                if op["брак"] > 0 and self.rnd.random() < op["брак"]:
                    op["брак_шт"] += 1
                    if i == 0:
                        self.вход_очередь.insert(0, item)
                    else:
                        self.буферы[i - 1]["очередь"].insert(0, (item, t))
                        self.буферы[i - 1]["last_pull"] = t  # честный темп
                    self._сервер_дальше(i, t)
                    self._попробовать(i, t)
                    continue
                # годная деталь → в буфер после операции
                б = self.буферы[i]
                if len(б["очередь"]) < б["ёмкость"]:
                    б["очередь"].append((item, t))  # ARRIVE
                    self._сервер_дальше(i, t)
                    self._попробовать(i, t)      # освободившийся сервер → следующая
                    self._попробовать(i + 1, t)
                else:
                    self._заблокировать(i, item)   # BLOCKED: ждём места
            elif тип == "SETUP_END" or тип == "CRANE_WAIT_END":
                i = ev[3]
                op = self.ops[i]
                self._занятость(op, op["занято_с"], t)
                op["свободно"] += 1
                self._попробовать(i, t)
            elif тип == "HORIZON":
                pass  # метка горизонта; доводка запущенного идёт до конца
        return self.итоги()

    def _сервер_дальше(self, i, t):
        """Сервер сдал деталь: переналадка / ожидание крана / свободен."""
        op = self.ops[i]
        нужна_пер = (op["партия"] and op["пер"] > 0
                     and op["счёт_партии"] % op["партия"] == 0)
        if нужна_пер:
            self.push(t + self.треуг(op["пер"]), "SETUP_END", i)
        elif self.кран_вер > 0 and self.rnd.random() < self.кран_вер:
            self.push(t + self.треуг(self.кран_дл), "CRANE_WAIT_END", i)
        else:
            self._занятость(op, op["занято_с"], t)
            op["свободно"] += 1

    def _после_сдачи(self, i, t):
        """Разблокированный сервер операции i сдал деталь в буфер."""
        self._сервер_дальше(i, t)

    def итоги(self):
        нзп_сред = self._нзп_интеграл / self.время if self.время else 0.0
        загрузка = []
        for op in self.ops[:self.K]:
            фонд = self.время * op["исп"]
            загрузка.append({"имя": op["имя"],
                             "загрузка_пкт": round(op["занято_мин"] / фонд * 100, 2)
                             if фонд else 0.0,
                             "брак_шт": op["брак_шт"]})
        ум = max(загрузка, key=lambda x: x["загрузка_пкт"])
        return {"seed": self.seed,
                "такт_мин": round(self.такт, 4),
                "база_мин": round(self.база, 4),
                "тц_мин": round(sum(o["ту"] for o in self.ops[:self.K]), 4),
                "впп_мин": round(statistics.median(self.впп), 2)
                if self.впп else None,
                "выпуск_шт": self.выпуск,
                "нзп_среднее_шт": round(нзп_сред, 1),
                "нзп_макс_шт": self.нзп_макс,
                "загрузка": загрузка,
                "узкое_место": ум["имя"],
                "запущено_шт": len(self.запущено)}


def raschet(d):
    """Один прогон с seed из входа (по умолчанию 1)."""
    сим = d.get("симуляция") or {}
    seed = сим.get("seed", 1)
    return _Сим(d, seed).run()


def оценка(d):
    """n прогонов с разными seed → медиана ± разброс (мин–макс) по выпуску
    и ВПП, плюс базовый прогон (seed из входа) целиком."""
    сим = d.get("симуляция") or {}
    seed0 = сим.get("seed", 1)
    n = сим.get("прогонов", 10)
    прогоны = [_Сим(d, seed0 + i).run() for i in range(n)]
    выпуски = [p["выпуск_шт"] for p in прогоны]
    вппы = [p["впп_мин"] for p in прогоны if p["впп_мин"] is not None]
    def свод(ряд):
        return {"медиана": round(statistics.median(ряд), 2),
                "мин": round(min(ряд), 2), "макс": round(max(ряд), 2)}
    return {"база_прогон": прогоны[0],
            "прогонов": n,
            "seed_база": seed0,
            "выпуск_шт": свод(выпуски),
            "впп_мин": свод(вппы) if вппы else None,
            "допущения": ДОПУЩЕНИЯ}


