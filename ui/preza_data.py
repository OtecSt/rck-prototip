# -*- coding: utf-8 -*-
"""Сборщик данных фаст-презентации (Спека П1, ломтик П2).

Чистая сборка: модуль не ходит в БД и не знает про Flask — на вход получает
карточку проекта и список прогонов (словари с уже разобранными итогами),
на выходе — dict со слайдами по скелету спеки (8 разделов), логом сборки
и темой. Числа не пересчитываются: берутся как есть из итоги_json прогонов
(форматирование — забота П3). Дельты «до/после» — через существующий
механизм сравнения (функция sravnit из app.py передаётся параметром).
"""

# Скелет слайдов (Спека П1, раздел 4): код → (заголовок, кикер, источники-инструменты)
СКЕЛЕТ = {
    "титул": {"заголовок": "Пилотный проект · РЦК",
              "кикер": "Защита пилотного проекта",
              "инструменты": []},  # данные — из карточки проекта
    "проблема": {"заголовок": "Проблема: узкое место потока",
                 "кикер": "Диагностика",
                 "инструменты": ["uzkie_mesta"]},
    "поток": {"заголовок": "Показатели потока",
              "кикер": "Диагностика",
              "инструменты": ["potok_calc", "oee"]},
    "симуляция": {"заголовок": "Симуляция «что если»",
                  "кикер": "Сценарный прогон",
                  "инструменты": ["simulation"]},
    "мероприятия": {"заголовок": "Мероприятия",
                    "кикер": "План мероприятий",
                    "инструменты": ["meropriyatiya"]},
    "эффект": {"заголовок": "Экономический эффект",
               "кикер": "Эффект проекта",
               "инструменты": ["ee"]},
    "план": {"заголовок": "План и статус",
             "кикер": "Цели и ход работ",
             "инструменты": ["smart", "protokol"]},
    "выводы": {"заголовок": "Выводы",
               "кикер": "Итоги проекта",
               "инструменты": []},  # сводка слайдов 2–6
}

ПОРЯДОК = ["титул", "проблема", "поток", "симуляция",
           "мероприятия", "эффект", "план", "выводы"]

ТЕМЫ = ("бумага", "графит")

# Дисклеймеры (Спека П1, п. 6.4): наследуются от инструментов-источников.
ДИСКЛЕЙМЕР_СИМУЛЯЦИЯ = "Модельный прогноз, не замер."

# Тёмные слайды по дизайн-концепции (Спека П1, раздел 5).
_ТЁМНЫЕ = ("титул", "выводы")


def _ч(x):
    """Число для шаблонной фразы выводов: целые — без хвоста, дробные —
    с запятой десятичной, тысячи — пробелами. Только отображение в буллете,
    значения слайдов этой функцией не трогаются."""
    if x is None:
        return "—"
    if isinstance(x, (int, float)):
        if isinstance(x, float) and not x.is_integer():
            return f"{x:,.2f}".replace(",", " ").replace(".", ",")
        return f"{int(round(x)):,}".replace(",", " ")
    return str(x).replace(".", ",")


def _источник(g):
    """Трассировка слайда к прогону (стоп-гейт спеки: каждое число — к прогону № N)."""
    return {"прогон_id": g["id"], "дата": g["дата"], "инструмент": g["инструмент"]}


def _последний(прогоны, инструмент):
    """Последний прогон инструмента (по id — прогоны immutable, новее = больше id)."""
    кандидаты = [g for g in прогоны if g["инструмент"] == инструмент]
    return max(кандидаты, key=lambda g: g["id"]) if кандидаты else None


def _пара_до_после(прогоны, инструмент):
    """Пара прогонов с метками «до»/«после» (последние с каждой меткой)."""
    до = [g for g in прогоны if g["инструмент"] == инструмент and g["метка"] == "до"]
    после = [g for g in прогоны if g["инструмент"] == инструмент and g["метка"] == "после"]
    if до and после:
        return max(до, key=lambda g: g["id"]), max(после, key=lambda g: g["id"])
    return None


def _слайд(код, данные, источники):
    return {"код": код,
            "заголовок": СКЕЛЕТ[код]["заголовок"],
            "кикер": СКЕЛЕТ[код]["кикер"],
            "тёмный": код in _ТЁМНЫЕ,
            "данные": данные,
            "источники": источники}


def _слайд_титул(проект, титул):
    """Слайд 1: поля из запроса перекрывают карточку проекта (Спека П1, п. 2)."""
    титул = титул or {}
    данные = {
        "предприятие": (титул.get("предприятие") or проект.get("предприятие") or ""),
        "поток": (титул.get("поток") or проект.get("поток") or ""),
        "автор": (титул.get("автор") or "РЦК"),
        "название_проекта": проект.get("название") or "",
        "дата": проект.get("создан") or "",
        "подпись": "Пилотный проект · РЦК",
    }
    return _слайд("титул", данные, [])


def _слайд_проблема(g):
    """Слайд 2: главное УМ, его доля ВПП, подтверждение — из итогов прогона УМ."""
    ит = g["итоги"]
    ум = ит.get("главное_ум")
    доля_ум = None
    for имя, сек, доля in ит.get("доли_впп") or []:
        if имя == ум:
            доля_ум = доля
            break
    данные = {"главное_ум": ум,
              "подтверждено": ит.get("подтверждено"),
              "доля_впп_ум_пкт": доля_ум,
              "доли_впп": ит.get("доли_впп") or [],
              "ранжирование": ит.get("ранжирование") or [],
              "поток": ит.get("поток")}
    return _слайд("проблема", данные, [_источник(g)])


def _слайд_поток(g_potok, g_oee):
    """Слайд 3: полоса метрик потока; OEE — вторая карточка, если прогон есть."""
    данные = {"поток": dict(g_potok["итоги"])}
    источники = [_источник(g_potok)]
    if g_oee is not None:
        данные["oee"] = dict(g_oee["итоги"])
        источники.append(_источник(g_oee))
    return _слайд("поток", данные, источники)


def _слайд_симуляция(прогоны, sravnit):
    """Слайд 4: база/сценарий. Метки «до»/«после» → дельта через sravnit
    (существующий механизм сравнения, сам сборщик ничего не пересчитывает)."""
    пара = _пара_до_после(прогоны, "simulation")
    if пара:
        g_a, g_b = пара
        дельта = sravnit("simulation", g_a["итоги"], g_b["итоги"])
        данные = {"база": dict(g_a["итоги"]),
                  "сценарий": dict(g_b["итоги"]),
                  "дельта": дельта,
                  "дисклеймер": ДИСКЛЕЙМЕР_СИМУЛЯЦИЯ}
        return _слайд("симуляция", данные, [_источник(g_a), _источник(g_b)])
    g = _последний(прогоны, "simulation")
    данные = {"база": dict(g["итоги"]),
              "сценарий": None,
              "дельта": None,
              "дисклеймер": ДИСКЛЕЙМЕР_СИМУЛЯЦИЯ}
    return _слайд("симуляция", данные, [_источник(g)])


def _слайд_мероприятия(g):
    """Слайд 5: сводка генератора мероприятий из итогов прогона + отчёт
    (разбор топ-5 по приоритету — вёрстка П3 из отчёта/итогов)."""
    данные = dict(g["итоги"])
    данные["отчёт_md"] = g.get("отчёт_md") or ""
    return _слайд("мероприятия", данные, [_источник(g)])


def _слайд_эффект(прогоны, sravnit):
    """Слайд 6: ЭЭ из итогов калькулятора; статусы/допущения — как в итогах,
    если инструмент их туда положил (Спека П1, п. 6.4)."""
    пара = _пара_до_после(прогоны, "ee")
    if пара:
        g_a, g_b = пара
        данные = dict(g_b["итоги"])
        данные["дельта"] = sravnit("ee", g_a["итоги"], g_b["итоги"])
        источники = [_источник(g_a), _источник(g_b)]
        база_для_статусов = g_b["итоги"]
    else:
        g = _последний(прогоны, "ee")
        данные = dict(g["итоги"])
        данные["дельта"] = None
        источники = [_источник(g)]
        база_для_статусов = g["итоги"]
    статусы = {k: база_для_статусов[k]
               for k in ("допущения", "статус", "статусы", "контекст_расходится")
               if k in база_для_статусов}
    if статусы:
        данные["статусы_допущения"] = статусы
    return _слайд("эффект", данные, источники)


def _слайд_план(g_smart, g_protokol):
    """Слайд 7: цели SMART списком + статус по протоколу закрытия."""
    данные, источники = {}, []
    if g_smart is not None:
        ит = g_smart["итоги"]
        данные["smart"] = {"рамка": ит.get("рамка"),
                           "целей": ит.get("целей"),
                           "обязательный_показатель_есть":
                               ит.get("обязательный_показатель_есть"),
                           "цели": ит.get("цели") or []}
        источники.append(_источник(g_smart))
    else:
        данные["smart"] = None
    if g_protokol is not None:
        ит = g_protokol["итоги"]
        данные["protokol"] = {"итого_баллов": ит.get("итого_баллов"),
                              "порог": ит.get("порог"),
                              "порог_пройден": ит.get("порог_пройден"),
                              "ээ_руб_год": ит.get("ээ_руб_год")}
        источники.append(_источник(g_protokol))
    else:
        данные["protokol"] = None
    return _слайд("план", данные, источники)


def _буллеты_выводов(слайды):
    """Слайд 8: 3–5 буллетов из ключевых чисел собранных слайдов —
    шаблонные фразы с подстановкой, без LLM (Спека П1, п. 9)."""
    по_коду = {s["код"]: s for s in слайды}
    буллеты = []
    if "проблема" in по_коду:
        d = по_коду["проблема"]["данные"]
        if d.get("главное_ум"):
            б = f"Главное узкое место потока — «{d['главное_ум']}»"
            if d.get("доля_впп_ум_пкт") is not None:
                б += f", доля во времени производственного потока — {_ч(d['доля_впп_ум_пкт'])} %"
            буллеты.append(б + ".")
    if "поток" in по_коду:
        п = по_коду["поток"]["данные"]["поток"]
        части = []
        if п.get("такт_мин") is not None:
            части.append(f"такт {_ч(п['такт_мин'])} мин/шт")
        if п.get("впп_мин") is not None:
            части.append(f"время производственного потока {_ч(п['впп_мин'])} мин")
        if части:
            буллеты.append("Показатели потока: " + ", ".join(части) + ".")
    if "симуляция" in по_коду:
        d = по_коду["симуляция"]["данные"]
        дельта = d.get("дельта")
        if дельта and (дельта.get("числа") or {}).get("выпуск_шт"):
            в = дельта["числа"]["выпуск_шт"]
            д = в.get("дельта")
            знак = f"{'+' if isinstance(d, (int, float)) and d >= 0 else ''}{_ч(д)}"
            буллеты.append(f"Сценарный прогон: выпуск {_ч(в['до'])} → {_ч(в['после'])} шт "
                           f"({знак} шт; модельный прогноз, не замер).")
        elif (d.get("база") or {}).get("выпуск_шт") is not None:
            буллеты.append(f"Модельный прогноз выпуска — {_ч(d['база']['выпуск_шт'])} шт "
                           "за горизонт (модельный прогноз, не замер).")
    if "мероприятия" in по_коду:
        d = по_коду["мероприятия"]["данные"]
        if d.get("мероприятий") is not None:
            б = f"План: {d['мероприятий']} мероприятий"
            if d.get("сумма_dEE_rub") is not None:
                б += (f", суммарный ожидаемый эффект "
                      f"{_ч(d['сумма_dEE_rub'])} руб/год")
            буллеты.append(б + ".")
    if "эффект" in по_коду:
        d = по_коду["эффект"]["данные"]
        if d.get("ээ") is not None:
            буллеты.append(f"Экономический эффект проекта — {_ч(d['ээ'])} руб/год.")
    return буллеты[:5]


def собрать(проект, прогоны, слайды=None, тема="бумага", титул=None, sravnit=None):
    """Собрать данные презентации по скелету спеки.

    проект  — dict карточки проекта (название, предприятие, поток, создан);
    прогоны — список dict {id, инструмент, итоги, отчёт_md, автор, дата, метка};
    слайды  — чек-лист кодов слайдов (None → все 8);
    тема    — «бумага» | «графит»;
    титул   — {предприятие, поток, автор} поверх карточки проекта;
    sravnit — существующий механизм сравнения прогонов (дельты «до/после»).

    Возвращает {"слайды": [...], "лог_сборки": [...], "тема": тема}.
    Слайд без данных не включается — строка в логе сборки (Спека П1, п. 7).
    """
    if тема not in ТЕМЫ:
        raise ValueError(f"неизвестная тема «{тема}»; доступны: {', '.join(ТЕМЫ)}")
    выбранные = ПОРЯДОК if слайды is None else [к for к in ПОРЯДОК if к in слайды]
    лог = []
    слайды_out = []

    def пропуск(код, причина):
        лог.append(f"слайд «{код}» пропущен: {причина}")

    for код in выбранные:
        if код == "титул":
            слайды_out.append(_слайд_титул(проект, титул))
        elif код == "проблема":
            g = _последний(прогоны, "uzkie_mesta")
            if g is None:
                пропуск(код, "нет прогона «uzkie_mesta»")
            else:
                слайды_out.append(_слайд_проблема(g))
        elif код == "поток":
            g = _последний(прогоны, "potok_calc")
            if g is None:
                пропуск(код, "нет прогона «potok_calc»")
            else:
                слайды_out.append(_слайд_поток(g, _последний(прогоны, "oee")))
        elif код == "симуляция":
            if _последний(прогоны, "simulation") is None:
                пропуск(код, "нет прогона «simulation»")
            else:
                слайды_out.append(_слайд_симуляция(прогоны, sravnit))
        elif код == "мероприятия":
            g = _последний(прогоны, "meropriyatiya")
            if g is None:
                пропуск(код, "нет прогона «meropriyatiya»")
            else:
                слайды_out.append(_слайд_мероприятия(g))
        elif код == "эффект":
            if _последний(прогоны, "ee") is None:
                пропуск(код, "нет прогона «ee»")
            else:
                слайды_out.append(_слайд_эффект(прогоны, sravnit))
        elif код == "план":
            g_smart = _последний(прогоны, "smart")
            g_protokol = _последний(прогоны, "protokol")
            if g_smart is None and g_protokol is None:
                пропуск(код, "нет прогонов «smart» и «protokol»")
            else:
                слайды_out.append(_слайд_план(g_smart, g_protokol))
        elif код == "выводы":
            буллеты = _буллеты_выводов(слайды_out)
            if len(буллеты) < 3:
                пропуск(код, "недостаточно собранных данных для выводов "
                        f"(опорных чисел меньше трёх, собрано {len(буллеты)})")
            else:
                слайды_out.append(_слайд("выводы",
                                         {"буллеты": буллеты,
                                          "финал": "Спасибо за внимание"},
                                         [ист for s in слайды_out
                                          for ист in s["источники"]]))
    return {"слайды": слайды_out, "лог_сборки": лог, "тема": тема}
