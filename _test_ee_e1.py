# -*- coding: utf-8 -*-
"""Регрессия ЭЭ-Инженер_Э1А (ломтик Э1-А): ядро ЭЭ-калькулятора v0.2 на ред. 4
(МР-13-2025, модель ФЦК v5.23).

Проверки:
  1. Новый золотой эталон «Пример расчета v5.23» — итоги и промежуточные
     величины по протоколу результатов/эталон_э1_пересчёт.md (до копеек);
  2. Архивные эталоны корпуса (4 кейса) — реальный ЭЭ не изменился;
  3. Дефолт налога на прибыль ред. 4 = 0,25;
  4. Цена ГП «после» (ред. 4): фактор «Цена ГП» в декомпозиции, сверка Σ = ЭЭ;
  5. Отказ: цена_изменилась = true без цена_ед_после;
  6. Сверхурочные → FTE (вложенная форма «после»); без фонда времени —
     предупреждение «FTE не считается»;
  7. Вес основного продукта — множитель фонда времени;
  8. Отрицательный потенциальный ЭЭ обнуляется (ядро G13);
  9. Идемпотентность: три прогона отчёта — байт-в-байт;
 10. Отложенный эффект запасов ЭЭзапг — отдельная строка отчёта.

Запуск: .venv/bin/python _test_ee_e1.py (сервер НЕ нужен — только ядро).
"""
import copy
import importlib.util
import json
import sys
from pathlib import Path

PROT = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("ee_kalk", PROT / "ээ_калькулятор.py")
ee = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ee)

результаты = []


def итог(имя, ок, пояс=""):
    результаты.append((имя, "PASS" if ок else "FAIL", пояс))
    print(f"[{'PASS' if ок else 'FAIL'}] {имя} {пояс}")


def окр(x):
    return round(x, 2)


# --- 1. Новый золотой эталон «Пример расчета v5.23» ---
d = json.loads((PROT / "данные_ээ_пример_v523.json").read_text(encoding="utf-8"))
errs = ee.validirovat(d)
итог("эталон v523: валидация без ошибок", not errs, "; ".join(errs[:2]))
r = ee.raschet(d)
итог("эталон v523: ЭЭреал = 11 261 156,71", окр(r["ээ"]) == 11261156.71,
     f"факт {ee.rub(r['ээ'])}")
итог("эталон v523: ЭЭпот = 2 010 025,66", окр(r["ээ_пот"]) == 2010025.66,
     f"факт {ee.rub(r['ээ_пот'])}")
итог("эталон v523: высвобождение = 705 000,00", окр(r["высвоб"]) == 705000.00,
     f"факт {ee.rub(r['высвоб'])}")
итог("эталон v523: отложенный ЭЭзапг = 42 300,00", окр(r["ээ_запг"]) == 42300.00,
     f"факт {ee.rub(r['ээ_запг'])}")
итог("эталон v523: налоги за 3 года = 13 596 144,77", окр(r["налоги"]) == 13596144.77,
     f"факт {ee.rub(r['налоги'])}")
# промежуточные величины (п. 5.3 спеки Э1 — сверяется не только итог)
пром = (abs(r["v1"] - 355680 / 85) < 1e-9 and окр(r["v2"]) == 5472.00
        and окр(r["с2"]) == 2592.05 and окр(r["дмп"]) == 8583795.39
        and окр(r["ф_брак"]) == 746510.11 and окр(r["з1"] - r["з2"]) == 1488551.20
        and окр(r["ф_объёмы"]) == 4780465.38 and окр(r["ф_нормы"]) == 3803330.02)
итог("эталон v523: промежуточные величины по протоколу", пром,
     f"v1={r['v1']:.6f} с2={r['с2']:.3f} дмп={r['дмп']:.2f} брак={r['ф_брак']:.2f}")
итог("эталон v523: сверка декомпозиции Σ = ЭЭ", abs(r["сверка"]["расх"]) <= 0.01,
     f"расхождение {r['сверка']['расх']}")

# --- 2. Архивные эталоны корпуса — реальный ЭЭ не изменился ---
эталоны = {"новохром": 23757960.67, "строгонов": 11480819.11,
           "оренбив": 8350501.24, "атэна": 9267933.87}
for кейс, эталон in эталоны.items():
    da = json.loads((PROT / f"данные_ээ_{кейс}.json").read_text(encoding="utf-8"))
    ra = ee.raschet(da)
    итог(f"архив {кейс}: ЭЭреал = {эталон:,.2f}".replace(",", " "),
         окр(ra["ээ"]) == эталон, f"факт {ee.rub(ra['ээ'])}")

# --- 3. Дефолт налога на прибыль ред. 4 = 0,25 ---
мин = {"тцикл_мин": {"до": 10, "после": 8}, "ттакт_мин": {"до": 9, "после": 9},
       "время_мин_год": {"до": 100000, "после": 100000},
       "цена_ед": 100, "перем_сс_ед": 60}
r3 = ee.raschet(мин)
итог("дефолт налога на прибыль = 25 %", r3["константы"]["нприб"] == 0.25,
     f"факт {r3['константы']['нприб']}")
итог("налоги считаются по 25 %",
     окр(r3["налоги"]) == окр((r3["ээ"] * 0.25 + r3["дмп"] * 0.2) * 3),
     f"факт {ee.rub(r3['налоги'])}")

# --- 4. Цена ГП «после» (ред. 4): фактор «Цена ГП», сверка Σ = ЭЭ ---
d4 = copy.deepcopy(d)
d4["цена_изменилась"] = True
d4["цена_ед_после"] = 7500
r4 = ee.raschet(d4)
итог("цена после: фактор «Цена ГП» = 500 × 5 472 = 2 736 000",
     окр(r4["ф_цена"]) == 2736000.00, f"факт {ee.rub(r4['ф_цена'])}")
итог("цена после: ЭЭреал вырос ровно на фактор цены",
     окр(r4["ээ"]) == окр(r["ээ"] + 2736000.00), f"факт {ee.rub(r4['ээ'])}")
итог("цена после: сверка декомпозиции сходится", abs(r4["сверка"]["расх"]) <= 0.01,
     f"расхождение {r4['сверка']['расх']}")

# --- 5. Отказ: цена_изменилась = true без цена_ед_после ---
d5 = copy.deepcopy(d)
d5["цена_изменилась"] = True
d5.pop("цена_ед_после", None)
errs5 = ee.validirovat(d5)
итог("цена после: отказ при пустой цене «после»",
     any("цена_ед_после" in e for e in errs5), "; ".join(errs5[:1]))

# --- 6. Сверхурочные → FTE ---
d6 = copy.deepcopy(d)
d6["постоянные"]["сверхурочные"] = {"после": {"чг_15": 1976, "чг_20": 0}}
r6 = ee.raschet(d6)
итог("сверхурочные: FTE «после» = 1976/1976×1,5 = 1,5 чел",
     окр(r6.get("fte2") or 0) == 1.50, f"факт {r6.get('fte2')}")
итог("сверхурочные: эффект ФОТ = (20 − 19,5) × 20 000 × 12 × 1,3 = 156 000",
     окр(r6["ф_фот"]) == 156000.00, f"факт {ee.rub(r6['ф_фот'])}")
итог("сверхурочные: ЭЭреал = эталон − 468 000",
     окр(r6["ээ"]) == окр(r["ээ"] - 468000.00), f"факт {ee.rub(r6['ээ'])}")
d6b = copy.deepcopy(d6)
del d6b["фонд_времени"]
r6b = ee.raschet(d6b)
итог("сверхурочные без фонда времени: предупреждение «FTE не считается»",
     any("FTE не считается" in w for w in r6b["предупр"]),
     "; ".join(r6b["предупр"][:1]))

# --- 7. Вес основного продукта ---
d7 = copy.deepcopy(d)
d7["вес_основного_продукта"] = 0.5
r7 = ee.raschet(d7)
итог("вес продукта 0,5: объём «до» уменьшен вдвое",
     abs(r7["v1"] - 355680 / 85 / 2) < 1e-9, f"факт {r7['v1']:.6f}")

# --- 8. Отрицательный потенциальный ЭЭ обнуляется ---
d8 = copy.deepcopy(d)
d8["цена_изменилась"] = True
d8["цена_ед_после"] = 2000  # ниже С₂ = 2 592,049 → маржа «после» отрицательная
r8 = ee.raschet(d8)
итог("отрицательный потенциальный обнуляется (G13)", r8["ээ_пот"] == 0.0,
     f"факт {ee.rub(r8['ээ_пот'])}")

# --- 9. Идемпотентность: три прогона байт-в-байт ---
отчёты = [ee.otchyot(d, ee.raschet(d)) for _ in range(3)]
итог("идемпотентность: 3 прогона идентичны",
     отчёты[0] == отчёты[1] == отчёты[2])

# --- 10. Отложенный эффект запасов — отдельная строка отчёта ---
отч = ee.otchyot(d, r)
итог("отчёт: строка «Отложенный эффект запасов» с 42 300,00",
     "Отложенный эффект запасов последующих лет" in отч and "42 300,00" in отч)

print()
плохие = [x for x in результаты if x[1] != "PASS"]
print(f"ИТОГО: {len(результаты) - len(плохие)}/{len(результаты)} PASS")
for x in плохие:
    print("ПРОВАЛ:", x)
sys.exit(1 if плохие else 0)
