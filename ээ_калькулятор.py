# ---------- Форматирование (русские деньги и числа) ----------

def rub(x, kop=True):
    """12 345 678,90 — разряды пробелами, копейки через запятую.
    Подавляет «-0,00» от float-остатков: |x| < полкопейки → +0."""
    if abs(x) < 0.005:
        x = 0.0
    nd = 2 if kop else 0
    s = f"{x:,.{nd}f}".replace(",", " ").replace(".", ",")
    return s


def num(x):
    """Число без денежного формата: 8 967,15."""
    if abs(x - round(x)) < 1e-9:
        return f"{int(round(x)):,}".replace(",", " ")
    return f"{x:,.2f}".replace(",", " ").replace(".", ",")


def pct(d):
    return num(d * 100) + " %"


# ---------- Валидация входа ----------

def _число(v):
    """Число (не bool), конечное — фикс У-1/У-3: NaN/inf не проходят валидацию."""
    return (isinstance(v, (int, float)) and not isinstance(v, bool)
            and math.isfinite(v))


def validirovat(d):
    """Жёсткие отказы. Ошибки — по-русски, с указанием секции и поля."""
    oshibki = []

    def пара(секция, поле, обяз=True, мин=0, строго_больше=0):
        v = d.get(секция, {})
        if not isinstance(v, dict):
            if обяз:
                oshibki.append(f"секция «{секция}»: должна быть объектом {{\"до\":…, \"после\":…}}")
            return None, None
        a, b = v.get("до"), v.get("после")
        for метка, x in (("до", a), ("после", b)):
            if x is None:
                if обяз:
                    oshibki.append(f"секция «{секция}», поле «{метка}»: не заполнено")
            elif not _число(x):
                oshibki.append(f"секция «{секция}», поле «{метка}»: «{x}» — не число")
            elif x < мин or (строго_больше is not None and x <= строго_больше):
                oshibki.append(f"секция «{секция}», поле «{метка}»: должно быть числом "
                               f"больше {строго_больше}")
        return a, b

    тц = пара("тцикл_мин", None)
    тт = пара("ттакт_мин", None)
    for секция in ("время_мин_год",):
        v = d.get(секция)
        if v is not None:
            пара(секция, None)
    # Альтернативный вход «фонд_времени»: если объект присутствует,
    # все три значения (смены, часы, дни) обязаны быть числами > 0
    ф = d.get("фонд_времени")
    if ф is not None:
        if not isinstance(ф, dict):
            oshibki.append("секция «фонд_времени»: должна быть объектом "
                           "{\"смены\":…, \"часы\":…, \"дни\":…}")
        else:
            for поле in ("смены", "часы", "дни"):
                v = ф.get(поле)
                if v is None:
                    oshibki.append(f"секция «фонд_времени», поле «{поле}»: не заполнено")
                elif not _число(v) or v <= 0:
                    oshibki.append(f"секция «фонд_времени», поле «{поле}»: должно быть "
                                   f"числом больше 0, получено «{v}»")
    if d.get("время_мин_год") is None and d.get("фонд_времени") is None:
        oshibki.append("секция «время_мин_год» или «фонд_времени»: нужен годовой фонд "
                       "времени (мин/год) до и после — либо тройка смены×часы×дни")

    for поле, имя in (("цена_ед", "цена единицы продукции"),
                      ("перем_сс_ед", "переменная себестоимость единицы")):
        v = d.get(поле)
        if v is None:
            oshibki.append(f"поле «{поле}» ({имя}): не заполнено")
        elif not _число(v) or v <= 0:
            oshibki.append(f"поле «{поле}» ({имя}): должно быть числом больше 0")

    # Нормы: неотрицательные; сумма эффектов не выше с/с «до»
    нормы = d.get("нормы") or {}
    eff = 0.0
    for вид, спец in (("сырье", ("норма_до", "норма_после", "цена")),
                      ("труд", ("трудоемкость_до", "трудоемкость_после", "ставка")),
                      ("электроэнергия", ("норма_до", "норма_после", "тариф")),
                      ("вода", ("норма_до", "норма_после", "тариф")),
                      ("газ", ("норма_до", "норма_после", "тариф")),
                      ("тепло", ("норма_до", "норма_после", "тариф"))):
        б = нормы.get(вид)
        if not б:
            continue
        for k in спец:
            v = б.get(k)
            if v is not None and (not _число(v) or v < 0):
                oshibki.append(f"секция «нормы → {вид}», поле «{k}»: должно быть "
                               f"неотрицательным числом")
        try:
            if вид == "труд":
                eff += ((б.get("трудоемкость_до") or 0) - (б.get("трудоемкость_после") or 0)) \
                       * (б.get("ставка") or 0)
            else:
                eff += ((б.get("норма_до") or 0) - (б.get("норма_после") or 0)) \
                       * (б.get("цена") or б.get("тариф") or 0)
        except TypeError:
            pass
    if _число(d.get("перем_сс_ед")) and eff > d["перем_сс_ед"]:
        oshibki.append("секция «нормы»: сумма эффектов по нормам "
                       f"({rub(eff)} руб/ед) больше переменной себестоимости "
                       f"({rub(d['перем_сс_ед'])} руб/ед) — удельная с/с «после» "
                       f"ушла бы в минус")

    # Брак и ставки
    бр = (d.get("прочее") or {}).get("брак_доля") or {}
    for метка in ("до", "после"):
        v = бр.get(метка)
        if v is not None and (not _число(v) or not 0 <= v < 1):
            oshibki.append(f"секция «прочее → брак_доля», поле «{метка}»: доля брака "
                           f"должна быть в [0; 1), получено «{v}»")
    к = d.get("константы") or {}
    for поле, имя in (("ключевая_ставка", "ключевая ставка ЦБ"),
                      ("ндс", "ставка НДС"), ("налог_прибыль", "налог на прибыль")):
        v = к.get(поле)
        if v is not None and (not _число(v) or not 0 <= v <= 1):
            oshibki.append(f"секция «константы», поле «{поле}» ({имя}): должна быть "
                           f"долей в [0; 1], получено «{v}»")
    v = к.get("соцотчисления")
    if v is not None and (not _число(v) or v < 1):
        oshibki.append("секция «константы», поле «соцотчисления»: множитель не может "
                       "быть меньше 1")

    for з in ("сим", "гп", "нзп"):
        б = (d.get("запасы_руб") or {}).get(з) or {}
        for метка in ("до", "после"):
            v = б.get(метка)
            if v is not None and (not _число(v) or v < 0):
                oshibki.append(f"секция «запасы_руб → {з}», поле «{метка}»: должно быть "
                               f"неотрицательным числом")

    # --- Ред. 4 (МР-13-2025 / v5.23): новые поля входа ---
    # Цена ГП «после»: флаг «цена_изменилась» = true требует значения (чек-лист G70/H87)
    ц_изм = d.get("цена_изменилась")
    ц_после = d.get("цена_ед_после")
    if ц_изм is not None and not isinstance(ц_изм, bool):
        oshibki.append("поле «цена_изменилась»: должно быть true/false")
    if ц_после is not None and (not _число(ц_после) or ц_после <= 0):
        oshibki.append(f"поле «цена_ед_после»: должно быть числом больше 0, "
                       f"получено «{ц_после}»")
    if ц_изм is True and ц_после is None:
        oshibki.append("секция «цены»: «цена_изменилась» = true, но «цена_ед_после» "
                       "не задана — домерить цену после проекта")
    # Вес основного продукта (чек-лист G72, множитель фонда времени)
    в = d.get("вес_основного_продукта")
    if в is not None and (not _число(в) or в <= 0):
        oshibki.append(f"поле «вес_основного_продукта»: должно быть числом больше 0, "
                       f"получено «{в}»")
    # Сверхурочные (лист «Сверхурочные»: часы в год по ставкам 1,5 и 2,0)
    св = (d.get("постоянные") or {}).get("сверхурочные")
    if св is not None:
        if not isinstance(св, dict):
            oshibki.append("секция «постоянные → сверхурочные»: должна быть объектом "
                           "{\"чг_15\":…, \"чг_20\":…} (или {\"до\":…, \"после\":…})")
        else:
            блоки = [св] + [б for б in (св.get("до"), св.get("после"))
                            if isinstance(б, dict)]
            for б in блоки:
                for k in ("чг_15", "чг_20"):
                    x = б.get(k)
                    if x is not None and (not _число(x) or x < 0):
                        oshibki.append(f"секция «постоянные → сверхурочные», поле «{k}»: "
                                       f"должно быть неотрицательным числом, получено «{x}»")
    return oshibki


# ---------- Расчётное ядро (модель ФЦК, концевой серийный поток) ----------

def raschet(d):
    r = {"расчёты": [], "домерить": [], "предупр": []}
    R = r["расчёты"].append

    if (d.get("тип_потока") or "концевой_серийный") != "концевой_серийный":
        r["отказ"] = ("ветка потока «" + str(d.get("тип_потока")) + "» не входит в контур "
                      "инструмента (только концевой серийный поток — спека Э1, п. 7)")
        return r

    к = d.get("константы") or {}
    соц = к.get("соцотчисления", SOC_DEF)
    ндс = к.get("ндс", NDS_DEF)
    нприб = к.get("налог_прибыль", NPRIB_DEF)
    кс_цб = к.get("ключевая_ставка")
    r["константы"] = {"соц": соц, "ндс": ндс, "нприб": нприб, "кс_цб": кс_цб}

    # --- Годовой фонд времени (мин/год), × вес основного продукта (ред. 4: D81) ---
    вес = d.get("вес_основного_продукта")
    if not _число(вес) or вес <= 0:
        вес = None

    def фонд(метка):
        в = (d.get("время_мин_год") or {}).get(метка)
        if _число(в):
            т = в
            пояс = f"время производства годной продукции ({метка}) = {num(в)} мин/год"
        else:
            ф = d.get("фонд_времени") or {}
            if all(_число(ф.get(k)) for k in ("смены", "часы", "дни")):
                т = ф["смены"] * ф["часы"] * ф["дни"] * 60
                пояс = (f"Т ({метка}) = Кс × Крч × Крд × 60 = {num(ф['смены'])} × "
                        f"{num(ф['часы'])} × {num(ф['дни'])} × 60 = {num(т)} мин/год")
            else:
                return None, None
        if вес is not None and вес != 1:
            пояс += (f"; × вес основного продукта {num(вес)} = {num(т * вес)} мин/год "
                     f"(чек-лист D81/E81, ред. 4)")
            т = т * вес
        return т, пояс

    т1, пояс1 = фонд("до")
    т2, пояс2 = фонд("после")
    if пояс1:
        R(пояс1)
    if пояс2:
        R(пояс2)

    тц1, тц2 = d["тцикл_мин"]["до"], d["тцикл_мин"]["после"]
    тт1, тт2 = d["ттакт_мин"]["до"], d["ттакт_мин"]["после"]

    # Связка флага спроса с Тцикл/Ттакт (состояние «до») — предупреждение, не отказ
    флаг_спрос = d.get("спрос_превышает_возможности")
    if isinstance(флаг_спрос, bool):
        if флаг_спрос and тц1 < тт1:
            r["предупр"].append(
                "флаг «спрос_превышает_возможности» = да, но «до» Тцикл "
                f"({num(тц1)} мин) < Ттакт ({num(тт1)} мин) — по связке спрос "
                "ограничивает объём, а не возможности производства; проверьте вход")
        elif not флаг_спрос and тт1 < тц1:
            r["предупр"].append(
                "флаг «спрос_превышает_возможности» = нет, но «до» Ттакт "
                f"({num(тт1)} мин) < Тцикл ({num(тц1)} мин) — по связке спрос "
                "превышает возможности производства; проверьте вход")
    цена, с1 = d["цена_ед"], d["перем_сс_ед"]
    # Ред. 4: цена ГП «после» может отличаться (чек-лист G70/H87; ядро F77);
    # дефолт методики — цена «после» = «до» (исключение ценового фактора)
    цена2 = цена
    if d.get("цена_изменилась") is True and _число(d.get("цена_ед_после")):
        цена2 = d["цена_ед_после"]
        R(f"Цена ГП изменена проектом: {rub(цена)} → {rub(цена2)} руб/ед "
          f"(чек-лист G70 = «да», ядро F77 = H87)")
    r["цена2"] = цена2

    # --- Удельная с/с «после»: эффекты норм (ядро E26/E29/E33…, соц 1.3) ---
    нормы = d.get("нормы") or {}
    эфф_норм = {}
    б = нормы.get("сырье") or {}
    if any(б.get(k) for k in ("норма_до", "норма_после")):
        э = ((б.get("норма_до") or 0) - (б.get("норма_после") or 0)) * (б.get("цена") or 0)
        эфф_норм["сырьё"] = э
        R(f"Эффект нормы сырья = (Мр₁ − Мр₂) × Цена = ({num(б.get('норма_до') or 0)} − "
          f"{num(б.get('норма_после') or 0)}) × {rub(б.get('цена') or 0)} = {rub(э)} руб/ед "
          f"(ядро E26 = E27 × E28)")
    б = нормы.get("труд") or {}
    if any(б.get(k) for k in ("трудоемкость_до", "трудоемкость_после")):
        э = ((б.get("трудоемкость_до") or 0) - (б.get("трудоемкость_после") or 0)) \
            * (б.get("ставка") or 0) * соц
        эфф_норм["ФОТ сдельный"] = э
        R(f"Эффект трудоёмкости = (Тр₁ − Тр₂) × Ставка × Соц = "
          f"({num(б.get('трудоемкость_до') or 0)} − {num(б.get('трудоемкость_после') or 0)}) × "
          f"{rub(б.get('ставка') or 0)} × {num(соц)} = {rub(э)} руб/ед (ядро E29 = E30×E31×E32)")
    for вид, имя in (("электроэнергия", "электроэнергия"), ("вода", "вода"),
                     ("газ", "газ"), ("тепло", "теплоэнергия")):
        б = нормы.get(вид) or {}
        if any(б.get(k) for k in ("норма_до", "норма_после")):
            э = ((б.get("норма_до") or 0) - (б.get("норма_после") or 0)) * (б.get("тариф") or 0)
            эфф_норм[имя] = э
            R(f"Эффект нормы ({имя}) = ({num(б.get('норма_до') or 0)} − "
              f"{num(б.get('норма_после') or 0)}) × {rub(б.get('тариф') or 0)} = {rub(э)} руб/ед")

    сумма_норм = sum(эфф_норм.values())
    с2 = с1 - сумма_норм
    if сумма_норм:
        R(f"Удельная с/с «после»: С₂ = С₁ − Σ эффектов норм = {rub(с1)} − {rub(сумма_норм)} "
          f"= {rub(с2)} руб/ед (ядро F79)")
    else:
        R(f"Удельная с/с «после» = «до» = {rub(с2)} руб/ед (нормы не менялись)")
    r["с2"] = с2

    # --- Объёмы реализации (чек-лист D77: Ттакт<Тцикл → Т/Тцикл, иначе Т/Ттакт) ---
    def объём(т, тц, тт, метка):
        if т is None:
            return None, None
        базис, имя_базиса = (тц, "Тцикл") if тт < тц else (тт, "Тнеобх.такт")
        v = т / базис
        return v, (f"V ({метка}) = Т / {имя_базиса} = {num(т)} / {num(базис)} = {num(v)} ед/год "
                   f"({'спрос ограничивает' if имя_базиса == 'Тнеобх.такт' else 'производство ограничивает'})")

    v1, пояс = объём(т1, тц1, тт1, "до")
    if пояс:
        R(пояс)
    v2, пояс = объём(т2, тц2, тт2, "после")
    if пояс:
        R(пояс)
    r["v1"], r["v2"] = v1, v2

    if v1 is None or v2 is None:
        r["домерить"].append("годовой фонд времени (мин/год) до и после → объёмы, "
                             "выручку, маржинальную прибыль и реальный ЭЭ")
        return r

    # Валидатор: расчётный объём «до» vs заявленный факт первичного сбора (±10 %)
    факт = d.get("объем_реализации_факт")
    if _число(факт) and факт > 0:
        откл = (v1 - факт) / факт * 100
        if abs(откл) > 10:
            r["предупр"].append(
                f"расчётный объём «до» {num(v1)} ед расходится с заявленным фактом "
                f"первичного сбора {num(факт)} ед на {num(откл)} % (допуск 10 %) — "
                f"модель считает по расчётному объёму, проверьте Тцикл/такт/время")
        else:
            R(f"Сверка объёма «до»: расчётный {num(v1)} ед vs факт {num(факт)} ед — "
              f"отклонение {num(откл)} % (в допуске 10 %)")

    # --- Выручка, переменные, маржинальная прибыль ---
    в1, в2 = v1 * цена, v2 * цена2
    пз1, пз2 = v1 * с1, v2 * с2
    мп1, мп2 = в1 - пз1, в2 - пз2
    дмп = мп2 - мп1
    R(f"Выручка «до»: В₁ = V₁ × Ц = {num(v1)} × {rub(цена)} = {rub(в1)} руб (ядро E71)")
    R(f"Выручка «после»: В₂ = V₂ × Ц₂ = {num(v2)} × {rub(цена2)} = {rub(в2)} руб (ядро F71)")
    R(f"Переменные «до»: ПЗ₁ = V₁ × С₁ = {num(v1)} × {rub(с1)} = {rub(пз1)} руб")
    R(f"Переменные «после»: ПЗ₂ = V₂ × С₂ = {num(v2)} × {rub(с2)} = {rub(пз2)} руб")
    R(f"МП₁ = В₁ − ПЗ₁ = {rub(в1)} − {rub(пз1)} = {rub(мп1)} руб (ядро E12)")
    R(f"МП₂ = В₂ − ПЗ₂ = {rub(в2)} − {rub(пз2)} = {rub(мп2)} руб (ядро F12)")
    R(f"ΔМП = МП₂ − МП₁ = {rub(мп2)} − {rub(мп1)} = {rub(дмп)} руб (ядро G12)")
    r["мп1"], r["мп2"], r["дмп"] = мп1, мп2, дмп
    r["в1"], r["в2"], r["пз1"], r["пз2"] = в1, в2, пз1, пз2

    # Декомпозиция ΔМП по J-логике v5.23: объёмы × маржа «до» (J72),
    # цена ГП × объём «после» (J74), нормы × объём «после» (J73 = Δуд.маржи × F72 − J74).
    # Тождество: J72 + J74 + J73 = ΔМП при любом цена2.
    ф_объёмы = (v2 - v1) * (цена - с1)
    ф_цена = (цена2 - цена) * v2
    ф_нормы = v2 * (с1 - с2)
    # Детализация норм по статьям (J75/J76/J77 — Δудельной статьи × объём «после»)
    ф_нормы_сим = эфф_норм.get("сырьё", 0.0) * v2
    ф_нормы_фот = эфф_норм.get("ФОТ сдельный", 0.0) * v2
    ф_нормы_тэр = sum(зн for имя, зн in эфф_норм.items()
                      if имя not in ("сырьё", "ФОТ сдельный")) * v2
    r["ф_объёмы"] = ф_объёмы
    r["ф_цена"] = ф_цена
    r["ф_нормы"] = ф_нормы
    r["ф_нормы_сим"], r["ф_нормы_фот"], r["ф_нормы_тэр"] = ф_нормы_сим, ф_нормы_фот, ф_нормы_тэр
    R(f"Декомпозиция ΔМП: объёмы = (V₂ − V₁) × (Ц − С₁) = ({num(v2)} − {num(v1)}) × "
      f"({rub(цена)} − {rub(с1)}) = {rub(ф_объёмы)} руб (ядро J72)")
    if ф_цена:
        R(f"Декомпозиция ΔМП: цена ГП = (Ц₂ − Ц₁) × V₂ = ({rub(цена2)} − {rub(цена)}) × "
          f"{num(v2)} = {rub(ф_цена)} руб (ядро J74)")
    if сумма_норм:
        R(f"Декомпозиция ΔМП: нормы = (С₁ − С₂) × V₂ = {rub(с1 - с2)} × {num(v2)} "
          f"= {rub(ф_нормы)} руб (ядро J73; СиМ {rub(ф_нормы_сим)} + сдельный ФОТ "
          f"{rub(ф_нормы_фот)} + ТЭР {rub(ф_нормы_тэр)})")

    # --- Постоянные расходы (ядро E135 = E136 + E137 + E141) ---
    п = d.get("постоянные") or {}
    з1 = з2 = 0.0
    есть_пост = False
    ф_ремонт = ф_фот = ф_комм = 0.0
    б = п.get("ремонт") or {}
    if any(_число(б.get(k)) and б.get(k) for k in ("до", "после")):
        есть_пост = True
        з1 += б.get("до") or 0
        з2 += б.get("после") or 0
        ф_ремонт = (б.get("до") or 0) - (б.get("после") or 0)
        R(f"Ремонт: {rub(б.get('до') or 0)} → {rub(б.get('после') or 0)} руб/год, "
          f"эффект = {rub(ф_ремонт)} руб (ядро E136/F136)")
    б = п.get("персонал_оклад") or {}
    # Ред. 4: сверхурочные → FTE (лист «Сверхурочные» D9–D17; МР-13-2025 п. 5.7.3).
    # Плоская форма {"чг_15", "чг_20"} — одни часы на оба периода; вложенная
    # {"до": {...}, "после": {...}} — раздельно. ФРВ — фонд часов на человека в год.
    св = п.get("сверхурочные") or {}

    def _св_часы(метка):
        бс = св.get(метка)
        if isinstance(бс, dict):
            return (бс.get("чг_15") or 0) or 0.0, (бс.get("чг_20") or 0) or 0.0
        return (св.get("чг_15") or 0) or 0.0, (св.get("чг_20") or 0) or 0.0

    есть_св = isinstance(св, dict) and bool(св) and any(
        _число(x) and x for x in _св_часы("до") + _св_часы("после"))
    if есть_св and not any(_число(б.get(k)) and б.get(k) for k in ("чел_до", "чел_после")):
        r["предупр"].append("сверхурочные заданы без базовой численности окладного "
                            "персонала — FTE не считается (спека Э1, п. 5.2)")
        есть_св = False
    фрв = None
    _ф = d.get("фонд_времени") or {}
    if all(_число(_ф.get(k)) for k in ("часы", "дни")):
        фрв = _ф["часы"] * _ф["дни"]
    if есть_св and фрв is None:
        r["предупр"].append("сверхурочные заданы без «фонд_времени» (нужны часы × дни "
                            "на человека в год) — FTE не считается (спека Э1, п. 5.2)")
        есть_св = False
    if any(_число(б.get(k)) and б.get(k) for k in ("чел_до", "чел_после")):
        if not _число(б.get("зп_мес")) or not б.get("зп_мес"):
            r["домерить"].append("среднемесячную ЗП персонала на окладе → эффект "
                                 "оптимизации окладного ФОТ")
        else:
            есть_пост = True
            fte1 = fte2 = 0.0
            if есть_св:
                чг15_1, чг20_1 = _св_часы("до")
                чг15_2, чг20_2 = _св_часы("после")
                fte1 = чг15_1 / фрв * 1.5 + чг20_1 / фрв * 2.0
                fte2 = чг15_2 / фрв * 1.5 + чг20_2 / фрв * 2.0
                R(f"Сверхурочные в FTE: ФРВ = {num(_ф['часы'])} ч × {num(_ф['дни'])} дн = "
                  f"{num(фрв)} ч/год на человека; «до» Чг1,5/ФРВ×1,5 + Чг2,0/ФРВ×2,0 = "
                  f"+{num(fte1)} чел, «после» +{num(fte2)} чел (лист «Сверхурочные» "
                  f"D9–D17; МР-13-2025 п. 5.7.3)")
            п1ф = (б.get("чел_до") or 0) + fte1
            п2ф = (б.get("чел_после") or 0) + fte2
            ф1 = п1ф * б["зп_мес"] * 12 * соц
            ф2 = п2ф * б["зп_мес"] * 12 * соц
            з1 += ф1
            з2 += ф2
            ф_фот = ф1 - ф2
            r["fte1"], r["fte2"] = fte1, fte2
            R(f"ФОТ окладный «до»: {num(п1ф)} чел (FTE) × {rub(б['зп_мес'])} руб/мес "
              f"× 12 × {num(соц)} = {rub(ф1)} руб/год; «после»: {num(п2ф)} чел → "
              f"{rub(ф2)} руб/год; эффект = {rub(ф_фот)} руб (ядро E137 = E138×E139×12×E140)")
    for кб in п.get("коммуналка") or []:
        if any(_число(кб.get(k)) and кб.get(k) for k in ("объем_до", "объем_после")):
            if not _число(кб.get("тариф")):
                r["домерить"].append(f"тариф постоянной коммуналки «{кб.get('вид', '?')}» "
                                     f"→ эффект постоянных энергоресурсов")
                continue
            есть_пост = True
            к1 = (кб.get("объем_до") or 0) * кб["тариф"]
            к2 = (кб.get("объем_после") or 0) * кб["тариф"]
            з1 += к1
            з2 += к2
            ф_комм += к1 - к2
            R(f"Коммуналка «{кб.get('вид', '?')}»: {num(кб.get('объем_до') or 0)} × "
              f"{rub(кб['тариф'])} = {rub(к1)} → {rub(к2)} руб/год (ядро E141)")
    if есть_пост:
        R(f"Зпост: {rub(з1)} → {rub(з2)} руб/год; эффект = {rub(з1 - з2)} руб (ядро G135)")
    r["з1"], r["з2"] = з1, з2
    r["ф_ремонт"], r["ф_фот"], r["ф_комм"] = ф_ремонт, ф_фот, ф_комм

    # --- Прочие доходы/расходы: брак, аренда, прочий эффект ---
    пр = d.get("прочее") or {}
    эфф_брак = 0.0
    бр = пр.get("брак_доля") or {}
    б1, б2 = бр.get("до"), бр.get("после")
    if _число(б1) and _число(б2) and б1 != б2:
        эфф_брак = (б1 - б2) * v2 / (1 - б2) * с2
        R(f"Эффект брака = (Б₁ − Б₂) × Орп₂ / (1 − Б₂) × Пр₂ = ({pct(б1)} − {pct(б2)}) × "
          f"{num(v2)} / (1 − {pct(б2)}) × {rub(с2)} = {rub(эфф_брак)} руб (ядро F161 v5.23: "
          f"Орп₂ = объём реализации «после», Пр₂ = уд. переменные «после»; "
          f"только неисправимый брак, МР-13-2025 разд. 7)")
    elif _число(б1) != _число(б2) or (б1 is None) != (б2 is None):
        r["домерить"].append("долю неисправимого брака до И после → эффект снижения брака")
    r["ф_брак"] = эфф_брак

    ар_реал = ар_пот = 0.0
    ар = пр.get("аренда") or {}
    if _число(ар.get("площадь_м2")) and ар.get("площадь_м2"):
        if _число(ар.get("ставка_реальная")) and ар.get("ставка_реальная"):
            ар_реал = ар["площадь_м2"] * ар["ставка_реальная"]
            R(f"Аренда (реальная) = {num(ар['площадь_м2'])} м² × {rub(ар['ставка_реальная'])} "
              f"руб/м²·год = {rub(ар_реал)} руб (ядро F157/F159)")
        if _число(ар.get("ставка_потенциальная")) and ар.get("ставка_потенциальная"):
            ар_пот = ар["площадь_м2"] * ар["ставка_потенциальная"]
            R(f"Аренда (потенциальная) = {num(ар['площадь_м2'])} м² × "
              f"{rub(ар['ставка_потенциальная'])} руб/м²·год = {rub(ар_пот)} руб (ядро F160)")
        if not ар_реал and not ар_пот:
            r["домерить"].append("ставку аренды (реальную и/или потенциальную) → эффект "
                                 "высвобождения площадей")
    проч_реал = проч_пот = 0.0
    if _число(пр.get("прочий_эффект_руб")) and пр.get("прочий_эффект_руб"):
        if пр.get("прочий_реальный", True):
            проч_реал = пр["прочий_эффект_руб"]
        else:
            проч_пот = пр["прочий_эффект_руб"]
        R(f"Прочий эффект ({'реальный' if проч_реал else 'потенциальный'}): "
          f"{rub(проч_реал or проч_пот)} руб (чек-лист G183/G184)")
    r["ар_реал"], r["ар_пот"], r["проч_реал"], r["проч_пот"] = ар_реал, ар_пот, проч_реал, проч_пот

    # --- Рабочий капитал (ядро E168, G166, F167) ---
    зап = d.get("запасы_руб") or {}
    рк1 = рк2 = 0.0
    есть_запасы = False
    for з, имя in (("сим", "сырьё и материалы"), ("гп", "готовая продукция"),
                   ("нзп", "НЗП")):
        б = зап.get(з) or {}
        if _число(б.get("до")) or _число(б.get("после")):
            есть_запасы = True
            рк1 += б.get("до") or 0
            рк2 += б.get("после") or 0
            R(f"Запасы ({имя}): {rub(б.get('до') or 0)} → {rub(б.get('после') or 0)} руб")
    высвоб = рк1 - рк2
    эфф_зап = 0.0
    if есть_запасы:
        R(f"РК = Σ запасов: {rub(рк1)} → {rub(рк2)} руб (ядро E168; ДЗ/КЗ в модели = 0)")
        R(f"Высвобождение ДС = РК₁ − РК₂ = {rub(рк1)} − {rub(рк2)} = {rub(высвоб)} руб "
          f"(ядро G166)")
        if высвоб:
            if _число(кс_цб):
                эфф_зап = высвоб * кс_цб
                R(f"Эффект запасов (годовой) = {rub(высвоб)} × КС ЦБ {pct(кс_цб)} = "
                  f"{rub(эфф_зап)} руб (ядро F167; МР-13-2025 п. 5.4)")
            else:
                r["домерить"].append("ключевую ставку ЦБ (константы → ключевая_ставка) → "
                                     "годовой эффект от снижения запасов")
    r["рк1"], r["рк2"], r["высвоб"], r["эфф_зап"] = рк1, рк2, высвоб, эфф_зап
    # Ред. 4: отложенный эффект запасов последующих лет ЭЭзапг = (ЗАП₁ − ЗАП₂) × КС —
    # отдельный показатель отчёта (МР-13-2025 разд. 6); в реальный ЭЭ уже входит
    # как доход по ключевой ставке (F167), второй раз не прибавляется.
    r["ээ_запг"] = эфф_зап

    # --- Реальный ЭЭ (ядро G9 = F9 − E9) ---
    оп1 = мп1 - з1
    оп2 = мп2 - з2 + эфф_брак + ар_реал + проч_реал
    ээ = оп2 - оп1 + эфф_зап
    R(f"ОП₁ = МП₁ − Зпост₁ = {rub(мп1)} − {rub(з1)} = {rub(оп1)} руб (ядро E9)")
    R(f"ОП₂ = МП₂ − Зпост₂ + ПРД = {rub(мп2)} − {rub(з2)} + "
      f"{rub(эфф_брак + ар_реал + проч_реал)} = {rub(оп2)} руб (ядро F9)")
    R(f"РЕАЛЬНЫЙ ЭЭ = (ОП₂ − ОП₁) + ΔРК × КС = ({rub(оп2)} − {rub(оп1)}) + {rub(эфф_зап)} "
      f"= {rub(ээ)} руб/год (ядро G9; МР-13-2025 п. 5.4)")
    r["ээ"] = ээ
    r["оп1"], r["оп2"] = оп1, оп2

    # --- Потенциальный ЭЭ (ядро G70/G13/G10; маржа «после» с учётом цены ред. 4) ---
    потенц = 0.0
    if т2 is not None and тц2 < тт2:
        v_пот = т2 / тц2
        потенц = max(0.0, (v_пот - v2) * (цена2 - с2))
        R(f"Потенциальный объём: V_пот = Т₂ / Тцикл₂ = {num(т2)} / {num(тц2)} = "
          f"{num(v_пот)} ед/год (ядро F76) — объём ограничен спросом (Тцикл₂ < Ттакта₂)")
        R(f"Потенциальный эффект мощности = max(0, (V_пот − V₂)) × (Ц₂ − С₂) = "
          f"{num(v_пот - v2)} × {rub(цена2 - с2)} = {rub(потенц)} руб (ядро G70)")
    else:
        R("Потенциальный эффект мощности = 0: Тцикл₂ ≥ Ттакта₂ — резерва мощности "
          "сверх спроса нет (ядро G70 = 0)")
    ээ_пот = max(0.0, потенц) + ар_пот + проч_пот
    r["ээ_пот"] = ээ_пот
    r["потенц_мощн"] = потенц

    # --- Налоги за 3 года (чек-лист G194: зашито 25 %; у нас — параметр входа) ---
    налоги = (ээ * нприб + дмп * ндс) * 3
    R(f"Налоги за 3 года = (ЭЭ × Нприб + ΔМП × НДС) × 3 = ({rub(ээ)} × {pct(нприб)} + "
      f"{rub(дмп)} × {pct(ндс)}) × 3 = {rub(налоги)} руб (чек-лист G194)")
    r["налоги"] = налоги

    # --- Расширенная факторная декомпозиция со сверкой (J-колонки v5.23; F191) ---
    факторы = [("Объёмы реализации (выработка)", ф_объёмы),
               ("Цена ГП (изменение цены/сортности)", ф_цена),
               ("Нормы: сырьё и материалы", ф_нормы_сим),
               ("Нормы: сдельный ФОТ с соцотчислениями", ф_нормы_фот),
               ("Нормы: ТЭР", ф_нормы_тэр),
               ("Постоянные: ремонт", ф_ремонт),
               ("Постоянные: ФОТ окладный", ф_фот),
               ("Постоянные: коммуналка", ф_комм),
               ("Запасы (доход по ключевой ставке ЦБ)", эфф_зап),
               ("Брак неисправимый", эфф_брак),
               ("Прочее (аренда реальная, прочие эффекты)", ар_реал + проч_реал)]
    r["факторы"] = [(имя, зн) for имя, зн in факторы if abs(зн) > 1e-9]
    сумма = sum(зн for _, зн in r["факторы"])
    расх = сумма - ээ
    r["сверка"] = {"сумма": сумма, "расх": расх}
    R(f"Контрольная сверка: Σ факторов = {rub(сумма)} руб; расхождение с ЭЭ = "
      f"{rub(расх)} руб (допуск 0,01; ядро F191)")
    if abs(расх) > 0.01:
        r["предупр"].append("ОШИБКА: факторная декомпозиция не сходится с реальным ЭЭ "
                            f"(расхождение {rub(расх)} руб) — проверьте входные данные")

    if not есть_запасы:
        r["домерить"].append("запасы СиМ/ГП/НЗП в рублях до и после → высвобождение ДС "
                             "и эффект через ключевую ставку")
    return r


