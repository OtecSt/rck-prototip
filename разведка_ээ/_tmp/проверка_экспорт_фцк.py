#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Проверка экспорта ФЦК «до копейки» на эталоне Оренбургхладокомбината.

Способ (LibreOffice на машине не установлен — проверено `which soffice`,
/Applications): поэтому пересчёт формул Excel'ем недоступен, и проверка
честно состоит из трёх независимых контуров:

1. БИТ-В-БИТ: все входные ячейки сгенерированного файла сравниваются
   с кэшированными значениями эталонного файла (openpyxl, два режима).
   В эталоне часть входов — формулы с зашитыми константами (G77, G84/G85,
   G87/G88); сравниваем ВЫЧИСЛЕННЫЕ значения (кэш), допуск 1e-9 отн.
2. ЦЕЛОСТНОСТЬ ФОРМУЛ: множество формул всех листов сгенерированного
   файла должно совпасть с эталонным (мы писали только входные ячейки).
3. НЕЗАВИСИМЫЙ ПЕРЕСЧЁТ: из ячеек СГЕНЕРИРОВАННОГО файла по семантике
   формул модели (ВСКРЫТИЕ §3) вычисляются G9 (реальный ЭЭ), G10
   (потенциальный), налоги за 3 года — и сверяются с эталонными
   4 047 872,00 / 1 598 390,48 / 5 100 318,72 до копейки (округление 2 знака).
"""
import io
import json
import sys
from pathlib import Path

import openpyxl

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(КОРЕНЬ))
import ээ_экспорт_фцк as экс

ЭТАЛОН = КОРЕНЬ / "разведка_ээ" / "1.4 Справка плановый_ЭЭ_Оренбургхладокомбинат.xlsm"
ВХОД = КОРЕНЬ / "разведка_ээ" / "_tmp" / "вход_эталон_оренбургхладокомбинат.json"

ЦЕЛЬ = {"G9": 4047872.00, "G10": 1598390.48, "налоги": 5100318.72}

# Входные ячейки чек-листа, которые эталон заполняет (ВСКРЫТИЕ §4)
ВХОДНЫЕ = (["E5", "E6", "E7", "E8", "E9", "E10", "E11", "G16", "H16",
            "G17", "G67", "G69", "G70", "E73"]
           + [f"{к}{р}" for к in "GH" for р in (74, 75, 77, 84, 85, 87, 88)]
           + ["G89", "G93", "G106", "G145", "G148", "G161", "G164", "G169",
              "G173", "G177", "G182", "G189", "G187", "H187", "G193"])


def близко(a, b, допуск=1e-9):
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return abs(a - b) <= допуск * max(1, abs(a), abs(b))
    return str(a).strip() == str(b).strip()


def формулы(wb):
    out = {}
    for ws in wb.worksheets:
        for row in ws.iter_rows():
            for c in row:
                if isinstance(c.value, str) and c.value.startswith("="):
                    out[(ws.title, c.coordinate)] = c.value
    return out


def main():
    d = json.loads(ВХОД.read_text(encoding="utf-8"))
    байты, предупр = экс.экспортировать_в_bytes(d)
    print(f"сгенерировано {len(байты)} байт; предупреждения: {предупр or 'нет'}")

    эт_f = openpyxl.load_workbook(ЭТАЛОН)                    # формулы
    эт_v = openpyxl.load_workbook(ЭТАЛОН, data_only=True)    # кэш значений
    ген_f = openpyxl.load_workbook(io.BytesIO(байты), keep_vba=True)
    ген_v = openpyxl.load_workbook(io.BytesIO(байты), data_only=True)

    # --- 1. Бит-в-бит входные ячейки ---
    плохие = []
    for яч in ВХОДНЫЕ:
        этал = эт_v["Чек-лист"][яч].value
        if этал is None:
            этал = эт_f["Чек-лист"][яч].value
        ген = ген_v["Чек-лист"][яч].value
        if этал is None and ген is None:
            continue
        # даты эталона — datetime; наши — date
        s1, s2 = str(этал)[:10], str(ген)[:10]
        if яч in ("G16", "H16"):
            ок = s1 == s2
        else:
            ок = близко(этал, ген)
        if not ок:
            плохие.append((яч, этал, ген))
    if плохие:
        print("✗ РАСХОЖДЕНИЯ ВХОДНЫХ ЯЧЕЕК:")
        for яч, a, b in плохие:
            print(f"  {яч}: эталон={a!r} vs наш={b!r}")
        return 1
    print(f"1. Бит-в-бит: {len(ВХОДНЫЕ)} входных ячеек совпали с эталоном ✓")

    # --- 2. Целостность формул ---
    # Допустимые расхождения — только объявленные входные ячейки чек-листа,
    # где экспортёр ОСОЗНАННО пишет значения поверх формул-с-константами
    # эталона (плановый режим ввода владельца, см. шапку ээ_экспорт_фцк.py).
    ЗАМЕНЁННЫЕ_ВХОДЫ = {("Чек-лист", яч) for яч in
                       ("G77", "H77", "G84", "G85", "H84", "H85", "G87", "G88", "H88")}
    ф1, ф2 = формулы(эт_f), формулы(ген_f)
    разн = [(k, ф1.get(k), ф2.get(k)) for k in set(ф1) | set(ф2)
            if ф1.get(k) != ф2.get(k)]
    неожиданные = [r for r in разн if r[0] not in ЗАМЕНЁННЫЕ_ВХОДЫ]
    if неожиданные:
        print(f"✗ ФОРМУЛЫ ПОВРЕЖДЕНЫ ({len(неожиданные)}):")
        for k, a, b in неожиданные[:20]:
            print(f"  {k}: {a!r} vs {b!r}")
        return 1
    print(f"2. Формулы идентичны эталону ({len(ф2)} шт.); осознанно заменены "
          f"значениями {len(разн)} входных ячеек планового режима ✓")

    # --- 3. Независимый пересчёт из ячеек сгенерированного файла ---
    ч = ген_v["Чек-лист"]
    G = lambda яч: ч[яч].value or 0
    т1, т2 = G("G77"), G("H77")
    тц1, тц2, тт1, тт2 = G("G74"), G("H74"), G("G75"), G("H75")
    D81, E81 = т1, т2                                # IF(G77="",смены…,G77)
    D82 = D81 / тц1 if тт1 < тц1 else D81 / тт1      # объём реализации «до»
    E82 = E81 / тц2 if тт2 < тц2 else E81 / тт2      # … «после»
    D83, E83 = D81 / тц1, E81 / тц2                  # объём производства
    E72 = G("G84") if D82 == 0 else D82              # ЭЭ!E72
    E73 = G("G85") if D83 == 0 else D83              # ЭЭ!E73
    F73 = G("G85") if E83 == 0 else E83              # ЭЭ!F73
    F75 = G("G84") if E82 == 0 else E82              # ЭЭ!F75
    if E72 < E73:
        F72 = E72 if F75 < E73 else E72 + (F75 - E73)
        F76 = (F73 - E73) if F75 < E73 else (F73 - F75)
    else:
        F72, F76 = F75, F73 - F75
    цена, сс = G("G87"), G("G88")
    F77 = G("H87") if ч["G70"].value == "да" else цена
    F79 = сс + 0 + 0 + 0                             # нормы не заданы → дельты 0
    E69 = E72 * цена - сс * E72                      # МП концевого «до»
    F69 = F72 * F77 - F79 * F72                      # МП «после»
    G12 = F69 - E69                                  # ΔМП
    G9 = G12 + 0 + 0 + 0                             # Зпост=0, ПДР=0, ΔРК=0
    G70 = F76 * (F77 - F79)                          # потенциальный мощности
    G10 = max(0, G70) + 0 + 0
    налоги = (G9 * 0.2 + G12 * G("G193")) * 3
    итог = {"G9": G9, "G10": G10, "налоги": налоги}
    ок = True
    for k, цель in ЦЕЛЬ.items():
        факт = итог[k]
        сходится = round(факт, 2) == round(цель, 2)
        ок &= сходится
        print(f"   {k}: пересчёт {факт:,.2f} vs эталон {цель:,.2f} "
              f"{'✓' if сходится else '✗ РАСХОЖДЕНИЕ'}")
    if not ок:
        return 1
    print("3. Независимый пересчёт G9/G10/налоги — сошёлся до копейки ✓")
    print("\nВСЕ ТРИ КОНТУРА ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
