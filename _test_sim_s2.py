# -*- coding: utf-8 -*-
"""Регрессия Разработчик_С2: UI симулятора «что если» (ломтик С2).

Проверки (по миссии С2):
  1. Контракт UI ↔ API: вход, который собирает фронт (collectData/applyScenario
     из index.html), принимается POST /api/simulate (200, ok) — все поля,
     что шлёт фронт, совпадают с валидацией С1;
  2. Контракт ответа: в результате есть все поля, которые рисует UI
     (база_прогон: такт/тц/впп/нзп/выпуск/узкое_место/загрузка; свод
     выпуск_шт/впп_мин медиана±разброс; допущения);
  3. Пресет-маппинг на уровне данных: SMED = переналадка −40 % на операции
     с макс. загрузкой; Пока-йоке = брак ×0,3 (слайдер −70 %); 5S = Ту −10 %
     всем; константы совпадают с объявленными в index.html (window.__acSim);
  4. Сценарная здравость через API: 5S не ухудшает выпуск; SMED на УМ не
     ухудшает выпуск; «+1 исполнитель» на УМ не ухудшает выпуск;
  5. DOM-контракт index.html: карточка data-tool="sim" (одна), пункт меню,
     регистрация в ИНСТРУМЕНТЫ, честная упаковка (плашка, допущения,
     «Модельный прогноз, не хронометраж»), баннер «Узкое место переехало»,
     пресеты, кран, сохранение, «взять из прогона», id всех элементов,
     которые дёргает JS;
  6. Контрольные эталоны неизменны: такт 2,00 / ВПП 7000,00 (симуляция,
     нулевая вариативность, тот же вход, что у _test_sim_s1).

Запуск: python3 _test_sim_s2.py (сервер НЕ нужен — Flask test_client).
"""
import copy
import json
import re
import sys
from pathlib import Path

PROT = Path(__file__).resolve().parent
UI = PROT / "ui"
sys.path.insert(0, str(UI))

import app as flask_app  # noqa: E402
import simulyator  # noqa: E402

результаты = []


def итог(проверка, статус, детали=""):
    результаты.append((проверка, статус, детали))
    print(f"[{статус}] {проверка} {детали}")


# Эталонный вход — как у _test_sim_s1 (контрольный potok_calc).
ЭТАЛОН = {"поток": "Тестовый поток", "спрос_шт_в_период": 240,
          "доступное_время_мин": 480, "численность_чел": 5,
          "операции": [
              {"имя": "Оп1", "тц_мин": 1.25, "запас_после_шт": 2000},
              {"имя": "Оп2", "тц_мин": 1.5, "запас_после_шт": 700},
              {"имя": "Оп3", "тц_мин": 1.44, "запас_после_шт": 800}]}

HTML = (UI / "templates" / "index.html").read_text(encoding="utf-8")
client = flask_app.app.test_client()


def simulate(d):
    r = client.post("/api/simulate", data=json.dumps(d),
                    content_type="application/json")
    return r.status_code, json.loads(r.data)


# --- JS-порт функций фронта (зеркало collectData/applyScenario из index.html).
# Контракт: имена полей, которые шлёт фронт.
def фронт_вход(сценарий=None, кран_вер=0.0):
    """Сборка входа ровно в том виде, как это делает UI С2."""
    d = copy.deepcopy(ЭТАЛОН)
    # фронт добавляет необязательные поля операций только когда заполнены
    d["операции"][1]["исполнители"] = 1
    d["операции"][1]["брак_пкт"] = 2.0
    d["операции"][1]["переналадка_мин"] = 15.0
    d["операции"][1]["партия_шт"] = 50
    d["симуляция"] = {"seed": 1, "прогонов": 10}
    if кран_вер > 0:
        d["симуляция"]["кран"] = {"вероятность": кран_вер, "длительность_мин": 5}
    if сценарий:
        # applyScenario: ту/пер/брак в %, исп — добавка к исполнителям
        for i, s in сценарий.items():
            op = d["операции"][i]
            if s.get("ту"):
                op["тц_мин"] = max(0.01, op["тц_мин"] * (1 + s["ту"] / 100))
            if s.get("пер"):
                op["переналадка_мин"] = max(
                    0, op.get("переналадка_мин", 0) * (1 + s["пер"] / 100))
            if s.get("брак"):
                op["брак_пкт"] = min(99, max(
                    0, op.get("брак_пкт", 0) * (1 + s["брак"] / 100)))
            if s.get("исп"):
                op["исполнители"] = op.get("исполнители", 1) + s["исп"]
    return d


# === 1. Контракт UI ↔ API: фронт-вход принимается ============================
код, res = simulate(фронт_вход())
итог("контракт: вход UI принят /api/simulate", "PASS" if код == 200 and res.get("ok")
     else "FAIL", f"HTTP {код}, ok={res.get('ok')}")

# с краном (галочка снята, ползунок > 0)
код2, res2 = simulate(фронт_вход(кран_вер=0.2))
итог("контракт: блок «кран» принят", "PASS" if код2 == 200 and res2.get("ok")
     else "FAIL", f"HTTP {код2}, ok={res2.get('ok')}")

# === 2. Контракт ответа: поля, которые рисует UI =============================
б = res["результат"]["база_прогон"]
нужные_база = ["такт_мин", "тц_мин", "впп_мин", "нзп_среднее_шт",
               "нзп_макс_шт", "выпуск_шт", "узкое_место", "загрузка"]
нет = [k for k in нужные_база if k not in б]
свод_ок = (res["результат"].get("выпуск_шт", {}).get("медиана") is not None
           and res["результат"].get("допущения"))
итог("контракт: поля ответа для UI", "PASS" if not нет and свод_ок else "FAIL",
     f"нет: {нет or '—'}, свод/допущения: {'ок' if свод_ок else 'нет'}")

# === 3. Пресет-маппинг на уровне данных ======================================
# Константы из index.html (window.__acSim.ПРЕСЕТЫ) против спеки.
m_smed = re.search(r'smed:\s*\{\s*поле:\s*"пер",\s*значение:\s*(-?\d+)', HTML)
m_poka = re.search(r'poka:\s*\{\s*множитель_брака:\s*([\d.]+),\s*значение:\s*(-?\d+)', HTML)
m_5s = re.search(r's5:\s*\{\s*поле:\s*"ту",\s*значение:\s*(-?\d+)', HTML)
пресеты_ок = (m_smed and int(m_smed.group(1)) == -40
              and m_poka and float(m_poka.group(1)) == 0.3
              and int(m_poka.group(2)) == -70
              and m_5s and int(m_5s.group(1)) == -10)
итог("пресеты: SMED=−40 % переналадки, Пока-йоке=брак×0,3 (−70 %), 5S=Ту−10 %",
     "PASS" if пресеты_ок else "FAIL",
     f"smed={m_smed.group(1) if m_smed else '?'}, "
     f"poka={m_poka.groups() if m_poka else '?'}, "
     f"5s={m_5s.group(1) if m_5s else '?'}")

# Поведение пресетов на данных: SMED бьёт по операции с макс. загрузкой.
заг = б["загрузка"]
ум_i = max(range(len(заг)), key=lambda i: заг[i]["загрузка_пкт"])
итог("пресеты: УМ базы = операция с макс. загрузкой",
     "PASS" if заг[ум_i]["имя"] == б["узкое_место"] else "FAIL",
     f"УМ «{б['узкое_место']}», макс. загрузка у «{заг[ум_i]['имя']}» "
     f"({заг[ум_i]['загрузка_пкт']} %)")

# === 4. Сценарная здравость ==================================================
база_выпуск = б["выпуск_шт"]
# 5S: Ту −10 % всем
_, r5s = simulate(фронт_вход({i: {"ту": -10} for i in range(3)}))
в5 = r5s["результат"]["база_прогон"]["выпуск_шт"]
итог("сценарий 5S: выпуск не хуже базы", "PASS" if в5 >= база_выпуск else "FAIL",
     f"{база_выпуск} → {в5} шт")
# SMED: переналадка −40 % на УМ (у нас УМ — Оп2, у неё есть переналадка)
_, rsmed = simulate(фронт_вход({ум_i: {"пер": -40}}))
вs = rsmed["результат"]["база_прогон"]["выпуск_шт"]
итог("сценарий SMED на УМ: выпуск не хуже базы",
     "PASS" if вs >= база_выпуск else "FAIL", f"{база_выпуск} → {вs} шт")
# +1 исполнитель на УМ
_, risp = simulate(фронт_вход({ум_i: {"исп": 1}}))
ви = risp["результат"]["база_прогон"]["выпуск_шт"]
итог("сценарий +1 исполнитель на УМ: выпуск не хуже базы",
     "PASS" if ви >= база_выпуск else "FAIL", f"{база_выпуск} → {ви} шт")
# УМ «переехал» детектируется на данных: снятие 20 % Ту с УМ меняет УМ или выпуск
_, rmove = simulate(фронт_вход({ум_i: {"ту": -20}}))
бm = rmove["результат"]["база_прогон"]
итог("сценарий: данные для баннера «УМ переехал» доступны",
     "PASS" if бm.get("узкое_место") else "FAIL",
     f"УМ «{б['узкое_место']}» → «{бm['узкое_место']}»")

# === 4б. Здравость С2.1: темп по источнику ====================================
# Поток с УМ выше такта (Оп2 2,4 > такт 2,0) и не-УМ тоже выше такта
# (Оп3 2,2); запасы обнулены, чтобы начальный НЗП не маскировал выпуск.
def поток_с21(мод=None):
    d = {"поток": "Тест С2.1", "спрос_шт_в_период": 240,
         "доступное_время_мин": 480,
         "операции": [{"имя": "Оп1", "тц_мин": 1.25, "запас_после_шт": 0},
                      {"имя": "Оп2", "тц_мин": 2.4, "запас_после_шт": 0},
                      {"имя": "Оп3", "тц_мин": 2.2, "запас_после_шт": 0}],
         "симуляция": {"seed": 1, "прогонов": 10}}
    if мод:
        мод(d)
    return d


о21_база = simulyator.оценка(поток_с21())
# (а) Ту −20 % на НЕ узком месте (Оп3): ВПП ниже, выпуск не вырос.
# Эталоны новой модели: ВПП-медиана 14,05 → 13,00 мин; выпуск 193 → 193 шт.
# Причина: темп по источнику — отгрузка из буфера Оп2 ускорилась, а запуск
# по-прежнему задаёт база (УМ Оп2).
о21_неум = simulyator.оценка(поток_с21(lambda d: d["операции"][2].update(
    тц_мин=round(2.2 * 0.8, 4))))
ок_а = (о21_неум["впп_мин"]["медиана"] < о21_база["впп_мин"]["медиана"]
        and о21_неум["выпуск_шт"]["медиана"] <= о21_база["выпуск_шт"]["медиана"])
итог("С2.1 здравость: −20 % Ту на не-УМ → ВПП ниже, выпуск не вырос",
     "PASS" if ок_а else "FAIL",
     f"ВПП {о21_база['впп_мин']['медиана']}→{о21_неум['впп_мин']['медиана']} мин, "
     f"выпуск {о21_база['выпуск_шт']['медиана']}→"
     f"{о21_неум['выпуск_шт']['медиана']} шт")
# (б) Ту −20 % на УМ (Оп2): выпуск вырос (база 193 → 211 шт).
# Причина: темп по источнику + запуск по базе — ускорение УМ снижает базу.
о21_ум = simulyator.оценка(поток_с21(lambda d: d["операции"][1].update(
    тц_мин=round(2.4 * 0.8, 4))))
ок_б = о21_ум["выпуск_шт"]["медиана"] > о21_база["выпуск_шт"]["медиана"]
итог("С2.1 здравость: −20 % Ту на УМ → выпуск вырос",
     "PASS" if ок_б else "FAIL",
     f"выпуск {о21_база['выпуск_шт']['медиана']}→"
     f"{о21_ум['выпуск_шт']['медиана']} шт, УМ «{о21_база['база_прогон']['узкое_место']}»")

# === 5. DOM-контракт index.html ==============================================
проверки_dom = {
    "карточка .tool[data-tool=\"sim\"] ровно одна":
        HTML.count('class="tool live" data-tool="sim"') == 1,
    "пункт меню sn-tool data-tool=sim": 'sn-tool" data-tool="sim"' in HTML,
    "регистрация ИНСТРУМЕНТЫ (hist-sim)": 'simulation: { list: "hist-sim-list"' in HTML,
    "честная плашка «Прогноз модели»": "Прогноз модели." in HTML,
    "сворачиваемые допущения": "sim-dop-all" in HTML and "sim-dop-list" in HTML
        and "Как пользоваться и допущения модели" in HTML,
    "подпись «Модельный прогноз, не хронометраж»":
        "Модельный прогноз, не хронометраж" in HTML,
    "баннер «Узкое место переехало»": "sim-um-moved" in HTML
        and "Узкое место переехало" in HTML,
    "кран: галочка + ползунок": "sim-crane-off" in HTML and "sim-crane-prob" in HTML,
    "«взять из прогона»": "sim-btn-pull" in HTML,
    "сохранение прогона (simulation)": "save-sim-btn" in HTML
        and 'saveRunTo("simulation"' in HTML,
    "дебаунс 300 мс сценария": "setTimeout(recalcScen, 300)" in HTML,
    "API endpoint": '"/api/simulate"' in HTML,
}
for имя, ок in проверки_dom.items():
    итог(f"DOM: {имя}", "PASS" if ок else "FAIL")

# id, которые дёргает JS симулятора, существуют в разметке
js_ids = ["sim-ops-body", "sim-status-line", "sim-grid", "sim-scen-ops",
          "sim-cmp-body", "sim-spread", "sim-um-moved", "sim-dop-list",
          "sim-поток", "sim-спрос", "sim-время", "sim-численность",
          "sim-btn-add", "sim-btn-pull", "sim-btn-reset",
          "sim-preset-smed", "sim-preset-poka", "sim-preset-5s",
          "save-sim-коммент", "save-sim-метка", "save-sim-автор", "save-sim-btn",
          "save-sim-status", "hist-sim-block", "hist-sim-list",
          "sim-crane-off", "sim-crane-prob", "sim-crane-prob-val",
          "sim-crane-prob-line"]
нет_ids = [i for i in js_ids if f'id="{i}"' not in HTML]
итог("DOM: все id, используемые JS, есть в разметке",
     "PASS" if not нет_ids else "FAIL", f"нет: {нет_ids or '—'}")

# === 6. Контрольные эталоны неизменны ========================================
r = simulyator.raschet({**copy.deepcopy(ЭТАЛОН),
                        "симуляция": {"seed": 1, "вариативность_мин": 1.0,
                                      "вариативность_макс": 1.0}})
такт_ок = abs(r["такт_мин"] - 2.0) <= 0.02
впп_ок = abs(r["впп_мин"] - 7000.0) <= 0.01
итог("эталон: такт 2,00 / ВПП 7000,00 (симуляция)",
     "PASS" if такт_ок and впп_ок else "FAIL",
     f"такт {r['такт_мин']}, ВПП {r['впп_мин']}")

# --- Свод ---
фейлы = [x for x in результаты if x[1] == "FAIL"]
print(f"\nИтого: {len(результаты) - len(фейлы)}/{len(результаты)} PASS")
sys.exit(1 if фейлы else 0)
