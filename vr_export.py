# -*- coding: utf-8 -*-
"""Экспорт в шаблон «Вскрытие резервов» V4.7.2 + предпроверка правил ФЦК.

Ломтик ВР-76. Без LLM.

Три функции:
  sobrat_dannye(proekt_id, db)  -> dict   — сбор значений из базы прогонов;
                                             чего нет — None + предупреждение.
  zapolnit(data)                -> bytes  — заполнение эталонного xlsx.
  proverit_pravila(data)        -> list   — наша предпроверка ДО ИИ-сервиса ФЦК.

Принцип заполнения (см. разведка_па/ФОРМАТ_ВР.md): openpyxl при сохранении
теряет фигуры слайдов ВР1–ВР5, x14-валидации (выпадающие списки) и колонтитулы,
поэтому пишем ТОЛЬКО белые ячейки листа «Ввод данных» прямой правкой
xl/worksheets/sheet1.xml внутри zip-копии эталона. Всё остальное —
байт-в-байт как в эталоне: формулы, стили, слайды, списки не трогаем.
"""
import json
import re
import zipfile
from io import BytesIO
from pathlib import Path
from xml.sax.saxutils import escape

# Эталон лежит рядом с модулем (deploy копирует каталог целиком).
ШАБЛОН = Path(__file__).resolve().parent / "assets" / "vr_shablon_v472.xlsx"

ЛИСТ_ВВОДА = "xl/worksheets/sheet1.xml"  # «Ввод данных» — первый лист книги

СРОК_РЕАЛИЗАЦИИ = "6 месяцев"  # по служебке вебинара — всегда

# Единицы ВПП в списке шаблона (Списки!F2:F5); «сек» там нет → конвертируем.
ЕД_ВПП_ШАБЛОНА = ("мин", "ч", "дн")

# Причины выбора потока (Списки!D167:D170) — для справки в предупреждениях.
ПРИЧИНЫ_ВЫБОРА = (
    "занимает максимальную долю в портфеле заказов",
    "имеет перспективы роста продаж",
    "характеризуется значительными потерями времени и ресурсов",
    "имеет максимальный охват переделов в компании",
)

# Наименования обязательных показателей — их из протокола в инд. показатели
# НЕ переносим (у них свои строки 27–29).
_ОБЯЗАТЕЛЬНЫЕ_РЕ = re.compile(
    r"(время протекания|впп|выработк|численност)", re.IGNORECASE)


# ---------------------------------------------------------------- сбор данных

def _итоги(r):
    try:
        return json.loads(r["итоги_json"])
    except Exception:
        return {}


def _вход(r):
    try:
        return json.loads(r["вход_json"])
    except Exception:
        return {}


def sobrat_dannye(proekt_id, db):
    """Собрать данные проекта из базы прогонов для шаблона ВР.

    proekt_id — id проекта; db — открытое sqlite3-соединение (row_factory=Row).
    Возвращает dict: значения (None, если в базе нет — НЕ выдумываем),
    'предупреждения' и 'источники' (прогон №/дата по каждому значению).
    """
    p = db.execute(
        "SELECT id, название, предприятие, поток FROM proekty WHERE id = ?",
        (proekt_id,)).fetchone()
    if p is None:
        raise ValueError(f"проект № {proekt_id} не найден")
    rows = db.execute(
        "SELECT id, инструмент, вход_json, итоги_json, метка, дата "
        "FROM progony WHERE id_proekta = ? ORDER BY id", (proekt_id,)).fetchall()

    data = {
        "proekt_id": proekt_id,
        "вид_поддержки": "РЦК",
        "предприятие": (p["предприятие"] or "").strip() or None,
        "регион": None,
        "отрасль": None,
        "оквэд": None,
        "название_проекта": (p["название"] or "").strip() or None,
        "срок_реализации": СРОК_РЕАЛИЗАЦИИ,
        "доля_выручки": None,          # число без знака %
        "причина_выбора": None,
        "проблемы": [],                # до 3 строк из Списки!D2:D22
        "доп_выручка_млн": None,       # D23
        "доп_прибыль_млн": None,       # D24
        "продукт_родп": None,          # D27
        "выработка_до": None, "выработка_после": None, "выработка_ед": None,
        "впп_до": None, "впп_после": None, "впп_ед": None,
        "численность_до": None, "численность_после": None,
        "инд_показатели": [],          # [{название,до,после,ед,вырос}], макс. 2
        "мероприятия": [],             # [{цель, описание}], макс. 5
        "предупреждения": [],
        "источники": {},
    }
    пред = data["предупреждения"]

    def источник(ключ, r):
        data["источники"][ключ] = {"прогон": r["id"], "дата": r["дата"],
                                   "инструмент": r["инструмент"]}

    # --- ЭЭ: доп. выручка (ээ_пот) и доп. прибыль (ээ), млн руб., округление ---
    ee_runs = [r for r in rows if r["инструмент"] == "ee"]
    if ee_runs:
        r = max(ee_runs, key=lambda g: (g["дата"] or "", g["метка"] == "после",
                                        g["id"]))
        itogi = _итоги(r)
        if itogi.get("ээ_пот") is not None:
            data["доп_выручка_млн"] = max(0, round(itogi["ээ_пот"] / 1_000_000))
            источник("доп_выручка_млн", r)
        if itogi.get("ээ") is not None:
            data["доп_прибыль_млн"] = max(0, round(itogi["ээ"] / 1_000_000))
            источник("доп_прибыль_млн", r)
        if r["метка"] != "после":
            пред.append(f"ЭЭ взят из прогона № {r['id']} без метки «после» — "
                        "проверьте актуальность расчёта.")
    else:
        пред.append("В проекте нет прогонов ЭЭ-калькулятора — экономический "
                    "эффект (доп. выручка/прибыль) заполните вручную из модели "
                    "расчёта (ячейки G14/G12 листа «Экономический эффект»).")

    # --- SMART: выработка и ВПП (текущий→до, целевой→после) ---
    smart_runs = [r for r in rows if r["инструмент"] == "smart"]
    if smart_runs:
        r = smart_runs[-1]
        for ц in _итоги(r).get("цели") or []:
            вид = ц.get("показатель_му66")
            if вид == "выработка" and data["выработка_до"] is None:
                data["выработка_до"] = ц.get("текущий")
                data["выработка_после"] = ц.get("целевой")
                data["выработка_ед"] = ц.get("ед")
                источник("выработка", r)
            elif вид == "впп" and data["впп_до"] is None:
                до, после, ед = ц.get("текущий"), ц.get("целевой"), ц.get("ед")
                if ед == "сек":  # в списке шаблона секунд нет — конвертируем
                    if isinstance(до, (int, float)):
                        до = round(до / 60, 2)
                    if isinstance(после, (int, float)):
                        после = round(после / 60, 2)
                    пред.append("ВПП из SMART переведено из секунд в минуты "
                                "(в списке шаблона есть только мин/ч/дн) — "
                                "проверьте ед. изм. в ячейке G28.")
                    ед = "мин"
                data["впп_до"], data["впп_после"], data["впп_ед"] = до, после, ед
                источник("впп", r)

    # --- Узкие места: ВПП до/после (первый и последний прогон), численность ---
    um_runs = [r for r in rows if r["инструмент"] == "uzkie_mesta"]
    if um_runs:
        if data["впп_до"] is None:
            до = _вход(um_runs[0]).get("впп_итого_сек")
            после = _вход(um_runs[-1]).get("впп_итого_сек")
            if isinstance(до, (int, float)):
                data["впп_до"] = round(до / 60, 2)
                источник("впп", um_runs[0])
            if isinstance(после, (int, float)):
                data["впп_после"] = round(после / 60, 2)
            if data["впп_до"] is not None:
                data["впп_ед"] = "мин"
                пред.append("ВПП взят из прогонов «Поиск узкого места» и "
                            "переведён из секунд в минуты — проверьте G28.")
        if data["численность_до"] is None:
            n = _вход(um_runs[0]).get("персонал_итого")
            if isinstance(n, (int, float)):
                data["численность_до"] = n
                источник("численность_до", um_runs[0])
    # --- Калькулятор потока: численность «до» как запасной источник ---
    if data["численность_до"] is None:
        pk = [r for r in rows if r["инструмент"] == "potok_calc"]
        if pk:
            n = _вход(pk[0]).get("численность_чел")
            if isinstance(n, (int, float)):
                data["численность_до"] = n
                источник("численность_до", pk[0])

    # --- Протокол: факт «после» перекрывает цель; инд. показатели ---
    pr_runs = [r for r in rows if r["инструмент"] == "protokol"]
    if pr_runs:
        r = pr_runs[-1]
        for пок in _вход(r).get("показатели") or []:
            назв = (пок.get("показатель") or "").strip()
            if not назв:
                continue
            факт = пок.get("факт")
            if _ОБЯЗАТЕЛЬНЫЕ_РЕ.search(назв):
                if re.search(r"впп|время протекания", назв, re.IGNORECASE):
                    if isinstance(факт, (int, float)):
                        v, ед = факт, (пок.get("ед_изм") or "").strip()
                        if ед == "сек":
                            v = round(v / 60, 2)
                            ед = "мин"
                        data["впп_после"] = v
                        if ед in ЕД_ВПП_ШАБЛОНА:
                            data["впп_ед"] = ед
                        источник("впп_после", r)
                elif re.search(r"выработк", назв, re.IGNORECASE):
                    if isinstance(факт, (int, float)):
                        data["выработка_после"] = факт
                        источник("выработка_после", r)
                elif re.search(r"численност", назв, re.IGNORECASE):
                    if isinstance(факт, (int, float)):
                        data["численность_после"] = факт
                        источник("численность_после", r)
            else:
                if len(data["инд_показатели"]) < 2 and isinstance(
                        факт, (int, float)) and isinstance(
                        пок.get("до"), (int, float)):
                    data["инд_показатели"].append({
                        "название": назв,
                        "до": пок["до"], "после": факт,
                        "ед": (пок.get("ед_изм") or "").strip() or None,
                        "вырос": факт > пок["до"]})
                    источник(f"инд_{len(data['инд_показатели'])}", r)

    # --- Чего в базе точно нет: честные предупреждения вместо выдумок ---
    if data["доля_выручки"] is None:
        пред.append("Доля потока в выручке в базе не хранится (в отборе — "
                    "только критерий «≥10 %» да/нет) — введите числом без "
                    "знака % в ячейку D14.")
    if not data["проблемы"]:
        пред.append("Проблемы на потоке (D18–D20) заполните вручную — выбором "
                    "из выпадающего списка шаблона; в базе прогонов отбора "
                    "с текстами из списка нет.")
    for поле, подсказка in (
            ("регион", "D6 — выбор из списка"),
            ("отрасль", "D7 — выбор из списка"),
            ("оквэд", "E8 — код, название подтянется само"),
            ("продукт_родп", "D27 — в родительном падеже"),
            ("причина_выбора", "D15 — выбор из списка: " + "; ".join(ПРИЧИНЫ_ВЫБОРА))):
        if data.get(поле) is None:
            пред.append(f"«{поле}» в базе нет — заполните в шаблоне вручную "
                        f"({подсказка}).")
    if data["выработка_до"] is None:
        пред.append("Выработка (E27/F27) не найдена в целях SMART — заполните "
                    "вручную.")
    if data["впп_до"] is None or data["впп_после"] is None:
        пред.append("ВПП — обязательный показатель шаблона: пара до/после не "
                    "собралась из прогонов полностью — заполните вручную.")
    if data["численность_после"] is None:
        пред.append("Численность потока «после» (F29) в прогонах нет — "
                    "заполните вручную.")
    if not data["инд_показатели"]:
        пред.append("Индивидуальные показатели (строки 33–34) оставлены "
                    "пустыми: по правилам они заполняются только если выделены "
                    "в карточке проекта и идут в протокол.")
    if not data["мероприятия"]:
        пред.append("Мероприятия (C43:C47 цели из списка + G43:G47 описания "
                    "≤256 символов, все 5 строк обязательны) заполните вручную "
                    "по физике результата — из плана мероприятий не тянем, "
                    "формат описаний иной.")
    return data


# ------------------------------------------------------- заполнение шаблона

def _буква_в_инд(буква):
    n = 0
    for ch in буква:
        n = n * 26 + (ord(ch) - 64)
    return n


def _разобрать_адрес(addr):
    m = re.fullmatch(r"([A-Z]+)(\d+)", addr)
    return m.group(1), int(m.group(2))


def _новая_ячейка(addr, value, style):
    """XML ячейки. Строки — inlineStr (sharedStrings не трогаем)."""
    s_attr = f' s="{style}"' if style else ""
    if value is None:
        return f'<c r="{addr}"{s_attr}/>'
    if isinstance(value, bool):
        return f'<c r="{addr}"{s_attr} t="b"><v>{1 if value else 0}</v></c>'
    if isinstance(value, (int, float)):
        v = ("%f" % value).rstrip("0").rstrip(".") if isinstance(value, float) \
            else str(value)
        return f'<c r="{addr}"{s_attr}><v>{v}</v></c>'
    return (f'<c r="{addr}"{s_attr} t="inlineStr">'
            f'<is><t xml:space="preserve">{escape(str(value))}</t></is></c>')


def _записать_ячейку(xml, addr, value):
    """Записать значение в ячейку sheet-XML, сохранив стиль существующей."""
    буква, номер = _разобрать_адрес(addr)
    m = re.search(r'<row r="%d"[^>]*>.*?</row>' % номер, xml, re.S)
    if not m:
        raise ValueError(f"строка {номер} не найдена на листе «Ввод данных»")
    row = m.group(0)
    # Атрибуты не могут заканчиваться на «/» — иначе self-closing разметка
    # «<c r="E27" s="70"/>» проглатывалась бы веткой «>.*?</c>» вместе
    # со следующими ячейками (баг, найден на H27).
    cm = re.search(r'<c r="%s"((?: [^>]*[^/>])?)(?:/>|>.*?</c>)' % addr,
                   row, re.S)
    style = None
    if cm:
        sm = re.search(r'\bs="(\d+)"', cm.group(0))
        style = sm.group(1) if sm else None
        new_row = row[:cm.start()] + _новая_ячейка(addr, value, style) \
            + row[cm.end():]
    else:
        # ячейки нет — вставляем по порядку столбцов
        новая = _новая_ячейка(addr, value, None)
        цель = _буква_в_инд(буква)
        поз = None
        for im in re.finditer(r'<c r="([A-Z]+)\d+"', row):
            if _буква_в_инд(im.group(1)) > цель:
                поз = im.start()
                break
        если = row.rfind("</row>")
        if поз is None:
            new_row = row[:если] + новая + row[если:]
        else:
            new_row = row[:поз] + новая + row[поз:]
    return xml[:m.start()] + new_row + xml[m.end():]


def zapolnit(data, шаблон=None):
    """Заполнить эталонный xlsx данными и вернуть bytes.

    Пишем ТОЛЬКО белые ячейки «Ввод данных»; None → ячейка не трогается
    (остаётся пустой). Все прочие части zip — байт-в-байт из эталона:
    формулы, слайды ВР1–ВР5, выпадающие списки сохраняются.
    """
    путь = Path(шаблон) if шаблон else ШАБЛОН
    if not путь.exists():
        raise FileNotFoundError(
            f"эталонный шаблон не найден: {путь} — скопируйте "
            "«Шаблон Вскрытие Резервов (V4.7.2).xlsx» в assets/")

    записи = {
        "D4": data.get("вид_поддержки") or "РЦК",
        "D5": data.get("предприятие"),
        "D6": data.get("регион"),
        "D7": data.get("отрасль"),
        "E8": data.get("оквэд"),
        "D9": data.get("название_проекта"),
        "D11": data.get("срок_реализации") or СРОК_РЕАЛИЗАЦИИ,
        "D14": data.get("доля_выручки"),
        "D15": data.get("причина_выбора"),
        "D23": data.get("доп_выручка_млн"),
        "D24": data.get("доп_прибыль_млн"),
        "D27": data.get("продукт_родп"),
        "E27": data.get("выработка_до"),
        "F27": data.get("выработка_после"),
        "G27": data.get("выработка_ед"),
        "E28": data.get("впп_до"),
        "F28": data.get("впп_после"),
        "G28": data.get("впп_ед"),
        "E29": data.get("численность_до"),
        "F29": data.get("численность_после"),
    }
    for i, пр in enumerate((data.get("проблемы") or [])[:3]):
        записи[f"D{18 + i}"] = пр
    for i, пок in enumerate((data.get("инд_показатели") or [])[:2]):
        r = 33 + i
        записи[f"C{r}"] = пок.get("название")
        записи[f"D{r}"] = bool(пок.get("вырос"))
        записи[f"E{r}"] = пок.get("до")
        записи[f"F{r}"] = пок.get("после")
        записи[f"G{r}"] = пок.get("ед")
    for i, м in enumerate((data.get("мероприятия") or [])[:5]):
        r = 43 + i
        записи[f"C{r}"] = м.get("цель")
        записи[f"G{r}"] = (м.get("описание") or "")[:256] or None

    src = zipfile.ZipFile(путь)
    xml = src.read(ЛИСТ_ВВОДА).decode("utf-8")
    for addr, value in записи.items():
        if value is None:
            continue
        xml = _записать_ячейку(xml, addr, value)

    # В формульных ячейках и на слайдах остаются кэшированные значения
    # эталона (#ДЕЛ/0! и т.п.) — просим Excel полностью пересчитать книгу
    # при открытии (calcPr fullCalcOnLoad), сами кэши не трогаем.
    wbx = src.read("xl/workbook.xml").decode("utf-8")
    if "<calcPr" in wbx:
        wbx = (re.sub(r'<calcPr([^>/]*?)\s*fullCalcOnLoad="[^"]*"',
                      r'<calcPr\1', wbx)
               if 'fullCalcOnLoad' in wbx else wbx)
        wbx = re.sub(r"<calcPr", '<calcPr fullCalcOnLoad="1"', wbx, count=1)
    else:
        wbx = wbx.replace("</workbook>",
                          '<calcPr fullCalcOnLoad="1"/></workbook>')

    out = BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for item in src.infolist():
            if item.filename == ЛИСТ_ВВОДА:
                blob = xml.encode("utf-8")
            elif item.filename == "xl/workbook.xml":
                blob = wbx.encode("utf-8")
            else:
                blob = src.read(item.filename)
            z.writestr(item, blob)
    src.close()
    return out.getvalue()


# ------------------------------------------------------- предпроверка правил

_СТРУКТУРА_НАЗВАНИЯ = re.compile(r"^оптимизаци", re.IGNORECASE)


def proverit_pravila(data):
    """Предпроверка по правилам вебинара ФЦК — ДО их ИИ-сервиса.

    Возвращает список dict: {правило, статус: ок|нарушение|нет_данных,
    пояснение}."""
    р = []

    def add(правило, статус, пояснение):
        р.append({"правило": правило, "статус": статус,
                  "пояснение": пояснение})

    # 1. Срок реализации — всегда «6 месяцев»
    срок = (data.get("срок_реализации") or "").strip()
    if срок == СРОК_РЕАЛИЗАЦИИ:
        add("Срок реализации", "ок", "«6 месяцев» — как требует служебка.")
    else:
        add("Срок реализации", "нарушение",
            f"указано «{срок or 'пусто'}», а по правилу вебинара срок всегда "
            "«6 месяцев» — исправьте перед загрузкой в мероприятие 2.8.")

    # 2. Доля выручки — числом без знака %
    доля = data.get("доля_выручки")
    if доля is None:
        add("Доля в выручке", "нет_данных",
            "в базе не хранится — введите в D14 числом без знака % "
            "(например 25, а не «25%»).")
    elif isinstance(доля, str):
        add("Доля в выручке", "нарушение",
            f"значение «{доля}» — строка; по правилу доля указывается числом "
            "без знака %.")
    elif isinstance(доля, (int, float)):
        add("Доля в выручке", "ок", f"{доля} — число без знака %.")
    else:
        add("Доля в выручке", "нарушение",
            "доля должна быть числом без знака %.")

    # 3. ЭЭ: выручка снизилась → 0; сокращение минуса → разница; целые млн
    for ключ, назв in (("доп_выручка_млн", "Дополнительная выручка"),
                       ("доп_прибыль_млн", "Дополнительная прибыль")):
        v = data.get(ключ)
        if v is None:
            add(назв, "нет_данных",
                "нет прогона ЭЭ — внесите из модели расчёта (G14/G12 листа "
                "«Экономический эффект»). Если выручка снизилась — ставится 0; "
                "если минус сократился (было −500, стало −400) — рост "
                "выручки = разница (100 млн руб.).")
        elif isinstance(v, (int, float)) and v < 0:
            add(назв, "нарушение",
                f"{v} млн руб. — отрицательный эффект недопустим: если "
                "выручка снизилась, ставится 0; если сократился минус — "
                "укажите разницу как рост (было −500, стало −400 → 100).")
        elif isinstance(v, float) and not v.is_integer():
            add(назв, "нарушение",
                f"{v} — дробное; по примечанию шаблона эффект округляется "
                "математически до целого млн руб.")
        else:
            add(назв, "ок", f"{v} млн руб. — целое, неотрицательное.")

    # 4. ВПП — обязательный показатель всегда
    if data.get("впп_до") is None or data.get("впп_после") is None:
        add("ВПП обязателен", "нарушение",
            "Время протекания процесса — обязательный показатель шаблона, а "
            "пара до/после не заполнена (до: {0}, после: {1}).".format(
                data.get("впп_до"), data.get("впп_после")))
    else:
        add("ВПП обязателен", "ок",
            f"{data['впп_до']} → {data['впп_после']} {data.get('впп_ед') or ''}.")

    # 5. Название проекта — строго по структуре из примечания D10
    назв = (data.get("название_проекта") or "").strip()
    if not назв:
        add("Название проекта", "нет_данных",
            "пусто; структура: «Оптимизация производства изделия», "
            "«Оптимизация процесса продаж продукта», «Оптимизация "
            "предоставления услуги …» и т.д.")
    elif _СТРУКТУРА_НАЗВАНИЯ.match(назв):
        add("Название проекта", "ок",
            "начинается с «Оптимизация…» — соответствует структуре из "
            "примечания шаблона.")
    else:
        add("Название проекта", "нарушение",
            f"«{назв}» не соответствует структуре из примечания шаблона: "
            "название должно начинаться с «Оптимизация …» (производства "
            "изделия / процесса продаж продукта / предоставления услуги …).")

    # 6. Доп. показатели — только из протокола, иначе пусто
    доп = data.get("инд_показатели") or []
    if доп:
        вне = [п["название"] for п in доп
               if not data["источники"].get(
                   f"инд_{(доп.index(п)) + 1}", {}).get("инструмент") == "protokol"]
        if вне:
            add("Дополнительные показатели", "нарушение",
                "показатели не из протокола: " + ", ".join(вне) +
                " — по правилу доп. показатели заполняются только если "
                "выделены в карточке проекта и идут в протокол.")
        else:
            add("Дополнительные показатели", "ок",
                "заполнены только показатели из протокола закрытия: " +
                ", ".join(п["название"] for п in доп) + ".")
    else:
        add("Дополнительные показатели", "ок",
            "пусты — корректно: в протоколе проекта индивидуальные "
            "показатели не выделены.")

    # 7. Ед. изм. ВПП из списка шаблона
    ед = data.get("впп_ед")
    if data.get("впп_до") is not None and ед not in ЕД_ВПП_ШАБЛОНА:
        add("Ед. изм. ВПП", "нарушение" if ед else "нет_данных",
            f"«{ед or 'пусто'}» — в списке шаблона (G28) только: "
            + ", ".join(ЕД_ВПП_ШАБЛОНА) + ".")
    elif ед:
        add("Ед. изм. ВПП", "ок", f"«{ед}» — из списка шаблона.")

    return р
