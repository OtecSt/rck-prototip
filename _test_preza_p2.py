# -*- coding: utf-8 -*-
"""Регрессия П2 (Спека П1 «Фаст-презентация»): серверный сборщик данных
sobrat_preza + POST /api/preza/build.

Проверки (по миссии П2):
  1. Эталонная сборка на тестовом проекте с прогонами всех инструментов
     (potok_calc, uzkie_mesta, simulation до/после, ee, oee, meropriyatiya,
     smart, protokol): сборка возвращает 8 слайдов по скелету спеки, числа
     в слайдах совпадают с итогами прогонов символ в символ (JSON-сверка
     значений с сохранёнными итоги_json; эталоны: такт 2,00 / ВПП 7000,00 —
     симуляция, УМ «фасовка» 38,7 % ВПП, ЭЭ НОВОХРОМ 23 757 960,67,
     OEE 0,704167);
  2. Гейты: проект не выбран / не существует → 400; проект без прогонов →
     честная ошибка «сначала сохраните хотя бы один прогон»;
  3. Проект с одним прогоном potok_calc → слайды «титул» и «поток» есть,
     остальные перечислены в логе сборки как пропущенные;
  4. Метки «до»/«после» у simulation → слайд симуляции содержит дельту
     (через существующий механизм sravnit, не пересчёт);
  5. Дисклеймер «модельный прогноз, не замер» присутствует в слайде
     симуляции;
  6. Чек-лист слайдов: запрос подмножества возвращает только выбранное.

Запуск: python3 _test_preza_p2.py (сервер НЕ нужен — Flask test_client,
временная БД в tempdir, рабочая agent_ceh.db не трогается).
"""
import copy
import json
import sys
import tempfile
from pathlib import Path

PROT = Path(__file__).resolve().parent
UI = PROT / "ui"
sys.path.insert(0, str(UI))
sys.path.insert(0, str(PROT))

import app as flask_app  # noqa: E402

результаты = []


def итог(проверка, статус, детали=""):
    результаты.append((проверка, статус, детали))
    print(f"[{статус}] {проверка} {детали}")


# --- Изоляция: временная БД (db() отказывается создавать файл — делаем touch)
_tmp = Path(tempfile.mkdtemp(prefix="preza_p2_")) / "test_agent_ceh.db"
_tmp.touch()
flask_app.DB_PATH = _tmp
flask_app.init_db()
client = flask_app.app.test_client()

# Эталонный вход потока — тот же, что у контрольного potok_calc (_test_sim_s1).
ЭТАЛОН = {"поток": "Тестовый поток", "спрос_шт_в_период": 240,
          "доступное_время_мин": 480, "численность_чел": 5,
          "операции": [
              {"имя": "Оп1", "тц_мин": 1.25, "запас_после_шт": 2000},
              {"имя": "Оп2", "тц_мин": 1.5, "запас_после_шт": 700},
              {"имя": "Оп3", "тц_мин": 1.44, "запас_после_шт": 800}]}

# Поток с УМ выше такта и нулевыми запасами (как _test_sim_s2, С2.1):
# снятие 20 % Ту с УМ увеличивает выпуск — дельта «до/после» содержательна.
СИМ_ДО = {"поток": "Тестовый поток", "спрос_шт_в_период": 240,
          "доступное_время_мин": 480,
          "операции": [{"имя": "Оп1", "тц_мин": 1.25, "запас_после_шт": 0},
                       {"имя": "Оп2", "тц_мин": 2.4, "запас_после_шт": 0},
                       {"имя": "Оп3", "тц_мин": 2.2, "запас_после_шт": 0}],
          "симуляция": {"seed": 1, "прогонов": 10}}
СИМ_ПОСЛЕ = copy.deepcopy(СИМ_ДО)
СИМ_ПОСЛЕ["операции"][1]["тц_мин"] = round(2.4 * 0.8, 4)

ЭТАЛОН_OEE = {"поток": "Тестовый поток", "плановое_время_мин": 480,
              "простои": {"аварии_мин": 47, "переналадка_мин": 38,
                          "микроостановки_мин": 22},
              "идеальное_тц_мин": 1.0, "выпуск_всего_шт": 350, "брак_шт": 12}

ЭТАЛОН_МЕР = {"predpriyatie": "Тест-завод", "uchastok": "фасовка",
              "vpp_pct": 38.7, "norma_vpp_pct": 15.0,
              "razryv": {"value": 23.7, "unit": "п.п. ВПП", "evidence": "fact"},
              "priznaki": {"простои_оборудования": True,
                           "организация_рабочих_мест": True},
              "vidy_potery": [{"nazvanie": "Ожидание"}],
              "zamery": {}}

ЭТАЛОН_SMART = {"рамка": "федеральная", "предприятие": "Тест-завод",
                "поток": "Тестовый поток",
                "цели": [{"наименование": "Выработка", "ед": "шт/чел",
                          "текущий": 10, "целевой": 12, "срок": "2026-12-31"}]}


def новый_проект():
    r = client.post("/api/proekty", json={"название": "Тест презы П2",
                                          "предприятие": "Тест-завод",
                                          "поток": "Тестовый поток"})
    return json.loads(r.data)["id"]


def сохранить(pid, инструмент, вход, метка=None):
    body = {"id_proekta": pid, "инструмент": инструмент, "вход": вход}
    if метка:
        body["метка"] = метка
    r = client.post("/api/progony", data=json.dumps(body, ensure_ascii=False),
                    content_type="application/json")
    j = json.loads(r.data)
    assert j.get("ok"), f"прогон {инструмент} не сохранился: {j}"
    return j["id"]


def сборка(pid, **kw):
    r = client.post("/api/preza/build",
                    data=json.dumps({"проект_id": pid, **kw},
                                    ensure_ascii=False),
                    content_type="application/json")
    return r.status_code, json.loads(r.data)


# === 1. Эталонная сборка: полный проект, 8 слайдов ==========================
pid = новый_проект()
g_potok = сохранить(pid, "potok_calc", ЭТАЛОН)
g_um = сохранить(pid, "uzkie_mesta",
                 json.load(open(PROT / "данные_окз_слепой.json", encoding="utf-8")))
sim_база = dict(ЭТАЛОН)
sim_база["симуляция"] = {"seed": 1, "вариативность_мин": 1.0,
                         "вариативность_макс": 1.0}
g_sim_do = сохранить(pid, "simulation", СИМ_ДО, метка="до")
g_sim_posle = сохранить(pid, "simulation", СИМ_ПОСЛЕ, метка="после")
g_sim = сохранить(pid, "simulation", sim_база)  # последний без метки — пара до/после не ломается
g_ee = сохранить(pid, "ee",
                 json.load(open(PROT / "данные_ээ_новохром.json", encoding="utf-8")))
g_oee = сохранить(pid, "oee", ЭТАЛОН_OEE)
g_mer = сохранить(pid, "meropriyatiya", ЭТАЛОН_МЕР)
g_smart = сохранить(pid, "smart", ЭТАЛОН_SMART)
g_prot = сохранить(pid, "protokol",
                   json.load(open(PROT / "данные_протокол_кушкуль.json",
                                  encoding="utf-8")))

код, res = сборка(pid)
собрано = res.get("собрано") or {}
слайды = собрано.get("слайды") or []
коды = [s["код"] for s in слайды]
итог("эталон: сборка ok, 8 слайдов по скелету",
     "PASS" if код == 200 and res.get("ok") and коды == [
         "титул", "проблема", "поток", "симуляция",
         "мероприятия", "эффект", "план", "выводы"] else "FAIL",
     f"HTTP {код}, слайды: {коды}")
итог("эталон: лог сборки пуст (все слайды собраны)",
     "PASS" if собрано.get("лог_сборки") == [] else "FAIL",
     f"лог: {собрано.get('лог_сборки')}")
итог("эталон: тема по умолчанию «бумага»",
     "PASS" if собрано.get("тема") == "бумага" else "FAIL",
     f"тема: {собрано.get('тема')}")

по = {s["код"]: s for s in слайды}

# Символ-в-символ: сверка значений слайдов с сохранёнными итоги_json прогонов
прогоны = {g["id"]: g for g in
           json.loads(client.get(f"/api/proekty/{pid}").data)["progony"]}
ит_поток = прогоны[g_potok]["итоги"]
ит_ум = прогоны[g_um]["итоги"]
ит_ээ = прогоны[g_ee]["итоги"]
ит_oee = прогоны[g_oee]["итоги"]

ок_поток = по["поток"]["данные"]["поток"] == ит_поток
итог("сверка: слайд «поток» = итоги potok_calc (JSON в JSON)",
     "PASS" if ок_поток else "FAIL",
     f"такт {ит_поток['такт_мин']}, ВПП {ит_поток['впп_мин']}")
ок_oee = по["поток"]["данные"].get("oee") == ит_oee and ит_oee["OEE"] == 0.704167
итог("сверка: OEE 0,704167 в слайде «поток»", "PASS" if ок_oee else "FAIL",
     f"OEE {(по['поток']['данные'].get('oee') or {}).get('OEE')}")
ок_ум = (по["проблема"]["данные"]["главное_ум"] == ит_ум["главное_ум"]
         and "фасовк" in (ит_ум["главное_ум"] or "")
         and по["проблема"]["данные"]["доли_впп"] == ит_ум["доли_впп"])
итог("сверка: слайд «проблема» = итоги uzkie_mesta (УМ «фасовка», 38,7 % ВПП)",
     "PASS" if ок_ум else "FAIL",
     f"УМ «{ит_ум['главное_ум']}», доля {по['проблема']['данные']['доля_впп_ум_пкт']} %")
ок_ээ = по["эффект"]["данные"]["ээ"] == ит_ээ["ээ"] == 23757960.67
итог("сверка: ЭЭ 23 757 960,67 в слайде «эффект»", "PASS" if ок_ээ else "FAIL",
     f"ээ {по['эффект']['данные'].get('ээ')}")

# Источники: каждое число трассируется к прогону (стоп-гейт спеки)
ок_ист = (по["поток"]["источники"] ==
          [{"прогон_id": g_potok, "дата": прогоны[g_potok]["дата"],
            "инструмент": "potok_calc"},
           {"прогон_id": g_oee, "дата": прогоны[g_oee]["дата"],
            "инструмент": "oee"}])
итог("трассировка: источники слайда «поток» → прогоны № N от дата",
     "PASS" if ок_ист else "FAIL",
     f"источники: {по['поток']['источники']}")

# === 4. Метки «до»/«после» у simulation → дельта =============================
сим = по["симуляция"]["данные"]
дельта = сим.get("дельта")
ок_дельта = (дельта is not None and дельта.get("инструмент") == "simulation"
             and "выпуск_шт" in (дельта.get("числа") or {})
             and дельта["числа"]["выпуск_шт"]["до"]
             == прогоны[g_sim_do]["итоги"]["выпуск_шт"]
             and дельта["числа"]["выпуск_шт"]["после"]
             == прогоны[g_sim_posle]["итоги"]["выпуск_шт"])
итог("дельта: слайд «симуляция» содержит дельту пары до/после (sravnit)",
     "PASS" if ок_дельта else "FAIL",
     f"выпуск {((дельта or {}).get('числа') or {}).get('выпуск_шт')}")
итог("дельта: источники симуляции — прогоны «до» и «после»",
     "PASS" if [x["прогон_id"] for x in по["симуляция"]["источники"]]
     == [g_sim_do, g_sim_posle] else "FAIL",
     f"{[x['прогон_id'] for x in по['симуляция']['источники']]}")

# === 5. Дисклеймер «модельный прогноз, не замер» =============================
ок_дискл = "модельный прогноз, не замер" in (сим.get("дисклеймер") or "").lower()
итог("дисклеймер «модельный прогноз, не замер» в слайде симуляции",
     "PASS" if ок_дискл else "FAIL", f"дисклеймер: {сим.get('дисклеймер')}")

# Эталон симуляции (нулевая вариативность): такт 2,00 / ВПП 7000,00
ит_сим = прогоны[g_sim]["итоги"]
итог("эталон: симуляция такт 2,00 / ВПП 7000,00 в итогах прогона",
     "PASS" if ит_сим["такт_мин"] == 2.0 and ит_сим["впп_мин"] == 7000.0
     else "FAIL", f"такт {ит_сим['такт_мин']}, ВПП {ит_сим['впп_мин']}")

# Слайд «выводы»: 3–5 буллетов + финал
в = по["выводы"]["данные"]
итог("выводы: 3–5 буллетов из чисел слайдов + «Спасибо за внимание»",
     "PASS" if 3 <= len(в.get("буллеты") or []) <= 5
     and в.get("финал") == "Спасибо за внимание" else "FAIL",
     f"буллетов: {len(в.get('буллеты') or [])}")

# Титул: поля запроса перекрывают карточку проекта
_, res2 = сборка(pid, титул={"предприятие": "АО «Перекрытие»", "автор": "Иванов"})
т2 = {s["код"]: s for s in res2["собрано"]["слайды"]}["титул"]["данные"]
итог("титул: поля запроса перекрывают проект, поток — из карточки",
     "PASS" if т2["предприятие"] == "АО «Перекрытие»"
     and т2["автор"] == "Иванов" and т2["поток"] == "Тестовый поток"
     else "FAIL", f"{т2['предприятие']} / {т2['поток']} / {т2['автор']}")

# === 2. Гейты ================================================================
пустой = новый_проект()
код3, res3 = сборка(пустой)
итог("гейт: проект без прогонов → 400 «сначала сохраните хотя бы один прогон»",
     "PASS" if код3 == 400 and not res3.get("ok")
     and any("сначала сохраните хотя бы один прогон" in e
             for e in res3.get("errors") or []) else "FAIL",
     f"HTTP {код3}, {res3.get('errors')}")
код4, res4 = сборка(999999)
итог("гейт: проект не существует → 400", "PASS" if код4 == 400 and not res4.get("ok")
     else "FAIL", f"HTTP {код4}, {res4.get('errors')}")
r5 = client.post("/api/preza/build", data="{}", content_type="application/json")
итог("гейт: проект не выбран (нет проект_id) → 400",
     "PASS" if r5.status_code == 400 and not json.loads(r5.data).get("ok")
     else "FAIL", f"HTTP {r5.status_code}")

# === 3. Только potok_calc → титул и поток, остальные в логе =================
один = новый_проект()
сохранить(один, "potok_calc", ЭТАЛОН)
_, res6 = сборка(один)
с6 = res6["собрано"]
коды6 = [s["код"] for s in с6["слайды"]]
пропущенные = set()
for строка in с6["лог_сборки"]:
    for к in ("проблема", "поток", "симуляция", "мероприятия",
              "эффект", "план", "выводы"):
        if f"слайд «{к}» пропущен" in строка:
            пропущенные.add(к)
итог("частичный: есть «титул» и «поток», остальные — в логе сборки",
     "PASS" if коды6 == ["титул", "поток"] and пропущенные == {
         "проблема", "симуляция", "мероприятия", "эффект", "план", "выводы"}
     else "FAIL",
     f"слайды {коды6}, пропущены {sorted(пропущенные)}")

# === 6. Чек-лист слайдов =====================================================
_, res7 = сборка(pid, слайды=["титул", "эффект"])
коды7 = [s["код"] for s in res7["собрано"]["слайды"]]
итог("чек-лист: запрошены «титул»+«эффект» — только они и собраны",
     "PASS" if коды7 == ["титул", "эффект"] else "FAIL", f"слайды {коды7}")
r8 = client.post("/api/preza/build",
                 data=json.dumps({"проект_id": pid, "слайды": ["титул", "баг"]}),
                 content_type="application/json")
итог("чек-лист: неизвестный код слайда → 400",
     "PASS" if r8.status_code == 400 else "FAIL", f"HTTP {r8.status_code}")

# --- Свод ---
фейлы = [x for x in результаты if x[1] == "FAIL"]
print(f"\nИтого: {len(результаты) - len(фейлы)}/{len(результаты)} PASS")
sys.exit(1 if фейлы else 0)
