# -*- coding: utf-8 -*-
"""Регрессия Разработчик_С1: ДСС-симулятор потока (ломтик С1) + /api/simulate.

Проверки (по миссии С1):
  1. Валидационный гейт: нулевая вариативность (triangular min=mode=max), без
     ограничений буферов, без крана → сходимость к детерминированному
     калькулятору потока: такт 2,00 мин, ВПП 7004,19 мин (допуск 1 %);
  2. Воспроизводимость: одинаковый (вход, seed) → побитово тот же выход;
  3. Здравость (сценарий с УМ выше такта): снятие 20 % Ту с УМ увеличивает
     выпуск и снижает ВПП; переналадка −40 % на УМ увеличивает выпуск; рост
     буферной ёмкости не уменьшает выпуск;
  4. Endpoint через тестовый клиент Flask: 200, JSON, запись в agent_ceh.db
     (инструмент simulation);
  5. Производительность: время 10-прогонной оценки на эталоне (замер).

Запуск: python3 _test_sim_s1.py (сервер НЕ нужен — ядро + test_client).
"""
import copy
import json
import sys
import time
from pathlib import Path

PROT = Path(__file__).resolve().parent
UI = PROT / "ui"
sys.path.insert(0, str(UI))

import simulyator  # noqa: E402

результаты = []


def итог(проверка, статус, детали=""):
    результаты.append((проверка, статус, детали))
    print(f"[{статус}] {проверка} {детали}")


# Эталонный вход — тот же, что у контрольного potok_calc в _test_cifra74.py
ЭТАЛОН = {"поток": "Тестовый поток", "спрос_шт_в_период": 240,
          "доступное_время_мин": 480, "численность_чел": 5,
          "операции": [
              {"имя": "Оп1", "тц_мин": 1.25, "запас_после_шт": 2000},
              {"имя": "Оп2", "тц_мин": 1.5, "запас_после_шт": 700},
              {"имя": "Оп3", "тц_мин": 1.44, "запас_после_шт": 800}]}

НУЛЬ_ВАР = {"seed": 1, "вариативность_мин": 1.0, "вариативность_макс": 1.0}


def вх(сим=None, мод=None):
    d = copy.deepcopy(ЭТАЛОН)
    d["симуляция"] = сим if сим is not None else dict(НУЛЬ_ВАР)
    if мод:
        мод(d)
    return d


# --- 1. Валидационный гейт: сходимость к potok_calc (такт 2,00 / ВПП 7004,19)
r = simulyator.raschet(вх())
такт_ок = abs(r["такт_мин"] - 2.0) <= 0.02
впп_откл = abs(r["впп_мин"] - 7004.19) / 7004.19 * 100
впп_ок = впп_откл <= 1.0
итог("гейт: такт 2,00", "PASS" if такт_ок else "FAIL",
     f"такт {r['такт_мин']} мин (допуск ±0,02)")
итог("гейт: ВПП 7004,19 ±1 %", "PASS" if впп_ок else "FAIL",
     f"ВПП {r['впп_мин']} мин, отклонение {впп_откл:.3f} %")

# --- 2. Воспроизводимость: одинаковый seed → побитово тот же выход
a = simulyator.оценка(вх({"seed": 42}))
b = simulyator.оценка(вх({"seed": 42}))
c = simulyator.оценка(вх({"seed": 43}))
бит_ок = json.dumps(a, sort_keys=True) == json.dumps(b, sort_keys=True)
другой = json.dumps(a, sort_keys=True) != json.dumps(c, sort_keys=True)
итог("воспроизводимость seed", "PASS" if бит_ок else "FAIL",
     "seed 42 == seed 42 побитово" + (", seed 43 отличается" if другой
                                      else ", ВНИМАНИЕ: seed 43 совпал"))

# --- 3. Здравость: УМ выше такта (Оп2 Ту 2,4 > такт 2,0) ---
def ум_сценарий(d):
    d["операции"][1]["тц_мин"] = 2.4
    # С2.1: запасы обнулены. При большом начальном НЗП отгрузка запаса идёт
    # по темпу операции-источника (такт 2,0), выпуск упирается в спрос (240)
    # и маскирует влияние УМ — было: выпуск 240→240, ВПП 6960,2→7000,0;
    # стало: выпуск 196→237, ВПП 9,6→6,0. Причина: темп по источнику.
    for op in d["операции"]:
        op["запас_после_шт"] = 0


база = simulyator.raschet(вх(мод=ум_сценарий))
без20 = simulyator.raschet(вх(мод=lambda d: (ум_сценарий(d),
                                             d["операции"][1].update(тц_мин=1.92))))
ок = (без20["выпуск_шт"] > база["выпуск_шт"]
      and без20["впп_мин"] < база["впп_мин"])
итог("здравость: −20 % Ту на УМ", "PASS" if ок else "FAIL",
     f"выпуск {база['выпуск_шт']}→{без20['выпуск_шт']} шт, "
     f"ВПП {база['впп_мин']}→{без20['впп_мин']} мин, УМ «{база['узкое_место']}»")


def переналадка(d, пер):
    ум_сценарий(d)
    d["операции"][1]["переналадка_мин"] = пер
    d["операции"][1]["партия_шт"] = 50


s0 = simulyator.raschet(вх(мод=lambda d: переналадка(d, 60.0)))
s1 = simulyator.raschet(вх(мод=lambda d: переналадка(d, 36.0)))
итог("здравость: SMED переналадка −40 % на УМ",
     "PASS" if s1["выпуск_шт"] > s0["выпуск_шт"] else "FAIL",
     f"выпуск {s0['выпуск_шт']}→{s1['выпуск_шт']} шт")


def ёмкость(d, cap):
    ум_сценарий(d)
    переналадка(d, 60.0)
    d["симуляция"]["ёмкость_буферов"] = {"Оп1": cap}


e5 = simulyator.raschet(вх(мод=lambda d: ёмкость(d, 5)))
e50 = simulyator.raschet(вх(мод=lambda d: ёмкость(d, 50)))
итог("здравость: рост буферной ёмкости",
     "PASS" if e50["выпуск_шт"] >= e5["выпуск_шт"] else "FAIL",
     f"выпуск ёмкость 5 → {e5['выпуск_шт']} шт, ёмкость 50 → "
     f"{e50['выпуск_шт']} шт (не уменьшается)")

# --- 4. Endpoint /api/simulate через тестовый клиент Flask ---
try:
    import app as app_mod
    клиент = app_mod.app.test_client()
    resp = клиент.post("/api/proekty", json={"название": "Тест симулятора С1",
                                             "предприятие": "Тест",
                                             "поток": "Тестовый поток"})
    pid = resp.get_json()["id"]
    тело = вх({"seed": 7})
    тело["id_proekta"] = pid
    t0 = time.time()
    resp = клиент.post("/api/simulate", json=тело)
    код = resp.status_code
    js = resp.get_json()
    ок = (код == 200 and js.get("ok") and js.get("id_прогона")
          and js["итоги"]["такт_мин"] == 2.0
          and js["итоги"]["seed"] == 7 and js["итоги"]["прогонов"] == 10
          and js["итоги"]["оценка_впп_мин"]["медиана"] is not None)
    гид = js.get("id_прогона")
    снап = клиент.get(f"/api/progony/{гид}").get_json() if гид else {}
    прогон = снап.get("progon") or {}
    запись_ок = (снап.get("ok")
                 and прогон.get("инструмент") == "simulation"
                 and "Прогноз модели" in прогон.get("отчёт_md", ""))
    итог("endpoint /api/simulate (200, JSON, запись в БД)",
         "PASS" if ок and запись_ок else "FAIL",
         f"HTTP {код}, прогон № {гид}, seed в снапшоте: "
         f"{прогон.get('итоги', {}).get('seed') if запись_ок else '—'}")
except Exception as e:
    итог("endpoint /api/simulate", "FAIL", f"исключение: {e}")

# --- 5. Производительность: 10-прогонная оценка на эталоне ---
t0 = time.time()
simulyator.оценка(вх({"seed": 1}))
мс = (time.time() - t0) * 1000
итог("производительность (10 прогонов, эталон)", "PASS" if мс < 5000 else "FAIL",
     f"{мс:.0f} мс")

print()
плохие = [x for x in результаты if x[1] != "PASS"]
print(f"ИТОГО: {len(результаты) - len(плохие)}/{len(результаты)} PASS")
for x in плохие:
    print("ПРОВАЛ:", x)
sys.exit(1 if плохие else 0)
